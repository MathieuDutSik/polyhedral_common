/*
  The mass sum_L 1 / |U(L)| of the genus of a definite Hermitian lattice
  over O_K, K = Q(sqrt D) imaginary quadratic of fundamental discriminant D,
  for the lattices that are unimodular at every prime, as in Hecke.jl
  (QuadForm/Herm/Mass.jl, after the thesis of M. Kirschmer and S. Cho):

    mass = 2^{1-m} prod_{i=1}^{m} |L(1 - i, chi_D^i)| prod_{p | D} lambda_p,

  with L(1 - i, chi) = -B_{i,chi} / i, the trivial character for i even.
  The primes not dividing D contribute nothing for a unimodular lattice. At
  a ramified prime p, with d = (-1)^{m (m-1) / 2} det h and eps = +1 if d is
  a norm from Q_p(sqrt D), -1 otherwise:
  - p odd: lambda_p = 1/2 for m odd, (p^{m/2} + eps) / 2 for m even (the
    normalized orders of Sp_m(F_p) and O^{eps}_m(F_p) of the Jordan
    decomposition, which has a single component),
  - p = 2: the unimodular case of the dyadic formula of Kirschmer, which
    also needs e = v_2(D) and the valuation at the prime over 2 of the norm
    ideal of L (the ideal generated by the h(x, x)).
  The other genera (a lattice not unimodular at some prime) are not
  treated: the function returns nothing.

  Checked against Hecke.jl on O_K^m for m = 2, 3, 4 and D = -3, -4, -7,
  -8, -11.
 */

inline bool IsFundamentalDiscriminant(int64_t D) {
  auto squarefree = [](int64_t x) -> bool {
    if (x < 0) {
      x = -x;
    }
    for (int64_t d = 2; d * d <= x; d++) {
      if (x % (d * d) == 0) {
        return false;
      }
    }
    return true;
  };
  int64_t r = ((D % 4) + 4) % 4;
  if (r == 1) {
    return squarefree(D);
  }
  if (r == 0) {
    int64_t k = D / 4;
    int64_t rk = ((k % 4) + 4) % 4;
    return (rk == 2 || rk == 3) && squarefree(k);
  }
  return false;
}

/*
  The Hermitian Gram matrix of the standard lattice O_K^m of the ring: the
  first m realified coordinates are an O_K-basis, and h(e_j, e_k) = a + b
  omega is recovered from t1 = B(e_j, e_k) = 2 a + s b and t2 = B(e_j, e_k
  W) = s a + 2 n b.
 */
template <typename T, typename Tint>
std::vector<std::vector<std::pair<T, T>>>
HermitianGramStandard(RealifiedRing<T, Tint> const &ring) {
  int m = ring.m;
  int n = ring.n();
  MyMatrix<Tint> BW = ring.B * ring.W.transpose();
  T s(ring.s), nw(ring.p);
  T absD = 4 * nw - s * s;
  std::vector<std::vector<std::pair<T, T>>> h(m, std::vector<std::pair<T, T>>(m));
  for (int j = 0; j < m; j++) {
    for (int k = 0; k < m; k++) {
      T t1(ring.B(j, k));
      T t2(BW(j, k));
      h[j][k] = {(2 * nw * t1 - s * t2) / absD, (2 * t2 - s * t1) / absD};
    }
  }
  (void)n;
  return h;
}

// The determinant over K of a square matrix, by Gaussian elimination.
template <typename T>
std::pair<T, T> DeterminantOverK(ImagQuadRing<T> const &ring,
                                 std::vector<std::vector<std::pair<T, T>>> M) {
  int m = M.size();
  std::pair<T, T> det = ring.one();
  for (int col = 0; col < m; col++) {
    int piv = -1;
    for (int r = col; r < m; r++) {
      if (!ring.is_zero(M[r][col])) {
        piv = r;
        break;
      }
    }
    if (piv == -1) {
      return ring.zero();
    }
    if (piv != col) {
      std::swap(M[piv], M[col]);
      det = ring.neg(det);
    }
    det = ring.mul(det, M[col][col]);
    std::pair<T, T> inv = ring.inverse(M[col][col]);
    for (int r = col + 1; r < m; r++) {
      std::pair<T, T> c = ring.mul(M[r][col], inv);
      for (int j = col; j < m; j++) {
        M[r][j] = ring.sub(M[r][j], ring.mul(c, M[col][j]));
      }
    }
  }
  return det;
}

// Whether the nonzero rational x is a norm from Q_p(sqrt D).
template <typename T> bool IsLocalNormQuadratic(T const &x, int64_t D, int64_t p) {
  int64_t num = UniversalScalarConversion<int64_t, T>(T(x.get_num()));
  int64_t den = UniversalScalarConversion<int64_t, T>(T(x.get_den()));
  // x and x den^2 = num den have the same class
  PadicClass cx = PadicFromInt64(num * den, p);
  PadicClass cD = PadicFromInt64(D, p);
  return HilbertSymbolClass(cx, cD, p) == 1;
}

template <typename T> T HermitianPowerInt(int64_t q, int e) {
  T res(1);
  T q_T(static_cast<long>(q));
  if (e >= 0) {
    for (int i = 0; i < e; i++) {
      res *= q_T;
    }
  } else {
    for (int i = 0; i < -e; i++) {
      res /= q_T;
    }
  }
  return res;
}

/*
  The local factor at the dyadic ramified prime of a unimodular lattice:
  the case m0 = m, m1 = 0 of _local_factor_dyadic of Hecke.jl. e = v_2(D),
  norm_val = the valuation at the prime over 2 of the norm ideal.
 */
template <typename T>
T HermitianLocalFactorDyadicUnimodular(int m, int e, int norm_val, bool d_is_norm) {
  int64_t q = 2;
  T half = T(1) / T(2);
  if (m % 2 == 1) {
    return half;
  }
  int k0 = m / 2;
  int k1 = 0;
  int f2 = e / 2;
  int l = norm_val / 2;
  T fac_m = HermitianPowerInt<T>(q, m) - T(1);
  if (d_is_norm) {
    bool h0 = (norm_val == 2 * f2);
    if (h0) {
      int t = (e % 2 == 0) ? k1 : k0;
      return (HermitianPowerInt<T>(q, t) + T(1)) * half;
    }
    if (e % 2 == 0) {
      return HermitianPowerInt<T>(q, m * (f2 - 1 - l) + k1) * fac_m * half;
    }
    return HermitianPowerInt<T>(q, m * (f2 - l) - k0) * fac_m * half;
  }
  if (e % 2 == 1) {
    if (l == (e - 1) / 2) {
      return (HermitianPowerInt<T>(q, k0) - T(1)) * half;
    }
    return HermitianPowerInt<T>(q, m * (f2 - l) - k0) * fac_m * half;
  }
  return HermitianPowerInt<T>(q, m * (f2 - 1 - l) + k1) * fac_m * half;
}

/*
  The mass of the genus of the standard lattice O_K^m of the ring with its
  form, or nothing when it is not covered (not unimodular at some prime,
  or O_K not the maximal order).
 */
template <typename T, typename Tint>
std::optional<T> HermitianGenusMass(RealifiedRing<T, Tint> const &ring, [[maybe_unused]] std::ostream &os) {
  if (ring.d != 2) {
    return {};
  }
  int m = ring.m;
  int64_t D = ring.s * ring.s - 4 * ring.p;
  if (!IsFundamentalDiscriminant(D)) {
#ifdef DEBUG_HERMITIAN_MASS
    os << "HMASS: " << D << " is not a fundamental discriminant\n";
#endif
    return {};
  }
  int64_t absD = -D;
  // unimodular at every prime iff det B = |D|^m
  T detB = DeterminantMat(UniversalMatrixConversion<T, Tint>(ring.B));
  T target(1);
  for (int i = 0; i < m; i++) {
    target *= T(static_cast<long>(absD));
  }
  if (T_abs(detB) != target) {
#ifdef DEBUG_HERMITIAN_MASS
    os << "HMASS: the lattice is not unimodular, det B = " << detB << "\n";
#endif
    return {};
  }
  // the standard mass
  T mass = HermitianPowerInt<T>(2, 1 - m);
  for (int i = 1; i <= m; i++) {
    int64_t chi = (i % 2 == 1) ? D : 1;
    T Lval = -GeneralizedBernoulli<T>(i, chi) / T(i);
    mass *= T_abs(Lval);
  }
  // the discriminant class
  ImagQuadRing<T> iq = ring.quad();
  std::pair<T, T> det_h = DeterminantOverK(iq, HermitianGramStandard(ring));
  if (det_h.second != 0) {
    std::cerr << "HMASS: the determinant of h is not rational\n";
    throw TerminalException{1};
  }
  T d = det_h.first;
  if ((m * (m - 1) / 2) % 2 == 1) {
    d = -d;
  }
  // the norm ideal of L over Z: gcd of Q(e_k) = B(e_k, e_k) / 2 and B(e_k, e_l)
  Tint norm_gen(0);
  int n = ring.n();
  for (int k = 0; k < n; k++) {
    for (int l = k; l < n; l++) {
      Tint val = (k == l) ? Tint(ring.B(k, k) / 2) : ring.B(k, l);
      norm_gen = GcdPair(norm_gen, val);
    }
  }
  for (int64_t p = 2; p <= absD; p++) {
    if (absD % p != 0 || !IsPrime<int64_t>(p)) {
      continue;
    }
    bool d_is_norm = IsLocalNormQuadratic(d, D, p);
    T lambda;
    if (p != 2) {
      if (m % 2 == 1) {
        lambda = T(1) / T(2);
      } else {
        lambda = (HermitianPowerInt<T>(p, m / 2) + T(d_is_norm ? 1 : -1)) / T(2);
      }
    } else {
      int e = 0;
      int64_t work = absD;
      while (work % 2 == 0) {
        work /= 2;
        e++;
      }
      int v2 = 0;
      Tint ng = T_abs(norm_gen);
      while (ng % 2 == 0) {
        ng /= 2;
        v2++;
      }
      lambda = HermitianLocalFactorDyadicUnimodular<T>(m, e, 2 * v2, d_is_norm);
    }
#ifdef DEBUG_HERMITIAN_MASS
    os << "HMASS: p=" << p << " lambda=" << lambda << "\n";
#endif
    mass *= lambda;
  }
  return mass;
}

