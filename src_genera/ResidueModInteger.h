/*
  Residues modulo an integer M, a prime or not, for the algebraic modular
  forms (AlgebraicModularFormsZ.h, AlgebraicModularFormsHerm.h) and the
  neighbors (HermitianNeighbor.h): of an integer, of a rational whose
  denominator is prime to M, and the key of a submodule of (Z / M)^n.
 */

// The residue in [0, ell - 1] of an integer.
template <typename Tint> int64_t order_residue(Tint const &x, int64_t const &ell) {
  Tint ell_T = UniversalScalarConversion<Tint, int64_t>(ell);
  Tint r = x % ell_T;
  if (r < 0) {
    r += ell_T;
  }
  return UniversalScalarConversion<int64_t, Tint>(r);
}

// The residue modulo ell (a prime or not) of a rational whose denominator
// is prime to ell.
template <typename T> int64_t order_residue_rat(T const &x, int64_t const &ell) {
  int64_t num = order_residue(GetNumerator_z(x), ell);
  int64_t den = order_residue(GetDenominator_z(x), ell);
#ifdef SANITY_CHECK_RESIDUE_MOD_INTEGER
  if (std::gcd(den, ell) != 1) {
    std::cerr << "RESMOD: a denominator is not prime to " << ell << "\n";
    throw TerminalException{1};
  }
#endif
  return (num * InverseModPrime(den, ell)) % ell;
}

/*
  The Hermite normal form, flattened (n x n, row major), of the sublattice
  of Z^n generated by the rows and by M Z^n, in int64_t: the generators are
  reduced modulo M, so that it is the key of a sublattice containing M Z^n,
  that is of a submodule of (Z / M)^n.
 */
inline std::vector<int64_t> HnfKeyModM(std::vector<std::vector<int64_t>> rows,
                                       int n, int64_t M) {
  // the generators reduced modulo M, then M e_j (which the reduction
  // would have killed)
  for (auto &r : rows) {
    for (auto &x : r) {
      x = ResidueModPrime(x, M);
    }
  }
  for (int j = 0; j < n; j++) {
    std::vector<int64_t> r(n, 0);
    r[j] = M;
    rows.push_back(r);
  }
  std::vector<int64_t> H(n * n, 0);
  size_t start = 0;
  for (int col = 0; col < n; col++) {
    // Euclid on the column among the rows from start on
    while (true) {
      int i_min = -1;
      for (size_t i = start; i < rows.size(); i++) {
        if (rows[i][col] != 0 && (i_min == -1 || std::abs(rows[i][col]) < std::abs(rows[i_min][col]))) {
          i_min = i;
        }
      }
      if (i_min == -1) {
        break;
      }
      bool other = false;
      for (size_t i = start; i < rows.size(); i++) {
        if (static_cast<int>(i) != i_min && rows[i][col] != 0) {
          int64_t q = rows[i][col] / rows[i_min][col];
          for (int j = col; j < n; j++) {
            rows[i][j] -= q * rows[i_min][j];
          }
          if (rows[i][col] != 0) {
            other = true;
          }
        }
      }
      if (!other) {
        std::swap(rows[start], rows[i_min]);
        break;
      }
    }
    if (rows[start][col] < 0) {
      for (int j = col; j < n; j++) {
        rows[start][j] = -rows[start][j];
      }
    }
    for (int j = 0; j < n; j++) {
      H[col * n + j] = rows[start][j];
    }
    start++;
  }
  // the entries above the diagonal reduced modulo the pivot below them
  for (int col = 0; col < n; col++) {
    int64_t piv = H[col * n + col];
    for (int i = 0; i < col; i++) {
      int64_t q = H[i * n + col] / piv;
      if (H[i * n + col] - q * piv < 0) {
        q -= 1;
      }
      if (q != 0) {
        for (int j = col; j < n; j++) {
          H[i * n + j] -= q * H[col * n + j];
        }
      }
    }
  }
  return H;
}

