/*
  Algebraic modular forms of trivial weight for the orthogonal group of a
  genus of positive definite even lattices over Z, from the list of its
  classes L_1, ..., L_h (the output of GENUS_Enumerate), with a level
  structure at a prime N or none (N = 1).

  The states are the pairs (L_j, O), O an orbit of Aut(L_j) on the isotropic
  lines of L_j / N L_j (for the form x -> (x, x) / 2 mod N), and a single
  state per class for N = 1. The Hecke operator at a prime p, with p not
  dividing N det: the entry (L_i, O) -> (L_j, O') of its matrix is the
  number of pairs (x, l) with x a line of L_i / p L_i giving a p-neighbor M
  isometric to L_j, and l the fixed line of O carried to O' by M. Since
  M / N M = L_i / N L_i, a line of L_i mod N is one of M, and an isometry
  M -> L_j carries it to L_j: any isometry, as two of them differ by an
  element of Aut(L_j), which preserves the orbits. Counted over the orbit X
  of x under Aut(L_i), as in AlgebraicModularForms.h, it is |X| / |O| times
  the number of l in O sent to O' by the neighbor of the representative of
  X. For N = 1 the entry (L_i, L_j) is the number of p-neighbors of L_i
  isometric to L_j.

  Unlike the enumeration, every class is expanded at every prime, so the
  work is a set of independent rows: the data of each class (the
  automorphism group, the orbits of the level lines), then for each class
  and prime its row. The neighbors are recognized by LatticeInvariantFamily
  rather than by a canonical form. The tree only separates the classes of
  the family, so the list must be the whole genus: its mass is checked
  against the mass formula before the rows are computed.
 */

// The orbits of Aut(L) on the lines of L / N L: the orbit of every line, -1
// for a non isotropic one, and the size of every orbit. A single orbit of
// size 1, and no line, for N = 1.
struct AmfZLevelData {
  std::vector<int64_t> orbit_of_line;
  std::vector<size_t> orbit_size;
};

namespace boost::serialization {
template <class Archive>
inline void serialize(Archive &ar, AmfZLevelData &d,
                      [[maybe_unused]] const unsigned int version) {
  ar &make_nvp("orbit_of_line", d.orbit_of_line);
  ar &make_nvp("orbit_size", d.orbit_size);
}
} // namespace boost::serialization

// Whether the line of L / N L of the vector z is isotropic for (x, x) / 2.
inline bool AmfZIsotropicLine(MyMatrix<int64_t> const &G,
                              std::vector<int> const &z, int N) {
  int n = G.rows();
  int64_t norm = 0;
  for (int a = 0; a < n; a++) {
    for (int b = 0; b < n; b++) {
      norm += static_cast<int64_t>(z[a]) * G(a, b) * static_cast<int64_t>(z[b]);
    }
  }
  int64_t half = norm / 2;
  return (half % N) == 0;
}

/*
  The orbits of the group generated by ListGen on the isotropic lines of
  L / N L. The isometries preserve the isotropy, so the orbits of the
  isotropic lines stay among them. The table has one entry per line of
  P^{n-1}(F_N): beyond max_lines lines the computation stops with an error.
 */
template <typename Tint>
AmfZLevelData AmfZLevelOrbits(MyMatrix<Tint> const &G,
                              std::vector<MyMatrix<Tint>> const &ListGen, int N,
                              size_t max_lines) {
  AmfZLevelData data;
  if (N == 1) {
    data.orbit_size = {1};
    return data;
  }
  int n = G.rows();
  size_t n_line = NumberProjectiveLines(n, N);
  if (n_line > max_lines) {
    std::cerr << "AMFZ: " << n_line << " lines modulo the level " << N
              << " in rank " << n << ", above max_level_lines=" << max_lines
              << "\n";
    throw TerminalException{1};
  }
  MyMatrix<int64_t> G64 = UniversalMatrixConversion<int64_t, Tint>(G);
  T_small_prime N_u = static_cast<T_small_prime>(N);
  ProjectiveLineCoder coder(n, N_u);
  std::vector<std::vector<ProjectiveLineCoder::T_coord>> ListGenRed;
  for (auto &eGen : ListGen) {
    if (!IsScalarModP(eGen, N)) {
      ListGenRed.push_back(
          coder.coords(FlattenModMatrix(ModMatrixOfMatrix(eGen, N_u))));
    }
  }
  // -2: isotropic and not reached yet
  data.orbit_of_line.assign(n_line, -1);
  for (size_t i_line = 0; i_line < n_line; i_line++) {
    if (AmfZIsotropicLine(G64, ProjectiveLineOfIndex(n, N, i_line), N)) {
      data.orbit_of_line[i_line] = -2;
    }
  }
  std::vector<ProjectiveLineCoder::T_coord> v(n), w(n);
  std::vector<size_t> ListActive;
  for (size_t i_line = 0; i_line < n_line; i_line++) {
    if (data.orbit_of_line[i_line] != -2) {
      continue;
    }
    int64_t i_orbit = static_cast<int64_t>(data.orbit_size.size());
    data.orbit_of_line[i_line] = i_orbit;
    ListActive.push_back(i_line);
    size_t size = 0;
    while (!ListActive.empty()) {
      size_t pos = ListActive.back();
      ListActive.pop_back();
      size++;
      coder.decode(pos, v);
      for (auto const &gred : ListGenRed) {
        size_t img = coder.image(v, gred, w);
        if (data.orbit_of_line[img] == -2) {
          data.orbit_of_line[img] = i_orbit;
          ListActive.push_back(img);
        }
#ifdef SANITY_CHECK_ALGEBRAIC_MODULAR_FORMS_Z
        if (data.orbit_of_line[img] != i_orbit) {
          std::cerr << "AMFZ: an automorphism sends an isotropic line to a "
                       "non isotropic one\n";
          throw TerminalException{1};
        }
#endif
      }
    }
    data.orbit_size.push_back(size);
  }
  return data;
}

/*
  The row of the class L_i at the prime p: the entries
  (o, j, o2) -> value, o an orbit of the level lines of L_i and o2 one of
  L_j, and the number of lines of L_i / p L_i that give a neighbor. The
  classes are those of the family; level_j their level data, ListGen_i the
  generators of Aut(L_i).
 */
struct AmfZRow {
  std::map<std::tuple<size_t, size_t, size_t>, int64_t> entries;
  size_t n_neighbor = 0;
};

template <typename T, typename Tint, typename Tgroup>
AmfZRow AmfZComputeRow(size_t i, int p, InvariantFamily<Tint> const &family,
                       std::vector<MyMatrix<Tint>> const &ListGen_i,
                       std::vector<AmfZLevelData> const &level, int N,
                       GenusMethods const &methods, std::ostream &os) {
  MyMatrix<Tint> const &G_i = family.ListGram[i];
  int n = G_i.rows();
#ifdef TIMINGS_ALGEBRAIC_MODULAR_FORMS_Z
  MicrosecondTime time;
#endif
  ProjectiveLineSelection ListRepr =
      ProjectiveLineOrbitRepresentatives<Tint>(n, p, ListGen_i);
#ifdef TIMINGS_ALGEBRAIC_MODULAR_FORMS_Z
  os << "|AMFZ: class " << i << " p=" << p << " line orbits|=" << time << "\n";
#endif
  // the sums of |X| times the number of lines of O sent to O2, divided by
  // |O| at the end
  std::map<std::tuple<size_t, size_t, size_t>, int64_t> sums;
  AmfZRow row;
  for (size_t i_orbit = 0; i_orbit < ListRepr.size(); i_orbit++) {
    std::vector<int> eLine = ProjectiveLineOfIndex(n, p, ListRepr.at(i_orbit));
    std::optional<GenusNeighborBasis<T, Tint>> opt =
        GenusNeighborKernel<T, Tint>(G_i, eLine, p, os);
    if (!opt) {
      continue;
    }
    int64_t size_X = static_cast<int64_t>(ListRepr.orbit_size(i_orbit));
    row.n_neighbor += static_cast<size_t>(size_X);
    MyMatrix<Tint> GramN = UniversalMatrixConversion<Tint, T>(opt->GramN);
    size_t j = family_invariant_index<Tint, Tgroup>(family, GramN, os);
    if (N == 1) {
      sums[{0, j, 0}] += size_X;
      continue;
    }
    // An isometry Q: M -> L_j, Q G_j Q^T = Gram(M), then the level lines
    // of L_i in the coordinates of L_j: z -> z B_M^{-1} Q, B_M = Bp / p
    // the basis of M in those of L_i, whose denominators are prime to N.
    MyMatrix<T> GramM = opt->GramN;
    MyMatrix<T> G_j = UniversalMatrixConversion<T, Tint>(family.ListGram[j]);
    std::optional<MyMatrix<Tint>> opt_iso =
        LatticeIsometry<T, Tint, Tgroup>({G_j}, {GramM}, {},
                                         methods.isomorphism, os);
#ifdef SANITY_CHECK_ALGEBRAIC_MODULAR_FORMS_Z
    if (!opt_iso) {
      std::cerr << "AMFZ: the neighbor recognized as the class " << j
                << " is not isometric to it\n";
      throw TerminalException{1};
    }
#endif
    MyMatrix<T> Q = UniversalMatrixConversion<T, Tint>(*opt_iso);
    if (Q * G_j * Q.transpose() != GramM) {
      // the isometry the other way
      Q = Inverse(Q);
#ifdef SANITY_CHECK_ALGEBRAIC_MODULAR_FORMS_Z
      if (Q * G_j * Q.transpose() != GramM) {
        std::cerr << "AMFZ: the isometry does not map the class to the "
                     "neighbor\n";
        throw TerminalException{1};
      }
#endif
    }
    MyMatrix<T> B_M = UniversalMatrixConversion<T, Tint>(opt->Bp) / T(p);
    MyMatrix<T> R = Inverse(B_M) * Q;
    std::vector<int64_t> R_red(n * n);
    for (int a = 0; a < n; a++) {
      for (int b = 0; b < n; b++) {
        R_red[a * n + b] = order_residue_rat(R(a, b), int64_t(N));
      }
    }
    AmfZLevelData const &level_i = level[i];
    AmfZLevelData const &level_j = level[j];
    std::map<std::pair<size_t, size_t>, int64_t> count;
    std::vector<int> w(n);
    for (size_t idx = 0; idx < level_i.orbit_of_line.size(); idx++) {
      int64_t o = level_i.orbit_of_line[idx];
      if (o < 0) {
        continue;
      }
      std::vector<int> z = ProjectiveLineOfIndex(n, N, idx);
      for (int b = 0; b < n; b++) {
        int64_t sum = 0;
        for (int a = 0; a < n; a++) {
          sum = (sum + z[a] * R_red[a * n + b]) % N;
        }
        w[b] = static_cast<int>(sum);
      }
      int64_t o2 = level_j.orbit_of_line[IndexOfProjectiveLine(w, N)];
#ifdef SANITY_CHECK_ALGEBRAIC_MODULAR_FORMS_Z
      if (o2 < 0) {
        std::cerr << "AMFZ: an isotropic level line is sent to a non "
                     "isotropic one\n";
        throw TerminalException{1};
      }
#endif
      count[{static_cast<size_t>(o), static_cast<size_t>(o2)}]++;
    }
    for (auto const &[key, c] : count) {
      sums[{key.first, j, key.second}] += size_X * c;
    }
  }
  for (auto const &[key, s] : sums) {
    int64_t size_O =
        static_cast<int64_t>(level[i].orbit_size[std::get<0>(key)]);
#ifdef SANITY_CHECK_ALGEBRAIC_MODULAR_FORMS_Z
    if (s % size_O != 0) {
      std::cerr << "AMFZ: a Hecke matrix entry is not an integer\n";
      throw TerminalException{1};
    }
#endif
    row.entries[key] = s / size_O;
  }
#ifdef TIMINGS_ALGEBRAIC_MODULAR_FORMS_Z
  os << "|AMFZ: class " << i << " p=" << p << ", " << ListRepr.size()
     << " orbits|=" << time << "\n";
#endif
#ifdef DEBUG_ALGEBRAIC_MODULAR_FORMS_Z
  os << "AMFZ: class " << i << " p=" << p << " done, " << ListRepr.size()
     << " orbits of lines, " << row.n_neighbor << " neighbors\n";
#endif
  return row;
}

/*
  The result: the Hecke matrices on the states, sparse, the states of the
  class j being offset[j], ..., offset[j] + n_orbit[j] - 1.
 */
template <typename TintGroup> struct AmfZResult {
  using Tmass = typename overlying_field<TintGroup>::field_type;
  int level;
  std::vector<TintGroup> ListAutOrder;
  std::vector<size_t> ListNumberOrbit;
  // the size of every level orbit of every class
  std::vector<std::vector<size_t>> ListOrbitSize;
  std::vector<size_t> offset;
  size_t n_state = 0;
  Tmass mass;
  Tmass mass_formula;
  std::vector<int> ListPrime;
  std::vector<size_t> ListNeighbor;
  // per prime, (row state, column state) -> entry
  std::vector<std::map<std::pair<size_t, size_t>, int64_t>> ListHecke;
};

template <typename TintGroup>
void WriteAmfZResult(std::ostream &os, AmfZResult<TintGroup> const &res,
                     std::string const &OutFormat) {
  if (OutFormat == "GAP") {
    os << "return rec(level:=" << res.level
       << ", n_class:=" << res.ListAutOrder.size()
       << ", n_state:=" << res.n_state << ",\nListAutOrder:=[";
    for (size_t j = 0; j < res.ListAutOrder.size(); j++) {
      os << (j > 0 ? ", " : "") << res.ListAutOrder[j];
    }
    os << "],\nListNumberOrbit:=[";
    for (size_t j = 0; j < res.ListNumberOrbit.size(); j++) {
      os << (j > 0 ? ", " : "") << res.ListNumberOrbit[j];
    }
    os << "],\nListOrbitSize:=[";
    for (size_t j = 0; j < res.ListOrbitSize.size(); j++) {
      os << (j > 0 ? ", " : "") << "[";
      for (size_t o = 0; o < res.ListOrbitSize[j].size(); o++) {
        os << (o > 0 ? "," : "") << res.ListOrbitSize[j][o];
      }
      os << "]";
    }
    os << "],\nmass:=" << res.mass << ", mass_formula:=" << res.mass_formula
       << ",\nListHecke:=[";
    for (size_t ip = 0; ip < res.ListPrime.size(); ip++) {
      os << (ip > 0 ? ",\n" : "") << "rec(prime:=" << res.ListPrime[ip]
         << ", n_neighbor:=" << res.ListNeighbor[ip] << ", entries:=[";
      bool first = true;
      for (auto const &[key, val] : res.ListHecke[ip]) {
        os << (first ? "" : ",") << "[" << (key.first + 1) << ","
           << (key.second + 1) << "," << val << "]";
        first = false;
      }
      os << "])";
    }
    os << "]);\n";
    return;
  }
  std::cerr << "AMFZ: unknown OutFormat=" << OutFormat
            << ", the allowed one is GAP\n";
  throw TerminalException{1};
}

/*
  The Hecke operators are self-adjoint for the inner product of the
  states, <(L_j, O), (L_j, O)> = |O| / |Aut(L_j)|: T(s, t) w(s) = T(t, s)
  w(t). That is checked with SANITY_CHECK, and with the extensive check
  that the operators at the different primes commute, which is cubic in
  the number of states.
 */
template <typename TintGroup>
void AmfZCheckResult([[maybe_unused]] AmfZResult<TintGroup> const &res) {
#ifdef SANITY_CHECK_ALGEBRAIC_MODULAR_FORMS_Z
  using Tmass = typename AmfZResult<TintGroup>::Tmass;
  std::vector<Tmass> weight;
  for (size_t j = 0; j < res.ListOrbitSize.size(); j++) {
    Tmass inv_aut =
        Tmass(1) / UniversalScalarConversion<Tmass, TintGroup>(res.ListAutOrder[j]);
    for (size_t size : res.ListOrbitSize[j]) {
      weight.push_back(Tmass(static_cast<long>(size)) * inv_aut);
    }
  }
  for (size_t ip = 0; ip < res.ListHecke.size(); ip++) {
    auto const &H = res.ListHecke[ip];
    for (auto const &[key, val] : H) {
      auto iter = H.find({key.second, key.first});
      int64_t val_t = (iter == H.end()) ? 0 : iter->second;
      if (Tmass(static_cast<long>(val)) * weight[key.first] !=
          Tmass(static_cast<long>(val_t)) * weight[key.second]) {
        std::cerr << "AMFZ: the Hecke operator at p=" << res.ListPrime[ip]
                  << " is not self-adjoint at the states " << key.first
                  << ", " << key.second << "\n";
        throw TerminalException{1};
      }
    }
  }
#endif
#ifdef SANITY_CHECK_ALGEBRAIC_MODULAR_FORMS_Z_EXTENSIVE
  std::cerr << "AMFZ: SANITY_CHECK_ALGEBRAIC_MODULAR_FORMS_Z_EXTENSIVE, the "
               "Hecke operators commute\n";
  size_t S = res.n_state;
  auto dense = [&](size_t ip) -> MyMatrix<mpz_class> {
    MyMatrix<mpz_class> M = ZeroMatrix<mpz_class>(S, S);
    for (auto const &[key, val] : res.ListHecke[ip]) {
      M(key.first, key.second) = mpz_class(static_cast<long>(val));
    }
    return M;
  };
  for (size_t ip = 0; ip < res.ListHecke.size(); ip++) {
    MyMatrix<mpz_class> A = dense(ip);
    for (size_t iq = ip + 1; iq < res.ListHecke.size(); iq++) {
      MyMatrix<mpz_class> B = dense(iq);
      if (A * B != B * A) {
        std::cerr << "AMFZ: the Hecke operators at p=" << res.ListPrime[ip]
                  << " and p=" << res.ListPrime[iq] << " do not commute\n";
        throw TerminalException{1};
      }
    }
  }
  std::cerr << "AMFZ: SANITY_CHECK_ALGEBRAIC_MODULAR_FORMS_Z_EXTENSIVE, "
               "done\n";
#endif
}

