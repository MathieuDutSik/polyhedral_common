/*
  The total mass of the genera of pairs (L, G), L in the genus of A and G
  acting with the character of a model representation R (matrices R_j of
  the generators acting on the columns):

    sum_{Lambda in gen(A)} sum_{rho : G -> O(Lambda) of the character of R}
      1 / |O(Lambda)|
    = sum_{Lambda} sum_{classes of rho} 1 / |C_{O(Lambda)}(rho)|,

  the count of the homomorphisms over the order of the group (orbit and
  stabilizer). It certifies the list of the genera of pairs found by the
  gluing (GENUS_GlueIsometry target=auto).

  O(Lambda) acts on an invariant family of vectors spanning Lambda
  (ExtractInvariantVectorFamilyZbasis), as a permutation group (permutalib).
  The homomorphisms are counted up to conjugacy by choosing the images of
  the generators in turn: x_1 among the representatives of the conjugacy
  classes of O (ConjugacyClasses) with the characteristic polynomial of
  R_1, with H_1 = C(x_1); x_j among the elements of the classes of the
  characteristic polynomial of R_j up to the conjugation by H_{j-1}, that
  is y^t for t in the double cosets C(y) \ O / H_{j-1}, with H_j = H_{j-1}
  cap C(x_j). Every class of homomorphisms is met once, with C(rho) = H_k.
  A tuple defines a homomorphism of the character of R exactly when the
  pairs (R(g), rho(g)) generated by the (R_j, rho(g_j)) have a single rho(g)
  for each R(g) (the graph of a map) and equal traces.
 */

// The traces of X^m, m = 1..n: equal for two matrices exactly when their
// characteristic polynomials are (Newton).
template <typename T> std::vector<T> TracesOfPowers(MyMatrix<T> const &X) {
  int n = X.rows();
  std::vector<T> res;
  MyMatrix<T> P = X;
  for (int m = 1; m <= n; m++) {
    T tr(0);
    for (int i = 0; i < n; i++) {
      tr += P(i, i);
    }
    res.push_back(tr);
    P = P * X;
  }
  return res;
}

/*
  Whether the tuple Y (on the columns) defines, through R_j -> Y_j, a
  homomorphism from the group generated by the R_j, with equal traces on
  every element when check_traces.
 */
template <typename T>
bool IsHomomorphismOfCharacter(std::vector<MyMatrix<T>> const &R,
                               std::vector<MyMatrix<T>> const &Y,
                               bool check_traces) {
  int nR = R[0].rows();
  int nY = Y[0].rows();
  auto flat = [](MyMatrix<T> const &M) -> std::vector<T> {
    std::vector<T> v;
    for (int i = 0; i < M.rows(); i++) {
      for (int j = 0; j < M.cols(); j++) {
        v.push_back(M(i, j));
      }
    }
    return v;
  };
  std::map<std::vector<T>, std::vector<T>> graph;
  std::vector<std::pair<MyMatrix<T>, MyMatrix<T>>> work{
      {IdentityMat<T>(nR), IdentityMat<T>(nY)}};
  graph[flat(work[0].first)] = flat(work[0].second);
  for (size_t pos = 0; pos < work.size(); pos++) {
    for (size_t j = 0; j < R.size(); j++) {
      MyMatrix<T> a = work[pos].first * R[j];
      MyMatrix<T> b = work[pos].second * Y[j];
      std::vector<T> ka = flat(a), kb = flat(b);
      auto iter = graph.find(ka);
      if (iter != graph.end()) {
        if (iter->second != kb) {
          return false;
        }
        continue;
      }
      if (check_traces) {
        T ta(0), tb(0);
        for (int i = 0; i < nR; i++) {
          ta += a(i, i);
        }
        for (int i = 0; i < nY; i++) {
          tb += b(i, i);
        }
        if (ta != tb) {
          return false;
        }
      }
      graph[ka] = kb;
      work.push_back({a, b});
    }
  }
  return true;
}

/*
  sum over the classes of rho : G -> O(A) of the character of R of
  1 / |C(rho)|, for one lattice A.
 */
template <typename T, typename Tint, typename Tgroup>
T HomomorphismClassMass(MyMatrix<T> const &A, std::vector<MyMatrix<T>> const &R,
                        std::ostream &os) {
  using Telt = typename Tgroup::Telt;
  using TintGroup = typename Tgroup::Tint;
  int n = A.rows();
  // the invariant family and O(A) on it (rows: v -> v g, g A g^T = A)
  MyMatrix<Tint> SHV_i = ExtractInvariantVectorFamilyZbasis<T, Tint>(A, os);
  MyMatrix<T> SHV = UniversalMatrixConversion<T, Tint>(SHV_i);
  IntAutomorphismGroup<Tint, Tgroup> aut = LatticeAutomorphismGroup<T, Tint, Tgroup>(
      std::vector<MyMatrix<T>>{A},
      LatticeMethodChoice(LatticeStabCanIsomMethod::Graph,
                          InvariantFamilyKind::IteratedShortest),
      os);
  std::vector<Telt> LGenPerm;
  for (auto const &g : aut.ListGen) {
    MyMatrix<T> g_T = UniversalMatrixConversion<T, Tint>(g);
    MyMatrix<T> img = SHV * g_T;
    // i -> j with SHV[i] g = SHV[j]
    LGenPerm.push_back(GetPermutationOnVectors<T, Telt>(img, SHV));
  }
  Telt id(static_cast<typename Telt::Tidx>(SHV.rows()));
  Tgroup O(LGenPerm, id);
  // a basis among the vectors, to map a permutation back to a matrix
  std::vector<int> basis_idx;
  {
    MyMatrix<T> cur(0, n);
    for (int i = 0; i < SHV.rows() && static_cast<int>(basis_idx.size()) < n;
         i++) {
      MyMatrix<T> test = Concatenate(cur, MyMatrix<T>(SHV.row(i)));
      if (RankMat(test) > static_cast<int>(basis_idx.size())) {
        cur = test;
        basis_idx.push_back(i);
      }
    }
  }
  MyMatrix<T> Bm(n, n);
  for (int i = 0; i < n; i++) {
    Bm.row(i) = SHV.row(basis_idx[i]);
  }
  MyMatrix<T> BmInv = Inverse(Bm);
  // the matrix on the columns of the permutation
  auto to_matrix = [&](Telt const &p) -> MyMatrix<T> {
    MyMatrix<T> Img(n, n);
    for (int i = 0; i < n; i++) {
      Img.row(i) = SHV.row(p.at(basis_idx[i]));
    }
    MyMatrix<T> X = BmInv * Img;
    return X.transpose();
  };
  // the classes, by the traces of the powers
  std::vector<typename Tgroup::ConjugacyClassData> classes =
      O.ConjugacyClasses();
  std::vector<std::vector<T>> class_traces;
  for (auto const &c : classes) {
    class_traces.push_back(TracesOfPowers(to_matrix(c.rep)));
  }
  size_t k = R.size();
  std::vector<std::vector<T>> gen_traces;
  for (auto const &Rj : R) {
    gen_traces.push_back(TracesOfPowers(Rj));
  }
  T total(0);
  size_t n_hom = 0;
  std::vector<Telt> xs(k);
  std::function<void(size_t, Tgroup const &)> rec =
      [&](size_t j, Tgroup const &H) -> void {
    if (j == k) {
      std::vector<MyMatrix<T>> Y;
      for (auto const &x : xs) {
        Y.push_back(to_matrix(x));
      }
      if (IsHomomorphismOfCharacter(R, Y, true)) {
        total += T(1) / UniversalScalarConversion<T, TintGroup>(H.size());
        n_hom++;
      }
      return;
    }
    for (size_t ic = 0; ic < classes.size(); ic++) {
      if (class_traces[ic] != gen_traces[j]) {
        continue;
      }
      Telt const &y = classes[ic].rep;
      std::vector<Telt> cands;
      if (j == 0) {
        cands.push_back(y);
      } else {
        Tgroup Cy = O.Centralizer_elt(y);
        for (auto const &t : O.double_cosets(Cy, H)) {
          cands.push_back(Conjugation(y, t));
        }
      }
      for (auto const &x : cands) {
        xs[j] = x;
        // the partial tuple must define a homomorphism of the subgroup
        std::vector<MyMatrix<T>> Rp(R.begin(), R.begin() + j + 1);
        std::vector<MyMatrix<T>> Yp;
        for (size_t u = 0; u <= j; u++) {
          Yp.push_back(to_matrix(xs[u]));
        }
        if (!IsHomomorphismOfCharacter(Rp, Yp, false)) {
          continue;
        }
        rec(j + 1, H.Centralizer_elt(x));
      }
    }
  };
  rec(0, O);
  os << "GROUP_HOM_COUNT: |O| = " << O.size() << ", " << classes.size()
     << " classes, " << n_hom << " classes of homomorphisms, mass " << total
     << "\n";
  return total;
}

/*
  The total over the genus of A: the classes by GenusEnumeration, or
  GenusEnumerationOdd for an odd A (closed by GenusMass, which covers both),
  then HomomorphismClassMass for each; nullopt when the enumeration of the
  genus did not close.
 */
template <typename T, typename Tint, typename Tgroup>
std::optional<T> HomomorphismGenusMass(MyMatrix<T> const &A,
                                       std::vector<MyMatrix<T>> const &R,
                                       std::ostream &os) {
  using Tmass = typename GenusEnumerationResult<T, Tgroup>::Tmass;
  T mass = GenusMass<T, Tint>(A);
  GenusMethods methods;
  bool even = true;
  for (int i = 0; i < A.rows(); i++) {
    even = even && IsInteger(A(i, i) / T(2));
  }
  GenusEnumerationResult<T, Tgroup> genus =
      even ? GenusEnumeration<T, Tint, Tgroup>(
                 std::vector<MyMatrix<T>>{A}, MassToGroupField<Tmass>(mass), 0,
                 methods, NeighborStrategy::Iterate, GenusRandomWalkOptions(),
                 false, GenusOrderOptions(), -1, os)
           : GenusEnumerationOdd<T, Tint, Tgroup>(
                 std::vector<MyMatrix<T>>{A}, MassToGroupField<Tmass>(mass), 0,
                 methods, NeighborStrategy::Iterate, GenusRandomWalkOptions(),
                 false, GenusOrderOptions(), -1, os);
  if (!genus.complete) {
    return {};
  }
  T total(0);
  for (auto const &L : genus.ListGram) {
    total += HomomorphismClassMass<T, Tint, Tgroup>(L, R, os);
  }
  os << "GROUP_HOM_COUNT: " << genus.ListGram.size()
     << " classes in the genus, total mass " << total << "\n";
  return total;
}

