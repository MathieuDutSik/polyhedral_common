/*
  The abelian number fields as subfields of Q(zeta_n): the field fixed by
  a subgroup H of (Z/n)^*, given by n and the elements of H. E is CM when
  -1 is not in H, with maximal real subfield the field fixed by <H, -1>;
  it is totally real when -1 is in H. Their Dirichlet characters are those
  modulo n trivial on H (CyclotomicArithmetic.h), and give the
  decomposition of the rational primes.
 */

struct AbelianField {
  int64_t n;
  std::vector<int64_t> H;
};

inline AbelianField MakeAbelianCMField(int64_t n,
                                       std::vector<int64_t> const &gens) {
  // the subgroup generated by gens
  std::set<int64_t> H{1 % std::max<int64_t>(n, 1)};
  std::vector<int64_t> queue{1 % std::max<int64_t>(n, 1)};
  while (!queue.empty()) {
    int64_t a = queue.back();
    queue.pop_back();
    for (int64_t g : gens) {
      int64_t b = ((a * (g % n)) % n + n) % n;
      if (std::gcd(b, n) != 1) {
        std::cerr << "CYCLO: " << g << " is not a unit modulo " << n << "\n";
        throw TerminalException{1};
      }
      if (H.insert(b).second) {
        queue.push_back(b);
      }
    }
  }
  if (n > 2 && H.count(n - 1) == 1) {
    std::cerr << "CYCLO: -1 is in H, the field is not CM\n";
    throw TerminalException{1};
  }
  return {n, std::vector<int64_t>(H.begin(), H.end())};
}

inline int64_t AbelianFieldDegree(AbelianField const &F) {
  return EulerPhi(F.n) / static_cast<int64_t>(F.H.size());
}

// The quadratic field data: a totally real field as (n, H) with -1 in H.
inline AbelianField MakeAbelianRealField(int64_t n,
                                           std::vector<int64_t> const &gens) {
  std::vector<int64_t> g = gens;
  if (n > 2) {
    g.push_back(n - 1);
  }
  // MakeAbelianCMField refuses -1: build the subgroup directly
  std::set<int64_t> Hs{1 % std::max<int64_t>(n, 1)};
  std::vector<int64_t> queue{1 % std::max<int64_t>(n, 1)};
  while (!queue.empty()) {
    int64_t a = queue.back();
    queue.pop_back();
    for (int64_t x : g) {
      int64_t b = ((a * (x % n)) % n + n) % n;
      if (Hs.insert(b).second) {
        queue.push_back(b);
      }
    }
  }
  return {n, std::vector<int64_t>(Hs.begin(), Hs.end())};
}

/*
  The decomposition of a rational prime q in the field of a group X of
  Dirichlet characters: e = [X : X_unr] with X_unr the characters of
  conductor prime to q, f the order of q on X_unr (the lcm of the orders of
  the chi(q)), and g = |X| / (e f).
 */
struct PrimeDecompositionData {
  int64_t e;
  int64_t f;
  int64_t g;
};

inline PrimeDecompositionData
PrimeDecompositionCharacters(DirichletGroup const &G,
                             std::vector<std::vector<int64_t>> const &X,
                             int64_t q) {
  int64_t n_unr = 0;
  int64_t f = 1;
  for (auto const &t : X) {
    std::pair<int64_t, std::vector<int64_t>> prim = PrimitiveCharacter(G, t);
    int64_t cond = prim.first;
    if (cond % q == 0) {
      continue;
    }
    n_unr++;
    int64_t ex = prim.second[q % cond];
    int64_t ord = G.e / std::gcd(G.e, ex);
    f = std::lcm(f, ord);
  }
  int64_t sz = static_cast<int64_t>(X.size());
  int64_t e = sz / n_unr;
  return {e, f, sz / (e * f)};
}

inline std::vector<std::vector<int64_t>>
FieldCharacters(DirichletGroup const &G, std::vector<int64_t> const &H,
                bool even_only) {
  std::vector<std::vector<int64_t>> res;
  for (auto &t : ListCharacters(G)) {
    bool ok = true;
    for (int64_t h : H) {
      if (CharacterExponent(G, t, h) != 0) {
        ok = false;
      }
    }
    if (ok && even_only && G.d > 2 && CharacterExponent(G, t, G.d - 1) != 0) {
      ok = false;
    }
    if (ok) {
      res.push_back(t);
    }
  }
  return res;
}

/*
  The decomposition of q in a CM field E and in its real subfield K, and
  the type of the primes of K over q in E (all alike, E / K being abelian):
  ramified (2) when e_q(E) = 2 e_q(K), split (0) when g_q(E) = 2 g_q(K),
  inert (1) otherwise.
 */
struct CMPrimeDecomposition {
  PrimeDecompositionData E;
  PrimeDecompositionData K;
  int type;
};

inline CMPrimeDecomposition DecomposePrimeCM(AbelianField const &F,
                                             int64_t q) {
  DirichletGroup G = ComputeDirichletGroup(F.n);
  CMPrimeDecomposition res;
  res.E = PrimeDecompositionCharacters(G, FieldCharacters(G, F.H, false), q);
  res.K = PrimeDecompositionCharacters(G, FieldCharacters(G, F.H, true), q);
  if (res.E.e == 2 * res.K.e) {
    res.type = 2;
  } else if (res.E.g == 2 * res.K.g) {
    res.type = 0;
  } else {
    res.type = 1;
  }
  return res;
}

