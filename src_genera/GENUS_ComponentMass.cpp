// The integers of a comma separated list.
inline std::vector<int64_t> ParseIntList(std::string const &lst) {
  std::vector<int64_t> res;
  std::stringstream ss(lst);
  std::string tok;
  while (std::getline(ss, tok, ',')) {
    if (!tok.empty()) {
      res.push_back(std::stoll(tok));
    }
  }
  return res;
}

/*
  The quadratic Hecke character chi_{E/K} of a quadratic lattice over a
  totally real abelian field (MassQuadraticHeckeL.h): the field K, the
  discriminant d, |D_K|, the norm of the conductor and the Dirichlet
  coefficients a_1, ..., a_X of L(s, chi), and with prec_bits > 0 the
  value L(1 - r, chi) for m = 2r (MPFR, and Arb when built with flint),
  for a comparison with PARI.
 */
template <typename T>
void PrintQuadHeckeL(std::string const &FileGram, std::string const &FileOmega,
                     int64_t n, std::vector<int64_t> const &gens, int64_t X,
                     int prec_bits) {
  MyMatrix<T> B = ReadMatrixFile<T>(FileGram);
  std::vector<MyMatrix<T>> Omega = ReadListMatrixFile<T>(FileOmega);
  int m = B.rows() / static_cast<int>(Omega.size());
  AbelianField FK = MakeAbelianRealField(n, gens);
  std::optional<std::pair<NumberField<T>, ElemE<T>>> Kd =
      QuadDiscriminantK(B, Omega);
  if (!Kd) {
    std::cout << "fail\n";
    return;
  }
  auto f_none = [](int64_t, std::vector<QuadHeckePrime> const &) -> void {};
  std::optional<QuadHeckeCharacter<T>> C = ComputeQuadHeckeCharacter(
      B, Omega, FK, Kd->second, Kd->first, m, X, true, f_none);
  if (!C) {
    std::cout << "fail\n";
    return;
  }
  std::cout << "f:";
  for (auto const &c : Kd->first.Phi) {
    std::cout << " " << c;
  }
  std::cout << "\nd:";
  for (auto const &c : Kd->second) {
    std::cout << " " << c;
  }
  std::cout << "\nDK: " << C->D_K << "\nNf: " << C->norm_conductor
            << "\ndelta: " << C->delta << "\na:";
  for (auto const &x : QuadHeckeCoefficients(*C, X)) {
    std::cout << " " << x;
  }
  std::cout << "\n";
  if (prec_bits > 0) {
    std::optional<QuadHeckeLData<T>> Ld =
        MakeQuadHeckeLData(B, Omega, FK, Kd->second, Kd->first, m);
    std::optional<mpfr::mpreal> L =
        QuadHeckeLNegative<mpfr::mpreal>(*Ld, prec_bits, false);
    if (L) {
      std::cout << "L: "
                << L->toString(static_cast<int>(prec_bits * 0.30103) + 5)
                << "\n";
    } else {
      std::cout << "L: fail\n";
    }
#ifdef ENABLE_FLINT_SUPPORT
    std::optional<ArbReal> La =
        QuadHeckeLNegative<ArbReal>(*Ld, prec_bits, false);
    if (La) {
      std::cout << "Larb: "
                << La->str(static_cast<slong>(prec_bits * 0.30103) + 5) << "\n";
    } else {
      std::cout << "Larb: fail\n";
    }
#endif
  }
}

template <typename T>
void PrintOptional(std::optional<T> const &x) {
  if (x) {
    std::cout << *x;
  } else {
    std::cout << "fail";
  }
}

template <typename T, typename Tint>
void ProcessComponentMass(FullNamelist const &eFull) {
  SingleBlock const &BlockDATA = eFull.get_block("DATA");
  SingleBlock const &BlockMETHOD = eFull.get_block("METHOD");
  std::string field = BlockDATA.get_string("field");
  int64_t n = BlockDATA.get_int("n");
  std::string H = BlockDATA.get_string("H");
  std::vector<int64_t> gens = ParseIntList(H == "unset" ? "" : H);
  int m = BlockDATA.get_int("rank");
  std::string HE = BlockDATA.get_string("HE");
  std::string GramFile = BlockDATA.get_string("GramFile");
  std::string OmegaFile = BlockDATA.get_string("OmegaFile");
  std::string output = BlockMETHOD.get_string("output");
  QuadLValueMethod lvalue =
      ParseQuadLValueMethod(BlockMETHOD.get_string("lvalue"));
  auto lattice = [&]() -> std::pair<MyMatrix<T>, std::vector<MyMatrix<T>>> {
    if (GramFile == "unset" || OmegaFile == "unset") {
      std::cerr << "GENUS_ComponentMass: output = " << output
                << " needs GramFile and OmegaFile\n";
      throw TerminalException{1};
    }
    return {ReadMatrixFile<T>(GramFile), ReadListMatrixFile<T>(OmegaFile)};
  };
  if (field == "cyclotomic" && output == "standard_mass") {
    // the standard mass of rank m over Q(zeta_n), and the mass in rank one
    std::cout << "return rec(d:=" << n << ", m:=" << m << ", standard_mass:="
              << StandardHermitianMassCyclotomic<T>(n, m);
    if (m == 1) {
      std::cout << ", mass:=" << RankOneHermitianMassCyclotomic<T>(n);
    }
    std::cout << ");\n";
    return;
  }
  if (field == "abelian_cm" && output == "standard_mass") {
    AbelianField F = MakeAbelianCMField(n, gens);
    std::cout << "return rec(n:=" << n
              << ", degree:=" << AbelianFieldDegree(F) << ", m:=" << m
              << ", standard_mass:=" << StandardHermitianMassAbelian<T>(F, m);
    if (m == 1) {
      std::cout << ", mass:=" << RankOneHermitianMassAbelian<T>(F);
    }
    std::cout << ");\n";
    return;
  }
  if (field == "abelian_cm" && output == "mass") {
    auto [B, Omega] = lattice();
    AbelianField F = MakeAbelianCMField(n, gens);
    std::cout << "return rec(mass:=";
    PrintOptional(HermitianMassAbelianLattice(B, Omega, F));
    std::cout << ");\n";
    return;
  }
  if (field == "abelian_real" && output == "standard_mass") {
    AbelianField FK = MakeAbelianRealField(n, gens);
    bool square = (HE == "square");
    std::optional<AbelianField> FE;
    if (HE != "unset" && !square) {
      FE = MakeAbelianCMField(n, ParseIntList(HE));
    }
    std::cout << "return rec(standard_mass:=";
    PrintOptional(StandardQuadraticMassAbelian<T>(FK, m, square, FE));
    std::cout << ");\n";
    return;
  }
  if (field == "abelian_real" && output == "local_factors") {
    auto [B, Omega] = lattice();
    AbelianField FK = MakeAbelianRealField(n, gens);
    std::map<int64_t, std::optional<T>> facs =
        QuadraticLocalFactors(B, Omega, FK);
    std::optional<T> local_mass = T(1);
    for (auto const &kv : facs) {
      if (kv.second && local_mass) {
        *local_mass *= *kv.second;
      } else {
        local_mass = {};
      }
    }
    std::cout << "return rec(mass:=";
    PrintOptional(QuadraticMassAbelianLattice(B, Omega, FK, lvalue));
    std::cout << ", local_mass:=";
    PrintOptional(local_mass);
    std::cout << ", factors:=[";
    bool first = true;
    for (auto const &kv : facs) {
      std::cout << (first ? "" : ", ") << "[" << kv.first << ", ";
      PrintOptional(kv.second);
      std::cout << "]";
      first = false;
    }
    std::cout << "]);\n";
    return;
  }
  if (field == "abelian_real" && output == "hecke") {
    PrintQuadHeckeL<T>(GramFile, OmegaFile, n, gens,
                       BlockMETHOD.get_int("hecke_X"),
                       BlockMETHOD.get_int("hecke_prec_bits"));
    return;
  }
  std::cerr << "GENUS_ComponentMass: output = " << output
            << " is not available for field = " << field << "\n";
  throw TerminalException{1};
}

int main(int argc, char *argv[]) {
  maybe_install_gmp_pool();
  HumanTime time;
  try {
    FullNamelist eFull = NAMELIST_GetStandard_GENUS_COMPONENT_MASS();
    ArithmeticDispatch dispatch;
    add_rational_integer_arithmetics_by_library(
        dispatch, [&]<typename T, typename Tint>() -> void {
          ProcessComponentMass<T, Tint>(eFull);
        });
    if (argc != 2) {
      std::cerr << "Number of argument is = " << argc << "\n";
      std::cerr << "This program is used as\n";
      std::cerr << "GENUS_ComponentMass [file.nml]\n";
      std::cerr << "With file.nml a namelist file\n";
      eFull.NAMELIST_WriteNamelistFile(std::cerr, true);
      std::cerr << "arithmetic values:\n";
      dispatch.print_descriptions(std::cerr);
      return -1;
    }
    NAMELIST_ReadNamelistFile(argv[1], eFull);
    dispatch.run(GetNamelistStringEntry(eFull, "DATA", "arithmetic"));
    std::cerr << "Normal termination of GENUS_ComponentMass\n";
  } catch (TerminalException const &e) {
    std::cerr << "Error in GENUS_ComponentMass\n";
    exit(e.eVal);
  }
  runtime(time);
}
