/*
  The mass of one component, for the comparisons with Hecke.jl and PARI:
  a lattice over an abelian field K, the subfield of Q(zeta_n) fixed by the
  subgroup H of (Z/n)^* generated by the residues given (-1 is added for a
  totally real field), or over Q(zeta_n) itself.

    GENUS_ComponentMass file.nml

  (the namelist and its documentation are printed when run without
  argument). The lattice, when there is one, is given by its trace Gram
  matrix and the actions of a Z-basis of the ring of integers (a number,
  then the matrices).
 */

