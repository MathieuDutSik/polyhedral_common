/*
  The spinor genera of a genus of positive definite lattices, from its
  symbol (Conway-Sloane, Sphere Packings, Lattices and Groups, Chapter 15,
  Section 9; the port of _proper_spinor_kernel, _improper_spinor_kernel and
  automorphous_numbers of SageMath's genus.py, by Brandhorst).

  The spinor genera of a genus of rank >= 3 are the cosets of
      A = prod_{p | 2d} Z_p^x / Z_p^{x2}
  modulo the subgroup K generated by the images Delta_p(r) of the
  automorphous numbers r at every p | 2d: the square classes that are spinor
  norms of proper local automorphisms. A is an F_2 vector space, two bits
  at 2 (the classes 3 and 5 of Z_2^x / Z_2^{x2}) and one bit at each odd
  p | d (the non-squares), so the number of proper spinor genera |A / K| is
  a power of 2. The improper spinor genera, the classes being taken up to
  all the isometries, add one generator, found from a vector of a
  representative of the genus.

  For a prime l not dividing 2d, an l-neighbour moves a lattice to the
  spinor genus shifted by Delta(l), the diagonal image of l in A. So the
  l-neighbour graph of the genus has |Q| / |<Delta(l)>| connected
  components, Q = A / K, and a single seed suffices at l exactly when
  Delta(l) generates Q.
 */

// The vector space A: its coordinate primes, 2 first.
struct SpinorSpace {
  std::vector<int64_t> primes;
  int dim() const { return static_cast<int>(primes.size()) + 1; }
};

// The square class of the q-adic unit x as bits of A at the place q.
template <typename Tint>
uint64_t SpinorSquareClassBits(SpinorSpace const &A, Tint const &x,
                               int64_t q) {
  if (q == 2) {
    int64_t u = UniversalScalarConversion<int64_t, Tint>(ResInt(x, Tint(8)));
    uint64_t bits = 0;
    if (u == 3 || u == 7) {
      bits |= 1;
    }
    if (u == 5 || u == 7) {
      bits |= 2;
    }
    return bits;
  }
  size_t idx = 0;
  while (A.primes[idx] != q) {
    idx++;
  }
  if (LegendreModQ<Tint>(x, q) == -1) {
    return uint64_t(1) << (idx + 1);
  }
  return 0;
}

// Delta_p(r) of Conway-Sloane: the unit part of r at p, and p^{v_p(r)}
// at the other places.
template <typename Tint>
uint64_t SpinorDeltaAt(SpinorSpace const &A, Tint r, int64_t p) {
  Tint p_T(static_cast<long>(p));
  int v = 0;
  while (ResInt(r, p_T) == 0) {
    r /= p_T;
    v++;
  }
  Tint pv(1);
  for (int i = 0; i < v; i++) {
    pv *= p_T;
  }
  uint64_t bits = SpinorSquareClassBits(A, r, p);
  for (int64_t q : A.primes) {
    if (q != p) {
      bits ^= SpinorSquareClassBits(A, pv, q);
    }
  }
  return bits;
}

// Delta(r) for r prime to the primes of A: its class at every place.
template <typename Tint>
uint64_t SpinorDelta(SpinorSpace const &A, Tint const &r) {
  uint64_t bits = 0;
  for (int64_t q : A.primes) {
    bits ^= SpinorSquareClassBits(A, r, q);
  }
  return bits;
}

// An F_2 subspace by an echelon basis.
struct SpinorSubspace {
  std::vector<uint64_t> basis;
  // reduces x by the basis; 0 iff x is in the span
  uint64_t reduce(uint64_t x) const {
    for (uint64_t b : basis) {
      uint64_t lead = uint64_t(1) << (63 - __builtin_clzll(b));
      if (x & lead) {
        x ^= b;
      }
    }
    return x;
  }
  bool insert(uint64_t x) {
    x = reduce(x);
    if (x == 0) {
      return false;
    }
    uint64_t lead = uint64_t(1) << (63 - __builtin_clzll(x));
    for (auto &b : basis) {
      if (b & lead) {
        b ^= x;
      }
    }
    basis.push_back(x);
    std::sort(basis.begin(), basis.end(), std::greater<uint64_t>());
    return true;
  }
  bool contains(uint64_t x) const { return reduce(x) == 0; }
  int rank() const { return static_cast<int>(basis.size()); }
};

/*
  The automorphous numbers at p, as integers representing square classes
  (u p^v, v in {0, 1}), from the Jordan decomposition of the local Gram
  matrix built from the symbol (Conway-Sloane 15.9.6, as in SageMath).
 */
template <typename T, typename Tint>
std::vector<Tint> SpinorAutomorphousNumbers(GenusSymbol const &s, int64_t p) {
  int n = s.rank;
  std::vector<Tint> automorphs;
  auto count = [](std::vector<Tint> const &V, Tint const &x) -> int {
    return static_cast<int>(std::count(V.begin(), V.end(), x));
  };
  if (p != 2) {
    std::vector<std::array<int, 3>> const &comps = s.sym_odd.at(p);
    MyMatrix<T> G = OddPrimeLocalGram<T>(p, comps, n);
    Tint up(static_cast<long>(LeastNonResidue(p)));
    // the diagonal entries, each kept at most twice
    std::vector<Tint> I;
    for (int i = 0; i < n; i++) {
      Tint x = UniversalScalarConversion<Tint, T>(G(i, i));
      if (count(I, x) < 2) {
        I.push_back(x);
      }
    }
    for (auto const &r1 : I) {
      for (auto const &r2 : I) {
        automorphs.push_back(r1 * r2);
      }
    }
    // supplement (i)
    for (auto const &c : comps) {
      if (c[1] >= 2) {
        automorphs.push_back(up);
        break;
      }
    }
    // the square classes u p^v
    Tint p_T(static_cast<long>(p));
    std::vector<Tint> res;
    for (auto x : automorphs) {
      int v = 0;
      while (ResInt(x, p_T) == 0) {
        x /= p_T;
        v++;
      }
      Tint sq = (LegendreModQ<Tint>(x, p) == -1) ? up : Tint(1);
      if (v % 2 == 1) {
        sq *= p_T;
      }
      if (count(res, sq) == 0) {
        res.push_back(sq);
      }
    }
    return res;
  }
  MyMatrix<T> G = TwoAdicLocalGram<T>(s.sym2, n);
  // the 1 x 1 and 2 x 2 blocks of the block diagonal G
  std::vector<Tint> I, II;
  int i = 0;
  while (i < n) {
    if (i + 1 < n && G(i, i + 1) != 0) {
      Tint q = UniversalScalarConversion<Tint, T>(G(i, i + 1));
      for (long c : {1, 3, 5, 7}) {
        II.push_back(Tint(2 * c) * q);
      }
      i += 2;
    } else {
      Tint u = UniversalScalarConversion<Tint, T>(G(i, i));
      if (count(I, u) < 2) {
        I.push_back(u);
      }
      i += 1;
    }
  }
  std::vector<Tint> L;
  for (auto const &x : I) {
    L.push_back(x);
  }
  for (auto const &x : II) {
    if (count(L, x) < 2) {
      L.push_back(x);
    }
  }
  for (size_t a = 0; a < L.size(); a++) {
    for (size_t b = 0; b < a; b++) {
      automorphs.push_back(L[a] * L[b]);
    }
  }
  // supplement (i): three dimensions within the scales 2^k, ..., 2^{k+3}
  // of the first component. SageMath examines the first component only
  // (a break at the end of its loop), and so does this port.
  {
    int s0 = s.sym2[0][0], dim = 0;
    for (size_t k = 0; k < s.sym2.size() && k < 3; k++) {
      if (s.sym2[k][0] - s0 < 4) {
        dim += s.sym2[k][1];
      }
    }
    if (dim >= 3) {
      for (long c : {1, 3, 5, 7}) {
        automorphs.push_back(Tint(c));
      }
    }
  }
  // supplement (ii): the ratios of the diagonal entries, by valuation
  std::vector<Tint> Isorted = I;
  auto val2 = [](Tint x) -> int {
    int v = 0;
    while (ResInt(x, Tint(2)) == 0) {
      x /= Tint(2);
      v++;
    }
    return v;
  };
  std::stable_sort(Isorted.begin(), Isorted.end(),
                   [&](Tint const &a, Tint const &b) -> bool {
                     return val2(a) < val2(b);
                   });
  for (size_t a = 0; a < Isorted.size(); a++) {
    for (size_t b = 0; b < a; b++) {
      int v = val2(Isorted[a]) - val2(Isorted[b]);
      Tint ua = Isorted[a], ub = Isorted[b];
      while (ResInt(ua, Tint(2)) == 0) {
        ua /= Tint(2);
      }
      while (ResInt(ub, Tint(2)) == 0) {
        ub /= Tint(2);
      }
      // u = ua / ub mod 8
      int64_t ua8 = UniversalScalarConversion<int64_t, Tint>(ResInt(ua, Tint(8)));
      int64_t ub8 = UniversalScalarConversion<int64_t, Tint>(ResInt(ub, Tint(8)));
      int64_t u = ResMulI64(ua8, ResInvI64(ub8, 8), 8);
      if (v == 0 && u == 1) {
        automorphs.push_back(Tint(2));
      }
      if (v == 0 && u == 5) {
        automorphs.push_back(Tint(6));
      }
      if (v == 0 || v == 2 || v == 4) {
        automorphs.push_back(Tint(5));
      }
      if ((v == 1 || v == 3) && (u == 1 || u == 5)) {
        automorphs.push_back(Tint(3));
      }
      if ((v == 1 || v == 3) && (u == 3 || u == 7)) {
        automorphs.push_back(Tint(7));
      }
    }
  }
  // the square classes u 2^v, u mod 8
  std::vector<Tint> res;
  for (auto x : automorphs) {
    int v = val2(x);
    for (int k = 0; k < v; k++) {
      x /= Tint(2);
    }
    Tint sq = ResInt(x, Tint(8));
    if (v % 2 == 1) {
      sq *= Tint(2);
    }
    if (count(res, sq) == 0) {
      res.push_back(sq);
    }
  }
  return res;
}

struct SpinorGenusData {
  SpinorSpace A;
  SpinorSubspace kernel_proper;
  // with a representative: the improper kernel
  std::optional<SpinorSubspace> kernel_improper;
  int n_proper() const { return 1 << (A.dim() - kernel_proper.rank()); }
  std::optional<int> n_improper() const {
    if (!kernel_improper) {
      return {};
    }
    return 1 << (A.dim() - kernel_improper->rank());
  }
  // the kernel to use for the isometry classes: the improper one if known
  SpinorSubspace const &kernel() const {
    return kernel_improper ? *kernel_improper : kernel_proper;
  }
  int n_spinor_genera() const { return 1 << (A.dim() - kernel().rank()); }
  // The number of connected components of the l-neighbour graph, l odd and
  // prime to d: |Q| / |<Delta(l)>|.
  template <typename Tint> int neighbor_components(int64_t l) const {
    uint64_t delta = SpinorDelta(A, Tint(static_cast<long>(l)));
    int n = n_spinor_genera();
    return kernel().contains(delta) ? n : n / 2;
  }
};

/*
  The spinor kernels of the genus of the symbol s (positive definite, rank
  >= 3). With the Gram matrix G of a lattice of the genus, the improper
  kernel too: a vector x with v_p(x G x) = v_p(norm) at every p | 2d gives
  the improper generator Delta(r), r the product of the other primes q with
  v_q(norm) + v_q(x G x) odd.
 */
template <typename T, typename Tint>
SpinorGenusData GenusSpinorData(GenusSymbol const &s,
                                std::optional<MyMatrix<T>> const &G) {
  SpinorGenusData data;
  data.A.primes.push_back(2);
  for (auto const &kv : s.sym_odd) {
    data.A.primes.push_back(kv.first);
  }
  if (data.A.dim() > 63) {
    std::cerr << "GSPIN: too many primes in the determinant\n";
    throw TerminalException{1};
  }
  for (int64_t p : data.A.primes) {
    for (auto const &r : SpinorAutomorphousNumbers<T, Tint>(s, p)) {
      data.kernel_proper.insert(SpinorDeltaAt(data.A, r, p));
    }
  }
  if (!G || data.kernel_proper.rank() == data.A.dim()) {
    if (G) {
      data.kernel_improper = data.kernel_proper;
    }
    return data;
  }
  // the norm valuations at the primes of A
  std::vector<int> norm_val;
  for (int64_t p : data.A.primes) {
    if (p == 2) {
      norm_val.push_back(s.sym2[0][0] + 1 - s.sym2[0][3]);
    } else {
      norm_val.push_back(s.sym_odd.at(p)[0][0]);
    }
  }
  int n = G->rows();
  std::mt19937_64 gen(1);
  std::uniform_int_distribution<int> dist(-2, 2);
  for (int iter = 0; iter < 1000000; iter++) {
    MyVector<T> x(n);
    for (int i = 0; i < n; i++) {
      x(i) = T(dist(gen));
    }
    T qT = x.dot(*G * x);
    if (qT == 0) {
      continue;
    }
    Tint q = UniversalScalarConversion<Tint, T>(qT);
    bool ok = true;
    for (size_t k = 0; k < data.A.primes.size(); k++) {
      Tint p_T(static_cast<long>(data.A.primes[k]));
      Tint y = q;
      int v = 0;
      while (ResInt(y, p_T) == 0) {
        y /= p_T;
        v++;
      }
      if (v != norm_val[k]) {
        ok = false;
        break;
      }
    }
    if (!ok) {
      continue;
    }
    // r: the primes f of q with v_f(norm) + v_f(q) odd. At the primes of A
    // the two valuations are equal, so they never enter; outside A the norm
    // is a unit and v_f(q) decides.
    Tint r(1);
    std::map<Tint, int> mult;
    for (auto const &f : FactorsInt(q)) {
      mult[f]++;
    }
    for (auto const &[f, m] : mult) {
      int64_t f_i = UniversalScalarConversion<int64_t, Tint>(f);
      bool in_A = std::find(data.A.primes.begin(), data.A.primes.end(),
                            f_i) != data.A.primes.end();
      if (!in_A && m % 2 == 1) {
        r *= f;
      }
    }
    SpinorSubspace K = data.kernel_proper;
    K.insert(SpinorDelta(data.A, r));
    data.kernel_improper = K;
#ifdef DEBUG_GENUS_SPINOR
    std::cerr << "GSPIN: the improper generator from q=" << q << ", r=" << r
              << "\n";
#endif
    return data;
  }
  std::cerr << "GSPIN: no vector of the norm valuations found\n";
  throw TerminalException{1};
}

