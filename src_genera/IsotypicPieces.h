/*
  The isotypic pieces of a finite group G, abelian or not: the even
  positive definite G-lattices P whose rational G-module is rho^c, rho an
  irreducible rational representation with End_G(rho) = Q (rho absolutely
  irreducible, e.g. the representation of degree 2 of S_3 or of the
  dihedral group of order 8), up to isometry of pairs (P, G).

  At a prime p not dividing |G|, Z_p[G] acts on V_rho through a maximal
  order M_n(Z_p), and Morita equivalence gives P_p = M_p (x) X_p for M a
  fixed G-lattice in rho and X_p = Hom_G(M, P)_p a quadratic Z_p-lattice of
  rank c. So the pieces are reached from the M (x) X, X over the genera of
  rank c (odd and even), by changing them at the primes dividing |G| only.
  There the G-lattices of V_p are connected by G-stable steps of index p:
  P and P' meet in P cap P', reached from either by a chain of maximal
  G-stable sublattices. The steps (FlipNeighbors):
  - down: L' = {x in L : x mod p in U}, U a maximal G-submodule of L / pL,
    the orthogonal of an irreducible submodule for the transposed action
    (the contragredient module);
  - up: L' = L + (1/p) W~, W an irreducible G-submodule of the kernel of
    the Gram matrix modulo p, when L' is even.
  The walk stays among the even lattices and does not go beyond a bound on
  the determinant, so it is a search, not a proof: that no piece is
  missed is checked by the total masses (GroupOracle.g).
 */

/*
  A G-lattice: its Gram matrix and the generators of G acting on the
  columns, g^T A g = A.
 */
template <typename T> struct GroupLattice {
  MyMatrix<T> gram;
  std::vector<MyMatrix<T>> gens;
};

// The G-lattice L in the basis of the rows of B (invertible over Q).
template <typename T>
GroupLattice<T> GroupLatticeInBasis(GroupLattice<T> const &L,
                                    MyMatrix<T> const &B) {
  MyMatrix<T> Binv = Inverse(B);
  GroupLattice<T> res{B * L.gram * B.transpose(), {}};
  for (auto const &g : L.gens) {
    // on the rows, x -> x g^T, in the new basis B g^T B^{-1}
    MyMatrix<T> P = B * g.transpose() * Binv;
    res.gens.push_back(P.transpose());
  }
  return res;
}

// The lattice spanned by the rows of Gen (rational, of full rank) in the
// basis of L, with the induced form and action.
template <typename T>
GroupLattice<T> GroupLatticeOfRows(GroupLattice<T> const &L,
                                   MyMatrix<T> const &Gen) {
  return GroupLatticeInBasis(L, GetZbasis(Gen));
}

// The primes dividing the order of the group generated by the gens.
template <typename T, typename Tint>
std::vector<Tint> GroupLatticePrimes(GroupLattice<T> const &M) {
  std::vector<MyMatrix<T>> ListP;
  for (auto const &g : M.gens) {
    ListP.push_back(g.transpose());
  }
  size_t order = GroupElementsAndInverses(ListP, 100000).first.size();
  std::vector<Tint> res;
  if (order > 1) {
    for (auto const &[q, e] : FactorsIntMap(Tint(static_cast<long>(order)))) {
      res.push_back(q);
    }
  }
  return res;
}

template <typename T> bool IsEvenIntegralGram(MyMatrix<T> const &A) {
  if (!IsIntegralMatrix(A)) {
    return false;
  }
  for (int i = 0; i < A.rows(); i++) {
    if (!IsInteger(A(i, i) / 2)) {
      return false;
    }
  }
  return true;
}

/*
  The irreducible G-submodules of the G-submodule W of F_p^n (rows, G
  acting on the right by the gens): the minimal ones among the spans of
  the orbits of the vectors of W, up to scalars.
 */
inline std::vector<RowSpaceModP>
IrreducibleSubmodulesOf(RowSpaceModP const &W,
                        std::vector<ModMatrix> const &gens, T_small_prime p) {
  int k = W.basis.rows();
  int n = W.basis.cols();
  // keyed by the dimension, then the entries of the echelon basis (the
  // order of matrices needs equal shapes)
  std::map<ModVector, RowSpaceModP> cyclic;
  if (k == 0) {
    return {};
  }
  // the coefficient vectors of W, normalized by a leading 1
  std::vector<T_residue> c(k, 0);
  size_t total = 1;
  for (int i = 0; i < k; i++) {
    total *= p;
  }
  for (size_t idx = 1; idx < total; idx++) {
    size_t x = idx;
    int lead = -1;
    for (int i = 0; i < k; i++) {
      c[i] = x % p;
      x /= p;
      if (c[i] != 0 && lead < 0) {
        lead = i;
      }
    }
    if (c[lead] != 1) {
      continue;
    }
    ModMatrix v = ZeroMatrix<T_residue>(1, n);
    for (int i = 0; i < k; i++) {
      for (int j = 0; j < n; j++) {
        v(0, j) = ResAdd(v(0, j), ResMul(c[i], W.basis(i, j), p), p);
      }
    }
    RowSpaceModP rs = SpinModule(v, gens, p);
    ModVector key{static_cast<T_residue>(rs.basis.rows())};
    for (T_residue x : FlattenModMatrix(rs.basis)) {
      key.push_back(x);
    }
    cyclic.emplace(key, rs);
  }
  // the minimal ones: no other cyclic submodule strictly inside
  std::vector<RowSpaceModP> res;
  for (auto const &[key, rs] : cyclic) {
    bool minimal = true;
    for (auto const &[key2, rs2] : cyclic) {
      if (rs2.basis.rows() < rs.basis.rows() &&
          RankModPrime(Concatenate(rs.basis, rs2.basis), p) ==
              static_cast<size_t>(rs.basis.rows())) {
        minimal = false;
        break;
      }
    }
    if (minimal) {
      res.push_back(rs);
    }
  }
  return res;
}

/*
  The G-stable neighbors of L at the prime p by one step, down to a maximal
  G-stable sublattice containing pL or up to a G-stable integral
  overlattice inside (1/p) L, see the comment at the top; the down steps
  first, n_down of them.
 */
template <typename T>
std::vector<GroupLattice<T>> FlipNeighbors(GroupLattice<T> const &L,
                                           T_small_prime p, size_t &n_down,
                                           bool with_up) {
  int n = L.gram.rows();
  std::vector<ModMatrix> gens_row, gens_tr;
  for (auto const &g : L.gens) {
    // rows: x -> x g^T; the contragredient: y -> y g
    gens_row.push_back(ModMatrixOfMatrix(MyMatrix<T>(g.transpose()), p));
    gens_tr.push_back(ModMatrixOfMatrix(g, p));
  }
  std::vector<GroupLattice<T>> res;
  RowSpaceModP full = ComputeRowSpaceModP(ModMatrixIdentity(n), p);
  T p_T = UniversalScalarConversion<T, T_small_prime>(p);
  // down: U = S^perp for the standard pairing, S irreducible for gens_tr
  for (auto const &S : IrreducibleSubmodulesOf(full, gens_tr, p)) {
    ModMatrix U = LeftNullspaceModP(MyMatrix<T_residue>(S.basis.transpose()),
                                    p);
    MyMatrix<T> Gen(U.rows() + n, n);
    for (int i = 0; i < U.rows(); i++) {
      for (int j = 0; j < n; j++) {
        Gen(i, j) = UniversalScalarConversion<T, T_residue>(U(i, j));
      }
    }
    for (int i = 0; i < n; i++) {
      for (int j = 0; j < n; j++) {
        Gen(U.rows() + i, j) = (i == j) ? p_T : T(0);
      }
    }
    res.push_back(GroupLatticeOfRows(L, Gen));
  }
  n_down = res.size();
  if (!with_up) {
    return res;
  }
  // up: W in the kernel of the Gram matrix modulo p
  ModMatrix K = LeftNullspaceModP(ModMatrixOfMatrix(L.gram, p), p);
  if (K.rows() > 0) {
    RowSpaceModP Kr = ComputeRowSpaceModP(K, p);
    for (auto const &W : IrreducibleSubmodulesOf(Kr, gens_row, p)) {
      MyMatrix<T> Gen(W.basis.rows() + n, n);
      for (int i = 0; i < W.basis.rows(); i++) {
        for (int j = 0; j < n; j++) {
          Gen(i, j) = UniversalScalarConversion<T, T_residue>(W.basis(i, j)) /
                      p_T;
        }
      }
      for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
          Gen(W.basis.rows() + i, j) = (i == j) ? T(1) : T(0);
        }
      }
      GroupLattice<T> N = GroupLatticeOfRows(L, Gen);
      if (IsIntegralMatrix(N.gram)) {
        res.push_back(N);
      }
    }
  }
  return res;
}

// The Kronecker product of the G-lattice M with the lattice X (G acting
// on M only).
template <typename T>
GroupLattice<T> TensorWithLattice(GroupLattice<T> const &M,
                                  MyMatrix<T> const &X) {
  auto kron = [](MyMatrix<T> const &U, MyMatrix<T> const &V) -> MyMatrix<T> {
    MyMatrix<T> R(U.rows() * V.rows(), U.cols() * V.cols());
    for (int i = 0; i < U.rows(); i++) {
      for (int j = 0; j < U.cols(); j++) {
        for (int k = 0; k < V.rows(); k++) {
          for (int l = 0; l < V.cols(); l++) {
            R(i * V.rows() + k, j * V.cols() + l) = U(i, j) * V(k, l);
          }
        }
      }
    }
    return R;
  };
  GroupLattice<T> res{kron(M.gram, X), {}};
  MyMatrix<T> I = IdentityMat<T>(X.rows());
  for (auto const &g : M.gens) {
    res.gens.push_back(kron(g, I));
  }
  return res;
}

/*
  The key of a start X (genus symbol gs, determinant d): its local symbols
  at the odd primes outside those of G, its 2-adic symbol when 2 is not a
  prime of G, and at each prime p of G the rational class of X over Q_p,
  the square class of d (valuation mod 2, the unit part modulo p, or
  modulo 8 at 2) and the Hasse invariant.
 */
template <typename T, typename Tint>
std::vector<int64_t> StartKey(GenusSymbol const &gs, Tint const &d,
                              std::vector<Tint> const &group_primes,
                              std::ostream &os) {
  std::set<int64_t> gp;
  for (auto const &p : group_primes) {
    gp.insert(UniversalScalarConversion<int64_t, Tint>(p));
  }
  std::vector<int64_t> key{gs.rank, gs.even ? 1 : 0};
  for (auto const &[p, comps] : gs.sym_odd) {
    if (gp.count(p) == 0) {
      key.push_back(p);
      for (auto const &cc : comps) {
        key.insert(key.end(), cc.begin(), cc.end());
      }
    }
  }
  key.push_back(-1);
  if (gp.count(2) == 0) {
    for (auto const &cc : gs.sym2) {
      key.insert(key.end(), cc.begin(), cc.end());
    }
  }
  key.push_back(-1);
  std::vector<T> diag =
      RationalDiagonalForm(GenusSymbolRepresentative<T, Tint>(gs, os));
  for (int64_t p : gp) {
    Tint u = d;
    int v = 0;
    Tint p_i(static_cast<long>(p));
    while (ResInt(u, p_i) == 0) {
      u /= p_i;
      v++;
    }
    int64_t m = (p == 2) ? 8 : p;
    int64_t u_m = UniversalScalarConversion<int64_t, Tint>(ResInt(u, Tint(static_cast<long>(m))));
    int64_t cls = u_m;
    if (p != 2) {
      // the Legendre symbol of u modulo p
      int64_t x = 1;
      for (int64_t k = 0; k < (p - 1) / 2; k++) {
        x = (x * u_m) % p;
      }
      cls = (x == 1) ? 1 : -1;
    }
    key.push_back(p);
    key.push_back(v % 2);
    key.push_back(cls);
    key.push_back(HasseInvariantDiagonal<T, Tint>(diag, p));
  }
  return key;
}

/*
  The integral part of L with its form divided by s = p_1 ... p_k: the x
  with b(x, L) in sZ, by the kernel of the Gram matrix modulo p_i in turn
  (the form of that sublattice is then divisible by p_i).
 */
template <typename T, typename Tint>
GroupLattice<T> ScaledIntegralPart(GroupLattice<T> L,
                                   std::vector<Tint> const &primes) {
  int n = L.gram.rows();
  for (auto const &p : primes) {
    T_residue p_r = UniversalScalarConversion<T_residue, Tint>(p);
    T p_T = UniversalScalarConversion<T, Tint>(p);
    ModMatrix K = LeftNullspaceModP(ModMatrixOfMatrix(L.gram, p_r), p_r);
    MyMatrix<T> Gen(K.rows() + n, n);
    for (int i = 0; i < K.rows(); i++) {
      for (int j = 0; j < n; j++) {
        Gen(i, j) = UniversalScalarConversion<T, T_residue>(K(i, j));
      }
    }
    for (int i = 0; i < n; i++) {
      for (int j = 0; j < n; j++) {
        Gen(K.rows() + i, j) = (i == j) ? p_T : T(0);
      }
    }
    L = GroupLatticeOfRows(L, Gen);
    L.gram /= p_T;
  }
  return L;
}

/*
  The pieces rho^c of the admissible determinants dets, from the G-lattice
  M in rho, the primes of |G| given: the starts M (x) X, X over the genera
  of rank c whose determinant makes that of M (x) X right outside the
  primes of G (times p^e, 0 <= e <= 3, at the primes of G, for the
  rational classes there), their forms also divided by s squarefree over
  the primes of G (ScaledIntegralPart: form_M (x) q for the q that are not
  integral), then the G-stable steps at the primes of G among the integral
  lattices, a step down only to a determinant whose valuation at a prime
  of G is at most 2 more than the largest admissible one. The even ones
  of admissible determinant are kept, one pair per class, by the
  canonical form.
 */
template <typename T, typename Tint, typename Tgroup>
std::vector<GroupLattice<T>>
IsotypicPieces(GroupLattice<T> const &M, int c, std::vector<Tint> const &dets,
               std::vector<Tint> const &group_primes, std::ostream &os) {
  int dim = M.gram.rows();
  Tint det_M = UniversalScalarConversion<Tint, T>(DeterminantMat(M.gram));
  auto split = [&](Tint x) -> std::pair<Tint, std::map<Tint, int>> {
    std::map<Tint, int> val;
    for (auto const &p : group_primes) {
      int v = 0;
      while (ResInt(x, p) == 0) {
        x /= p;
        v++;
      }
      val[p] = v;
    }
    return {x, val};
  };
  Tint det_M_out = split(det_M).first;
  // the bounds at the primes of G, and the determinants of X outside them
  std::map<Tint, int> max_val;
  std::set<Tint> dets_X_out;
  for (auto const &D : dets) {
    auto [D_out, val] = split(D);
    for (auto const &[p, v] : val) {
      max_val[p] = std::max(max_val[p], v);
    }
    Tint M_part = MyPow<Tint>(det_M_out, c);
    if (ResInt(D_out, M_part) != 0) {
      continue;
    }
    Tint rest = D_out / M_part;
    // rest = det(X)^dim
    Tint root(1);
    bool ok = true;
    if (rest > 1) {
      for (auto const &[q, e] : FactorsIntMap(rest)) {
        if (static_cast<int>(e) % dim != 0) {
          ok = false;
          break;
        }
        root *= MyPow<Tint>(q, static_cast<int>(e) / dim);
      }
    }
    if (ok) {
      dets_X_out.insert(root);
    }
  }
  auto within = [&](T const &det) -> bool {
    for (auto const &[p, v] :
         split(UniversalScalarConversion<Tint, T>(det)).second) {
      if (v > max_val[p] + 2) {
        return false;
      }
    }
    return true;
  };
  LatticeMethodChoice choice = DefaultPairMethods().canonical;
  std::set<std::vector<MyMatrix<T>>> known;
  std::vector<GroupLattice<T>> queue, res;
  // the starts and the up steps lower the determinant: not bounded
  auto insert = [&](GroupLattice<T> const &L, bool bounded) -> void {
    if (!IsIntegralMatrix(L.gram) ||
        (bounded && !within(DeterminantMat(L.gram)))) {
      return;
    }
    std::vector<MyMatrix<T>> ListP;
    for (auto const &g : L.gens) {
      ListP.push_back(g.transpose());
    }
    MyMatrix<Tint> B =
        PairCanonicalBasis<T, Tint, Tgroup>(L.gram, ListP, choice, os);
    GroupLattice<T> Lc =
        GroupLatticeInBasis(L, UniversalMatrixConversion<T, Tint>(B));
    std::vector<MyMatrix<T>> key{Lc.gram};
    for (auto const &g : Lc.gens) {
      key.push_back(g);
    }
    if (known.insert(key).second) {
      queue.push_back(Lc);
    }
  };
  // the starts
  std::vector<Tint> extra{Tint(1)};
  for (auto const &p : group_primes) {
    std::vector<Tint> next;
    for (auto const &x : extra) {
      Tint pe(1);
      for (int e = 0; e <= 3; e++) {
        next.push_back(x * pe);
        pe *= p;
      }
    }
    extra = next;
  }
  // the scalings of the form by 1/s, s squarefree over the primes of G:
  // the rational classes form_M (x) q with q not integral
  std::vector<std::vector<Tint>> scales{{}};
  for (auto const &p : group_primes) {
    size_t n_sc = scales.size();
    for (size_t i = 0; i < n_sc; i++) {
      std::vector<Tint> sc = scales[i];
      sc.push_back(p);
      scales.push_back(sc);
    }
  }
  // one X per local symbol outside the primes of G and rational class at
  // them (the steps make the rest), the one of least determinant
  std::map<std::vector<int64_t>, std::pair<Tint, GenusSymbol>> starts_X;
  for (auto const &d_out : dets_X_out) {
    for (auto const &e : extra) {
      for (bool even : {true, false}) {
        for (auto const &gs : EnumerateGenusSymbols<Tint>(c, d_out * e, even)) {
          std::vector<int64_t> key =
              StartKey<T, Tint>(gs, d_out * e, group_primes, os);
          auto iter = starts_X.find(key);
          if (iter == starts_X.end() || d_out * e < iter->second.first) {
            starts_X[key] = {d_out * e, gs};
          }
        }
      }
    }
  }
  for (auto const &[key, val] : starts_X) {
    MyMatrix<T> X = GenusSymbolRepresentative<T, Tint>(val.second, os);
    for (auto const &sc : scales) {
      insert(ScaledIntegralPart(TensorWithLattice(M, X), sc), false);
    }
  }
  size_t n_start = queue.size();
  // the steps at the primes of G
  for (size_t pos = 0; pos < queue.size(); pos++) {
    GroupLattice<T> L = queue[pos];
    for (auto const &p : group_primes) {
      T_small_prime p_s = UniversalScalarConversion<T_small_prime, Tint>(p);
      size_t n_down = 0;
      std::vector<GroupLattice<T>> neigh =
          FlipNeighbors(L, p_s, n_down, true);
      for (size_t i = 0; i < neigh.size(); i++) {
        insert(neigh[i], i < n_down);
      }
    }
  }
  for (auto const &L : queue) {
    Tint det_L = UniversalScalarConversion<Tint, T>(DeterminantMat(L.gram));
    if (IsEvenIntegralGram(L.gram) &&
        std::binary_search(dets.begin(), dets.end(), det_L)) {
      res.push_back(L);
    }
  }
  os << "ISOM_PIECES: " << n_start << " starts, " << queue.size()
     << " lattices, " << res.size() << " pieces of admissible determinant\n";
  return res;
}

/*
  The certified search, for rho of Schur index 1 (ListGens(Z[G]) of full
  rank n^2 in End(M) = M_n(Z)).

  Let Lambda be the image of Z_p[G] in End(V_rho) and Lambda' = End(M_p) =
  M_n(Z_p), a maximal order containing it, p^a the exponent of Lambda' /
  Lambda (ConductorExponent). For a G-lattice L, N = Lambda' L is a
  Lambda'-lattice and p^a N subset Lambda L = L subset N. By Morita, N = M
  (x) X with the form b_M (x) q, and as p^a N is in L, integral, q has
  values in p^{-2a - v} (v the valuation of the content of b_M): N is an M
  (x) X with its form divided by p^e, X integral, 0 <= e <= 2a + v, and
  v_p det N >= v_p det L - 2 a rank L. L is reached from N by a chain of
  maximal G-sublattices, whose determinants grow from det N to det L. So
  every piece of determinant D is found by the steps down from the
  starts M (x) X / prod p^e_p, X over the genera (odd and even) of rank c
  whose determinant puts that of the start between v_p(D) - 2 a_p rank and
  v_p(D) at each prime p of G (and right outside them), cutting the lattices
  whose determinant goes beyond the largest admissible valuation: a finite
  and complete search, up to the completeness of the genus symbols and the
  Morita equivalence. One pair per class, by the canonical form (of the
  form scaled to be integral).
 */

// v_p of the exponent of M_n(Z) / span(g, g in G), or nullopt when the
// span is not of full rank n^2.
template <typename T, typename Tint>
std::optional<int> ConductorExponent(GroupLattice<T> const &M, Tint const &p) {
  int n = M.gram.rows();
  std::vector<MyMatrix<T>> ListP;
  for (auto const &g : M.gens) {
    ListP.push_back(g.transpose());
  }
  std::vector<MyMatrix<T>> elts =
      GroupElementsAndInverses(ListP, 100000).first;
  MyMatrix<T> Span(static_cast<int>(elts.size()), n * n);
  for (size_t k = 0; k < elts.size(); k++) {
    for (int i = 0; i < n; i++) {
      for (int j = 0; j < n; j++) {
        Span(static_cast<int>(k), i * n + j) = elts[k](i, j);
      }
    }
  }
  MyMatrix<T> B = GetZbasis(Span);
  if (B.rows() != n * n) {
    return {};
  }
  MyMatrix<T> Binv = Inverse(B);
  Tint e(1);
  for (int i = 0; i < n * n; i++) {
    for (int j = 0; j < n * n; j++) {
      e = LCMpair(e, UniversalScalarConversion<Tint, T>(GetDenominator(Binv(i, j))));
    }
  }
  int a = 0;
  while (ResInt(e, p) == 0) {
    e /= p;
    a++;
  }
  return a;
}

// v_p of a nonzero rational.
template <typename T, typename Tint> int RationalValuation(T const &x, Tint const &p) {
  T den = GetDenominator(x);
  T num = x * den;
  Tint num_i = UniversalScalarConversion<Tint, T>(T_abs(num));
  Tint den_i = UniversalScalarConversion<Tint, T>(den);
  int v = 0;
  while (ResInt(num_i, p) == 0) {
    num_i /= p;
    v++;
  }
  while (ResInt(den_i, p) == 0) {
    den_i /= p;
    v--;
  }
  return v;
}

template <typename T, typename Tint, typename Tgroup>
std::optional<std::vector<GroupLattice<T>>>
IsotypicPiecesCertified(GroupLattice<T> const &M, int c,
                        std::vector<Tint> const &dets,
                        std::vector<Tint> const &group_primes,
                        std::ostream &os) {
  int n = M.gram.rows();
  int rank = n * c;
  // per prime of G: a_p, the content and det valuations of M, the range
  std::vector<int> a, v_cont, v_detM, hi, lo;
  for (auto const &p : group_primes) {
    std::optional<int> opt = ConductorExponent<T, Tint>(M, p);
    if (!opt) {
      return {};
    }
    a.push_back(*opt);
    int vc = std::numeric_limits<int>::max();
    for (int i = 0; i < n; i++) {
      for (int j = 0; j < n; j++) {
        if (M.gram(i, j) != 0) {
          vc = std::min(vc, RationalValuation<T, Tint>(M.gram(i, j), p));
        }
      }
    }
    v_cont.push_back(vc);
    v_detM.push_back(RationalValuation<T, Tint>(DeterminantMat(M.gram), p));
    int h = 0, l = std::numeric_limits<int>::max();
    for (auto const &D : dets) {
      int vD = RationalValuation<T, Tint>(UniversalScalarConversion<T, Tint>(D), p);
      h = std::max(h, vD);
      l = std::min(l, vD);
    }
    hi.push_back(h);
    lo.push_back(l - 2 * a.back() * rank);
  }
  // the determinants of X outside the primes of G
  // M is integral: its determinant is an integer
  Tint det_M = UniversalScalarConversion<Tint, T>(DeterminantMat(M.gram));
  auto out_part = [&](Tint x) -> Tint {
    for (auto const &p : group_primes) {
      while (ResInt(x, p) == 0) {
        x /= p;
      }
    }
    return x;
  };
  Tint det_M_out = out_part(det_M);
  std::set<Tint> dets_X_out;
  for (auto const &D : dets) {
    Tint D_out = out_part(D);
    Tint M_part = MyPow<Tint>(det_M_out, c);
    if (ResInt(D_out, M_part) != 0) {
      continue;
    }
    Tint rest = D_out / M_part;
    Tint root(1);
    bool ok = true;
    if (rest > 1) {
      for (auto const &[q, e] : FactorsIntMap(rest)) {
        if (static_cast<int>(e) % n != 0) {
          ok = false;
          break;
        }
        root *= MyPow<Tint>(q, static_cast<int>(e) / n);
      }
    }
    if (ok) {
      dets_X_out.insert(root);
    }
  }
  LatticeMethodChoice choice = DefaultPairMethods().canonical;
  std::set<std::vector<MyMatrix<T>>> known;
  std::vector<GroupLattice<T>> queue, res;
  auto insert = [&](GroupLattice<T> const &L) -> void {
    T det = DeterminantMat(L.gram);
    for (size_t ip = 0; ip < group_primes.size(); ip++) {
      if (RationalValuation<T, Tint>(det, group_primes[ip]) > hi[ip]) {
        return;
      }
    }
    // the canonical form of the form scaled to be integral
    T den(1);
    for (int i = 0; i < L.gram.rows(); i++) {
      for (int j = 0; j < L.gram.cols(); j++) {
        den = LCMpair(den, GetDenominator(L.gram(i, j)));
      }
    }
    std::vector<MyMatrix<T>> ListP;
    for (auto const &g : L.gens) {
      ListP.push_back(g.transpose());
    }
    MyMatrix<T> A = den * L.gram;
    MyMatrix<Tint> B = PairCanonicalBasis<T, Tint, Tgroup>(A, ListP, choice, os);
    GroupLattice<T> Lc =
        GroupLatticeInBasis(L, UniversalMatrixConversion<T, Tint>(B));
    std::vector<MyMatrix<T>> key{Lc.gram};
    for (auto const &g : Lc.gens) {
      key.push_back(g);
    }
    if (known.insert(key).second) {
      queue.push_back(Lc);
    }
  };
  // the starts: per prime of G, the scaling e and the valuation of det X
  std::vector<std::pair<Tint, Tint>> choices{{Tint(1), Tint(1)}};
  for (size_t ip = 0; ip < group_primes.size(); ip++) {
    Tint const &p = group_primes[ip];
    std::vector<std::pair<Tint, Tint>> next;
    for (int e = 0; e <= 2 * a[ip] + v_cont[ip]; e++) {
      // v(det N) = c v(det M) + n v(det X) - rank e in [lo, hi]
      for (int vx = 0; c * v_detM[ip] + n * vx - rank * e <= hi[ip]; vx++) {
        if (c * v_detM[ip] + n * vx - rank * e < lo[ip]) {
          continue;
        }
        for (auto const &[sc, dx] : choices) {
          next.push_back({sc * MyPow<Tint>(p, e), dx * MyPow<Tint>(p, vx)});
        }
      }
    }
    choices = next;
  }
  size_t n_X = 0;
  for (auto const &d_out : dets_X_out) {
    for (auto const &[sc, dx] : choices) {
      for (bool even : {true, false}) {
        for (auto const &gs : EnumerateGenusSymbols<Tint>(c, d_out * dx, even)) {
          MyMatrix<T> X = GenusSymbolRepresentative<T, Tint>(gs, os);
          GroupLattice<T> N = TensorWithLattice(M, X);
          N.gram /= UniversalScalarConversion<T, Tint>(sc);
          insert(N);
          n_X++;
        }
      }
    }
  }
  size_t n_start = queue.size();
  for (size_t pos = 0; pos < queue.size(); pos++) {
    GroupLattice<T> L = queue[pos];
    for (auto const &p : group_primes) {
      T_small_prime p_s = UniversalScalarConversion<T_small_prime, Tint>(p);
      size_t n_down = 0;
      std::vector<GroupLattice<T>> neigh = FlipNeighbors(L, p_s, n_down, false);
      for (size_t i = 0; i < n_down; i++) {
        insert(neigh[i]);
      }
    }
  }
  for (auto const &L : queue) {
    if (!IsEvenIntegralGram(L.gram)) {
      continue;
    }
    Tint det_L = UniversalScalarConversion<Tint, T>(DeterminantMat(L.gram));
    if (std::binary_search(dets.begin(), dets.end(), det_L)) {
      res.push_back(L);
    }
  }
  os << "ISOM_PIECES: certified, " << n_X << " X, " << n_start << " starts, "
     << queue.size() << " lattices, " << res.size()
     << " pieces of admissible determinant\n";
  return res;
}

/*
  The complete search for any Schur index, through a maximal order.

  B = Q rho(G) in End(V_rho), Lambda = Z rho(G). At a prime p of G,
  MaximalOrderAt finds a maximal order Lambda'_p of B_p containing Lambda:
  if Lambda is not maximal, Lambda + p^{a-1} Lambda' (Lambda' maximal
  containing it, p^a Lambda' in Lambda, a >= 1 minimal) is a ring between
  Lambda and p^{-1} Lambda, so some x in p^{-1} Lambda generates with
  Lambda a ring inside p^{-1} Lambda, larger than Lambda; and none exists
  once Lambda is maximal.

  For a G-lattice L, N = Lambda'_p L satisfies p^a N in L in N, and as p^a
  N in L is integral, the form on N has values in p^{-2a}: N lies in a
  maximal p^{-2a}-integral Lambda'_p-lattice. Those are unique up to the
  isometries of the hermitian space, the centralizer of G (Eichler for the
  split Morita cases, Shimura for the hermitian spaces over a local
  division algebra). So a start whose completion at each prime p of G is
  such a maximal lattice, and whose completions at the other primes are
  those of the pieces (M (x) X, X over the local symbols there, Morita at
  p not dividing |G|), contains a lattice of the genus of every piece,
  reached by the steps down with the determinant cut. For rho of Schur
  index 2 (Albert type III, a definite quaternion algebra with its
  canonical involution) the positive hermitian forms of rank c are all
  isometric, so a single rational class.
 */

// The flattened matrices (rows of length n^2) and back.
template <typename T>
MyMatrix<T> FlattenMatrices(std::vector<MyMatrix<T>> const &mats) {
  int n = mats[0].rows();
  MyMatrix<T> R(static_cast<int>(mats.size()), n * n);
  for (size_t k = 0; k < mats.size(); k++) {
    for (int i = 0; i < n; i++) {
      for (int j = 0; j < n; j++) {
        R(static_cast<int>(k), i * n + j) = mats[k](i, j);
      }
    }
  }
  return R;
}

template <typename T>
std::vector<MyMatrix<T>> UnflattenMatrices(MyMatrix<T> const &R, int n) {
  std::vector<MyMatrix<T>> res;
  for (int k = 0; k < R.rows(); k++) {
    MyMatrix<T> X(n, n);
    for (int i = 0; i < n; i++) {
      for (int j = 0; j < n; j++) {
        X(i, j) = R(k, i * n + j);
      }
    }
    res.push_back(X);
  }
  return res;
}

/*
  A maximal order Lambda'_p of B_p containing Lambda = Z rho(G) (rho on M,
  matrices acting on the columns), as a Z-basis of Lambda + (p-power
  denominators), with a, p^a Lambda' in Lambda; nullopt when p^dim B is
  beyond max_elt.
 */
template <typename T, typename Tint> struct MaximalOrderData {
  std::vector<MyMatrix<T>> basis;
  int a;
};

template <typename T, typename Tint>
std::optional<MaximalOrderData<T, Tint>>
MaximalOrderAt(GroupLattice<T> const &M, Tint const &p, size_t max_elt) {
  int n = M.gram.rows();
  std::vector<MyMatrix<T>> ListP;
  for (auto const &g : M.gens) {
    ListP.push_back(g.transpose());
  }
  std::vector<MyMatrix<T>> elts;
  for (auto const &x : GroupElementsAndInverses(ListP, 100000).first) {
    elts.push_back(x.transpose());
  }
  MyMatrix<T> Lam0 = GetZbasis(FlattenMatrices(elts));
  int dim = Lam0.rows();
  T p_T = UniversalScalarConversion<T, Tint>(p);
  size_t n_elt = 1;
  for (int i = 0; i < dim; i++) {
    n_elt *= UniversalScalarConversion<size_t, Tint>(p);
    if (n_elt > max_elt) {
      return {};
    }
  }
  int p_i = UniversalScalarConversion<int, Tint>(p);
  // the coordinates of rows of B (rational span of Lam0) in the basis Lam0,
  // and the volume of a lattice of B relative to Lam0
  MyMatrix<T> Lam0T = Lam0.transpose();
  MyMatrix<T> Pinv = Lam0T * Inverse(MyMatrix<T>(Lam0 * Lam0T));
  auto coords = [&](MyMatrix<T> const &S) -> MyMatrix<T> { return S * Pinv; };
  auto volume = [&](MyMatrix<T> const &S) -> T {
    return T_abs(DeterminantMat(coords(S)));
  };
  MyMatrix<T> Lam = Lam0;
  // the ring generated by the rows of S and the products, inside
  // p^{-1} Lam, or nullopt
  auto closure = [&](MyMatrix<T> S) -> std::optional<MyMatrix<T>> {
    MyMatrix<T> LamInv = Inverse(coords(Lam));
    while (true) {
      std::vector<MyMatrix<T>> mats = UnflattenMatrices(S, n);
      std::vector<MyMatrix<T>> prods = mats;
      for (auto const &x : mats) {
        for (auto const &y : mats) {
          prods.push_back(x * y);
        }
      }
      MyMatrix<T> S2 = GetZbasis(FlattenMatrices(prods));
      // inside p^{-1} Lam: p S2 Lam^{-1} integral
      MyMatrix<T> C = p_T * coords(S2) * LamInv;
      if (!IsIntegralMatrix(C)) {
        return {};
      }
      if (volume(S2) == volume(S)) {
        return S2;
      }
      S = S2;
    }
  };
  bool changed = true;
  while (changed) {
    changed = false;
    std::vector<int> c(dim, 0);
    for (size_t idx = 1; idx < n_elt && !changed; idx++) {
      size_t x = idx;
      for (int i = 0; i < dim; i++) {
        c[i] = static_cast<int>(x % p_i);
        x /= p_i;
      }
      MyMatrix<T> S(dim + 1, n * n);
      for (int i = 0; i < dim; i++) {
        S.row(i) = Lam.row(i);
      }
      for (int j = 0; j < n * n; j++) {
        T v(0);
        for (int i = 0; i < dim; i++) {
          v += T(c[i]) * Lam(i, j);
        }
        S(dim, j) = v / p_T;
      }
      std::optional<MyMatrix<T>> opt = closure(GetZbasis(S));
      if (opt && volume(*opt) < volume(Lam)) {
        Lam = *opt;
        changed = true;
      }
    }
  }
  // a: p^a Lam in Lam0
  MyMatrix<T> C = coords(Lam);
  int a = 0;
  while (!IsIntegralMatrix(C)) {
    C *= p_T;
    a++;
  }
  return MaximalOrderData<T, Tint>{UnflattenMatrices(Lam, n), a};
}

/*
  The steps down from the starts with the determinant cut (valuations at
  the primes of G at most hi), one pair per class by the canonical form of
  the form scaled to be integral; the even lattices of determinant in dets.
 */
template <typename T, typename Tint, typename Tgroup>
std::vector<GroupLattice<T>>
StepsDownWithCut(std::vector<GroupLattice<T>> const &starts,
                 std::vector<Tint> const &dets,
                 std::vector<Tint> const &group_primes,
                 std::vector<int> const &hi, std::ostream &os) {
  LatticeMethodChoice choice = DefaultPairMethods().canonical;
  std::set<std::vector<MyMatrix<T>>> known;
  std::vector<GroupLattice<T>> queue, res;
  auto insert = [&](GroupLattice<T> const &L) -> void {
    T det = DeterminantMat(L.gram);
    for (size_t ip = 0; ip < group_primes.size(); ip++) {
      if (RationalValuation<T, Tint>(det, group_primes[ip]) > hi[ip]) {
        return;
      }
    }
    T den(1);
    for (int i = 0; i < L.gram.rows(); i++) {
      for (int j = 0; j < L.gram.cols(); j++) {
        den = LCMpair(den, GetDenominator(L.gram(i, j)));
      }
    }
    std::vector<MyMatrix<T>> ListP;
    for (auto const &g : L.gens) {
      ListP.push_back(g.transpose());
    }
    MyMatrix<T> A = den * L.gram;
    MyMatrix<Tint> B = PairCanonicalBasis<T, Tint, Tgroup>(A, ListP, choice, os);
    GroupLattice<T> Lc =
        GroupLatticeInBasis(L, UniversalMatrixConversion<T, Tint>(B));
    std::vector<MyMatrix<T>> key{Lc.gram};
    for (auto const &g : Lc.gens) {
      key.push_back(g);
    }
    if (known.insert(key).second) {
      queue.push_back(Lc);
    }
  };
  for (auto const &N : starts) {
    insert(N);
  }
  size_t n_start = queue.size();
  for (size_t pos = 0; pos < queue.size(); pos++) {
    GroupLattice<T> L = queue[pos];
    for (auto const &p : group_primes) {
      T_small_prime p_s = UniversalScalarConversion<T_small_prime, Tint>(p);
      size_t n_down = 0;
      std::vector<GroupLattice<T>> neigh = FlipNeighbors(L, p_s, n_down, false);
      for (size_t i = 0; i < n_down; i++) {
        insert(neigh[i]);
      }
    }
  }
  for (auto const &L : queue) {
    if (!IsEvenIntegralGram(L.gram)) {
      continue;
    }
    Tint det_L = UniversalScalarConversion<Tint, T>(DeterminantMat(L.gram));
    if (std::binary_search(dets.begin(), dets.end(), det_L)) {
      res.push_back(L);
    }
  }
  os << "ISOM_PIECES: " << n_start << " starts, " << queue.size()
     << " lattices, " << res.size() << " pieces of admissible determinant\n";
  return res;
}

/*
  The pieces by the maximal orders (any Schur index, see the comment
  above): nullopt when a maximal order is beyond the bounds.
 */
template <typename T, typename Tint, typename Tgroup>
std::optional<std::vector<GroupLattice<T>>>
IsotypicPiecesMaximalOrder(GroupLattice<T> const &M, int c,
                           std::vector<Tint> const &dets,
                           std::vector<Tint> const &group_primes,
                           std::ostream &os) {
  int n = M.gram.rows();
  size_t n_gen = M.gens.size();
  std::vector<MaximalOrderData<T, Tint>> orders;
  std::vector<int> hi;
  for (auto const &p : group_primes) {
    std::optional<MaximalOrderData<T, Tint>> opt =
        MaximalOrderAt<T, Tint>(M, p, 1000000);
    if (!opt) {
      return {};
    }
    orders.push_back(*opt);
    int h = 0;
    for (auto const &D : dets) {
      h = std::max(h, RationalValuation<T, Tint>(
                          UniversalScalarConversion<T, Tint>(D), p));
    }
    hi.push_back(h);
    os << "ISOM_PIECES: maximal order at p=" << p << ", a=" << opt->a
       << ", dim " << opt->basis.size() << "\n";
  }
  // the determinants of X outside the primes of G
  auto out_part = [&](Tint x) -> Tint {
    for (auto const &p : group_primes) {
      while (ResInt(x, p) == 0) {
        x /= p;
      }
    }
    return x;
  };
  Tint det_M_out =
      out_part(UniversalScalarConversion<Tint, T>(DeterminantMat(M.gram)));
  std::set<Tint> dets_X_out;
  for (auto const &D : dets) {
    Tint D_out = out_part(D);
    Tint M_part = MyPow<Tint>(det_M_out, c);
    if (ResInt(D_out, M_part) != 0) {
      continue;
    }
    Tint rest = D_out / M_part;
    Tint root(1);
    bool ok = true;
    if (rest > 1) {
      for (auto const &[q, e] : FactorsIntMap(rest)) {
        if (static_cast<int>(e) % n != 0) {
          ok = false;
          break;
        }
        root *= MyPow<Tint>(q, static_cast<int>(e) / n);
      }
    }
    if (ok) {
      dets_X_out.insert(root);
    }
  }
  // one X per local symbol outside the primes of G
  std::vector<Tint> extra{Tint(1)};
  for (auto const &p : group_primes) {
    std::vector<Tint> next;
    for (auto const &x : extra) {
      Tint pe(1);
      for (int e = 0; e <= 3; e++) {
        next.push_back(x * pe);
        pe *= p;
      }
    }
    extra = next;
  }
  std::map<std::vector<int64_t>, std::pair<Tint, GenusSymbol>> starts_X;
  for (auto const &d_out : dets_X_out) {
    for (auto const &e : extra) {
      for (bool even : {true, false}) {
        for (auto const &gs : EnumerateGenusSymbols<Tint>(c, d_out * e, even)) {
          std::vector<int64_t> key = StartKey<T, Tint>(gs, d_out * e,
                                                       group_primes, os);
          // the part outside the primes of G only
          size_t cut = 0;
          int n_sep = 0;
          while (cut < key.size() && n_sep < 2) {
            if (key[cut] == -1) {
              n_sep++;
            }
            cut++;
          }
          key.resize(cut);
          key[1] = 0;
          auto iter = starts_X.find(key);
          if (iter == starts_X.end() || d_out * e < iter->second.first) {
            starts_X[key] = {d_out * e, gs};
          }
        }
      }
    }
  }
  std::vector<GroupLattice<T>> starts;
  for (auto const &[key, val] : starts_X) {
    MyMatrix<T> X = GenusSymbolRepresentative<T, Tint>(val.second, os);
    GroupLattice<T> L = TensorWithLattice(M, X);
    int nL = L.gram.rows();
    MyMatrix<T> I = IdentityMat<T>(X.rows());
    for (size_t ip = 0; ip < group_primes.size(); ip++) {
      T p_T = UniversalScalarConversion<T, Tint>(group_primes[ip]);
      T_small_prime p_s =
          UniversalScalarConversion<T_small_prime, Tint>(group_primes[ip]);
      // L with the operators of Lambda'_p, then Lambda'_p L
      GroupLattice<T> LL = L;
      for (auto const &lam : orders[ip].basis) {
        LL.gens.push_back(TensorWithLattice(GroupLattice<T>{lam, {}}, I).gram);
      }
      MyMatrix<T> Gen = IdentityMat<T>(nL);
      for (size_t k = n_gen; k < LL.gens.size(); k++) {
        Gen = Concatenate(Gen, MyMatrix<T>(LL.gens[k].transpose()));
      }
      LL = GroupLatticeOfRows(LL, Gen);
      // up to a maximal p^{-2a}-integral Lambda'_p-lattice
      T scale = 1;
      for (int i = 0; i < 2 * orders[ip].a; i++) {
        scale *= p_T;
      }
      LL.gram *= scale;
      while (true) {
        size_t n_down = 0;
        std::vector<GroupLattice<T>> neigh = FlipNeighbors(LL, p_s, n_down, true);
        if (neigh.size() == n_down) {
          break;
        }
        LL = neigh[n_down];
      }
      LL.gram /= scale;
      LL.gens.resize(n_gen);
      L = LL;
    }
    starts.push_back(L);
  }
  os << "ISOM_PIECES: maximal orders, " << starts_X.size() << " X\n";
  return StepsDownWithCut<T, Tint, Tgroup>(starts, dets, group_primes, hi, os);
}

