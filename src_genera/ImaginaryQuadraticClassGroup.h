/*
  The class group of the maximal order of an imaginary quadratic field of
  discriminant D < 0, by the primitive positive definite binary quadratic
  forms (a, b, c), b^2 - 4 a c = D: Gauss reduction, Dirichlet composition
  (Shanks, as in Cohen, A Course in Computational Algebraic Number Theory,
  Algorithm 5.4.7), the identity (1, D mod 2, ...) and the inverse
  (a, -b, c). The form (a, b, c) is the class of the ideal a Z + ((-b +
  sqrt D) / 2) Z.
 */

template <typename Tint> struct BinaryForm {
  Tint a, b, c;
  bool operator<(BinaryForm const &o) const {
    return std::tie(a, b, c) < std::tie(o.a, o.b, o.c);
  }
  bool operator==(BinaryForm const &o) const {
    return a == o.a && b == o.b && c == o.c;
  }
};

// The reduced form equivalent to f (positive definite): |b| <= a <= c, and
// b >= 0 when |b| = a or a = c.
template <typename Tint> BinaryForm<Tint> BinaryFormReduce(BinaryForm<Tint> f) {
  while (true) {
    // b into (-a, a]
    Tint two_a = Tint(2) * f.a;
    if (f.b > f.a || f.b <= -f.a) {
      Tint q = QuoInt(Tint(f.a - f.b), two_a);
      // b + 2 a q in (-a, a]
      Tint bn = f.b + two_a * q;
      f.c = f.c + q * (f.b + f.a * q);
      f.b = bn;
    }
    if (f.a > f.c) {
      std::swap(f.a, f.c);
      f.b = -f.b;
      continue;
    }
    if (f.a == f.c && f.b < 0) {
      f.b = -f.b;
    }
    return f;
  }
}

template <typename Tint>
void BinaryFormExtendedGcd(Tint const &x, Tint const &y, Tint &u, Tint &v,
                           Tint &d) {
  // u x + v y = d = gcd(x, y) >= 0
  Tint r0 = x, r1 = y, u0(1), u1(0), v0(0), v1(1);
  while (r1 != 0) {
    Tint q = QuoInt(r0, r1);
    Tint r2 = r0 - q * r1;
    r0 = r1;
    r1 = r2;
    Tint u2 = u0 - q * u1;
    u0 = u1;
    u1 = u2;
    Tint v2 = v0 - q * v1;
    v0 = v1;
    v1 = v2;
  }
  if (r0 < 0) {
    r0 = -r0;
    u0 = -u0;
    v0 = -v0;
  }
  u = u0;
  v = v0;
  d = r0;
}

// The composition of two forms of discriminant D, reduced.
template <typename Tint>
BinaryForm<Tint> BinaryFormCompose(BinaryForm<Tint> f1, BinaryForm<Tint> f2,
                                   Tint const &D) {
  if (f1.a > f2.a) {
    std::swap(f1, f2);
  }
  Tint s = (f1.b + f2.b) / Tint(2);
  Tint n = f2.b - s;
  Tint u, v, d, y1;
  if (ResInt(f2.a, f1.a) == 0) {
    y1 = Tint(0);
    d = f1.a;
  } else {
    BinaryFormExtendedGcd(f2.a, f1.a, u, v, d);
    y1 = u;
  }
  Tint x2, y2, d1;
  if (ResInt(s, d) == 0) {
    y2 = Tint(-1);
    x2 = Tint(0);
    d1 = d;
  } else {
    BinaryFormExtendedGcd(s, d, x2, y2, d1);
    y2 = -y2;
  }
  Tint v1 = f1.a / d1;
  Tint v2 = f2.a / d1;
  Tint r = ResInt(Tint(y1 * y2 * n - x2 * f2.c), v1);
  if (r < 0) {
    r += v1;
  }
  BinaryForm<Tint> f3;
  f3.b = f2.b + Tint(2) * v2 * r;
  f3.a = v1 * v2;
  f3.c = (f3.b * f3.b - D) / (Tint(4) * f3.a);
#ifdef SANITY_CHECK_IMAGINARY_QUADRATIC_CLASS_GROUP
  if (f3.b * f3.b - Tint(4) * f3.a * f3.c != D) {
    std::cerr << "IQCG: the composition does not have the discriminant\n";
    throw TerminalException{1};
  }
#endif
  return BinaryFormReduce(f3);
}

template <typename Tint> BinaryForm<Tint> BinaryFormIdentity(Tint const &D) {
  BinaryForm<Tint> f;
  f.a = Tint(1);
  f.b = (ResInt(D, Tint(2)) == 0) ? Tint(0) : Tint(1);
  f.c = (f.b * f.b - D) / Tint(4);
  return f;
}

template <typename Tint> BinaryForm<Tint> BinaryFormInverse(BinaryForm<Tint> const &f) {
  return BinaryFormReduce(BinaryForm<Tint>{f.a, -f.b, f.c});
}

// The reduced primitive forms of discriminant D: the class group.
template <typename Tint>
std::vector<BinaryForm<Tint>> BinaryFormAllReduced(Tint const &D) {
  std::vector<BinaryForm<Tint>> res;
  Tint absD = -D;
  for (Tint a(1); Tint(3) * a * a <= absD; a += 1) {
    for (Tint b = -a + 1; b <= a; b += 1) {
      if (ResInt(Tint(b * b - D), Tint(4 * a)) != 0) {
        continue;
      }
      Tint c = (b * b - D) / (Tint(4) * a);
      if (c < a || (c == a && b < 0)) {
        continue;
      }
      if (GcdPair(GcdPair(a, b), c) != 1) {
        continue;
      }
      res.push_back(BinaryForm<Tint>{a, b, c});
    }
  }
  return res;
}

/*
  A quotient C / C0 of the class group, C0 the subgroup generated by gens:
  the elements of C0, and the canonical representative of a coset (its
  smallest form).
 */
template <typename Tint> struct ClassGroupQuotient {
  Tint D;
  std::vector<BinaryForm<Tint>> sub;
  size_t order_group;
  size_t order_quotient() const { return order_group / sub.size(); }
  BinaryForm<Tint> canonical(BinaryForm<Tint> const &f) const {
    BinaryForm<Tint> best = BinaryFormCompose(f, sub[0], D);
    for (auto const &g : sub) {
      BinaryForm<Tint> h = BinaryFormCompose(f, g, D);
      if (h < best) {
        best = h;
      }
    }
    return best;
  }
};

template <typename Tint>
ClassGroupQuotient<Tint> GetClassGroupQuotient(Tint const &D,
                                               std::vector<BinaryForm<Tint>> const &gens) {
  ClassGroupQuotient<Tint> res;
  res.D = D;
  res.order_group = BinaryFormAllReduced(D).size();
  std::set<BinaryForm<Tint>> S{BinaryFormIdentity(D)};
  std::vector<BinaryForm<Tint>> todo(S.begin(), S.end());
  while (!todo.empty()) {
    BinaryForm<Tint> f = todo.back();
    todo.pop_back();
    for (auto const &g : gens) {
      BinaryForm<Tint> h = BinaryFormCompose(f, g, D);
      if (S.insert(h).second) {
        todo.push_back(h);
      }
    }
  }
  res.sub.assign(S.begin(), S.end());
  return res;
}

