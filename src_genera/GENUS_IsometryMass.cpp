// One matrix, or a number followed by the matrices: told apart by the
// number of integers on the first line.
template <typename T>
std::vector<MyMatrix<T>> ReadGeneratorsFile(std::string const &file) {
  std::ifstream is(file);
  if (!is.good()) {
    std::cerr << "GENUS_IsometryMass: cannot read " << file << "\n";
    throw TerminalException{1};
  }
  std::string line;
  std::getline(is, line);
  std::istringstream ls(line);
  int n_tok = 0;
  std::string tok;
  while (ls >> tok) {
    n_tok++;
  }
  if (n_tok == 2) {
    return {ReadMatrixFile<T>(file)};
  }
  return ReadListMatrixFile<T>(file);
}

template <typename T> std::vector<int64_t> FlattenMatrix(MyMatrix<T> const &M) {
  std::vector<int64_t> v;
  for (int i = 0; i < M.rows(); i++) {
    for (int j = 0; j < M.cols(); j++) {
      v.push_back(UniversalScalarConversion<int64_t, T>(M(i, j)));
    }
  }
  return v;
}

template <typename T, typename Tint>
std::vector<int> KernelRanks(MyMatrix<T> const &P, int m) {
  std::vector<int> res;
  for (int d = 1; d <= m; d++) {
    if (m % d != 0) {
      continue;
    }
    MyMatrix<T> Phi = EvaluatePolynomialMatrix(CyclotomicPolynomial(d), P);
    res.push_back(P.rows() - RankMat(Phi));
  }
  return res;
}

template <typename T>
void AddCheckResult(std::map<std::string, std::pair<int64_t, T>> &groups,
                    IsometryMassResult<T> const &res) {
  std::ostringstream key;
  key << "mass=" << *res.mass;
  for (auto const &cm : res.component_masses) {
    key << " [d=" << cm.d << " rank=" << cm.rank << " det=" << cm.det
        << " mass=" << *cm.mass << "]";
  }
  key << " glue=" << res.glue_factor;
  if (res.image_assumed) {
    key << " image_assumed";
  }
  auto iter = groups.find(key.str());
  if (iter == groups.end()) {
    groups[key.str()] = {1, *res.mass};
  } else {
    iter->second.first++;
  }
}

template <typename T>
void WriteCheckGroups(
    std::ostream &os,
    std::map<std::string, std::pair<int64_t, T>> const &groups,
    T const &order_T) {
  bool all_integral = true;
  for (auto const &kv : groups) {
    T ratio =
        UniversalScalarConversion<T, int64_t>(kv.second.first) / (order_T * kv.second.second);
    os << "count=" << kv.second.first << " ratio=" << ratio << " " << kv.first
       << "\n";
    if (!IsInteger(ratio)) {
      all_integral = false;
    }
  }
  os << "check: "
     << (all_integral ? "every ratio is an integer"
                      : "FAILED, a ratio is not an integer")
     << "\n";
}

/*
  The elements of O(L), acting on the rows, for the brute-force checks.
 */
template <typename T, typename Tint, typename Tgroup>
std::vector<MyMatrix<T>> OrthogonalGroupElements(MyMatrix<T> const &A,
                                                 T &order_T) {
  int n = A.rows();
  // the generators satisfy g A g^T = A (LatticeAutomorphismGroup)
  std::vector<MyMatrix<T>> ListMat{A};
  IntAutomorphismGroup<Tint, Tgroup> aut =
      LatticeAutomorphismGroup<T, Tint, Tgroup>(
          ListMat,
          LatticeMethodChoice(LatticeStabCanIsomMethod::Graph,
                              InvariantFamilyKind::IteratedShortest),
          std::cerr);
  std::vector<MyMatrix<T>> gens =
      UniversalStdVectorMatrixConversion<T, Tint>(aut.ListGen);
  size_t max_elt = 2000000;
  std::set<std::vector<int64_t>> seen;
  std::vector<MyMatrix<T>> elts{IdentityMat<T>(n)};
  seen.insert(FlattenMatrix(elts[0]));
  for (size_t pos = 0; pos < elts.size(); pos++) {
    for (auto const &h : gens) {
      MyMatrix<T> x = elts[pos] * h;
      if (seen.insert(FlattenMatrix(x)).second) {
        elts.push_back(x);
        if (elts.size() > max_elt) {
          std::cerr << "GENUS_IsometryMass: O(L) is too large for the check\n";
          throw TerminalException{1};
        }
      }
    }
  }
  // compared in the integers of the group, which need not convert to T
  using TintGroup = typename Tgroup::Tint;
  if (UniversalScalarConversion<TintGroup, int64_t>(
          static_cast<int64_t>(elts.size())) != aut.order) {
    std::cerr << "GENUS_IsometryMass: listed " << elts.size()
              << " elements but |O(L)| = " << aut.order << "\n";
    throw TerminalException{1};
  }
  order_T = UniversalScalarConversion<T, int64_t>(static_cast<int64_t>(elts.size()));
  return elts;
}

/*
  The check over the conjugates: every tau in O(L) of the order and the
  kernel ranks of g, the mass of the genus of (L, <tau>).
 */
template <typename T, typename Tint, typename Tgroup>
void ProcessCheckConjugates(MyMatrix<T> const &A, MyMatrix<T> const &g,
                            IsometryMassBounds const &bounds,
                            std::ostream &os) {
  MyMatrix<T> P0 = g.transpose();
  int m = IsometryOrder(P0);
  std::vector<int> ranks0 = KernelRanks<T, Tint>(P0, m);
  T order_T;
  std::vector<MyMatrix<T>> elts =
      OrthogonalGroupElements<T, Tint, Tgroup>(A, order_T);
  std::map<std::string, std::pair<int64_t, T>> groups;
  for (auto const &P : elts) {
    if (IsometryOrder(P) != m || KernelRanks<T, Tint>(P, m) != ranks0) {
      continue;
    }
    IsometryMassResult<T> res = GroupGenusMass<T, Tint>(
        A, {MyMatrix<T>(P.transpose())}, bounds, std::cerr);
    if (!res.mass) {
      std::cerr << "GENUS_IsometryMass: the check needs the masses of all "
                   "the components\n";
      throw TerminalException{1};
    }
    AddCheckResult(groups, res);
  }
  os << "|O(L)| = " << elts.size() << "\n";
  WriteCheckGroups(os, groups, order_T);
}

/*
  The check over the centralizer: the groups <g, tau>, tau running over
  C_{O(L)}(g). When the genus of L has one class, the pairs (g', tau') of a
  genus X of pairs of commuting isometries with g' conjugate to g number
  |g^{O(L)}| times those with g' = g, so sum_{tau} 1 / |C_{O(L)}(g)| over
  X is mass(X), and the counts of every group divided by |C(g)| mass are
  integers.
 */
template <typename T, typename Tint, typename Tgroup>
void ProcessCheckCentralizer(MyMatrix<T> const &A, MyMatrix<T> const &g,
                             IsometryMassBounds const &bounds,
                             std::ostream &os) {
  MyMatrix<T> P0 = g.transpose();
  T order_T;
  std::vector<MyMatrix<T>> elts =
      OrthogonalGroupElements<T, Tint, Tgroup>(A, order_T);
  std::map<std::string, std::pair<int64_t, T>> groups;
  int64_t n_cent = 0;
  for (auto const &P : elts) {
    if (P * P0 != P0 * P) {
      continue;
    }
    n_cent++;
    IsometryMassResult<T> res = GroupGenusMass<T, Tint>(
        A, {g, MyMatrix<T>(P.transpose())}, bounds, std::cerr);
    if (!res.mass) {
      std::cerr << "GENUS_IsometryMass: a component has no mass\n";
      throw TerminalException{1};
    }
    AddCheckResult(groups, res);
  }
  os << "|O(L)| = " << elts.size() << " |C(g)| = " << n_cent << "\n";
  WriteCheckGroups(os, groups, UniversalScalarConversion<T, int64_t>(n_cent));
}

template <typename T, typename Tint, typename Tgroup>
void ProcessIsometryMass(FullNamelist const &eFull) {
  SingleBlock const &BlockDATA = eFull.get_block("DATA");
  SingleBlock const &BlockMETHOD = eFull.get_block("METHOD");
  SingleBlock const &BlockSYSTEM = eFull.get_block("SYSTEM");
  std::string GramFile = BlockDATA.get_string("GramFile");
  std::string GeneratorsFile = BlockDATA.get_string("GeneratorsFile");
  if (GramFile == "unset" || GeneratorsFile == "unset") {
    std::cerr << "GENUS_IsometryMass: GramFile and GeneratorsFile are "
                 "needed\n";
    throw TerminalException{1};
  }
  std::string mode = BlockMETHOD.get_string("mode");
  std::string check_kind = BlockMETHOD.get_string("check_kind");
  IsometryMassBounds bounds;
  bounds.lvalue = ParseQuadLValueMethod(BlockMETHOD.get_string("lvalue"));
  MyMatrix<T> A = ReadMatrixFile<T>(GramFile);
  std::vector<MyMatrix<T>> gens = ReadGeneratorsFile<T>(GeneratorsFile);
  auto f = [&](std::ostream &os) -> void {
    if (mode == "mass") {
      WriteIsometryMassResult(
          os, GroupGenusMass<T, Tint>(A, gens, bounds, std::cerr));
      return;
    }
    if (mode != "check") {
      std::cerr << "GENUS_IsometryMass: the mode must be mass or check\n";
      throw TerminalException{1};
    }
    if (gens.size() != 1) {
      std::cerr << "GENUS_IsometryMass: the check takes one generator g\n";
      throw TerminalException{1};
    }
    if (check_kind == "conjugates") {
      ProcessCheckConjugates<T, Tint, Tgroup>(A, gens[0], bounds, os);
    } else if (check_kind == "centralizer") {
      ProcessCheckCentralizer<T, Tint, Tgroup>(A, gens[0], bounds, os);
    } else {
      std::cerr << "GENUS_IsometryMass: check_kind must be conjugates or "
                   "centralizer\n";
      throw TerminalException{1};
    }
  };
  FILE_PrintStderrStdoutFile(BlockSYSTEM.get_string("OutFile"), f);
}

int main(int argc, char *argv[]) {
  maybe_install_gmp_pool();
  HumanTime time;
  try {
    // the group orders are in TintGroup, whatever the arithmetic of the
    // coordinates T / Tint chosen below
    using Tidx = uint32_t;
    using Telt = permutalib::SingleSidedPerm<Tidx>;
    using TintGroup = mpz_class;
    using Tgroup = permutalib::Group<Telt, TintGroup>;
    FullNamelist eFull = NAMELIST_GetStandard_GENUS_ISOMETRY_MASS();
    ArithmeticDispatch dispatch;
    add_rational_integer_arithmetics_by_library(
        dispatch, [&]<typename T, typename Tint>() -> void {
          ProcessIsometryMass<T, Tint, Tgroup>(eFull);
        });
    if (argc != 2) {
      std::cerr << "Number of argument is = " << argc << "\n";
      std::cerr << "This program is used as\n";
      std::cerr << "GENUS_IsometryMass [file.nml]\n";
      std::cerr << "With file.nml a namelist file\n";
      eFull.NAMELIST_WriteNamelistFile(std::cerr, true);
      std::cerr << "arithmetic values:\n";
      dispatch.print_descriptions(std::cerr);
      return -1;
    }
    NAMELIST_ReadNamelistFile(argv[1], eFull);
    dispatch.run(GetNamelistStringEntry(eFull, "DATA", "arithmetic"));
    std::cerr << "Normal termination of GENUS_IsometryMass\n";
  } catch (TerminalException const &e) {
    std::cerr << "Error in GENUS_IsometryMass\n";
    exit(e.eVal);
  }
  runtime(time);
}
