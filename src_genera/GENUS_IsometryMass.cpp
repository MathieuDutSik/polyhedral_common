/*
  The mass of the genus of a pair (L, G), L an even positive definite
  lattice and G the finite group generated by isometries of L
  (GroupGenusMass, Mass.h), or its brute-force check on small lattices.

    GENUS_IsometryMass file.nml

  (the namelist and its documentation are printed when run without
  argument). The check lists the elements of O(L) and, for each element
  tau of the kind chosen, computes the mass of the genus of the group it
  gives, grouping them by the mass and the genera of the components. When
  the genus of L has a single class, the pairs over L are all the pairs of
  these genera and sum_{tau in a genus of pairs X} 1 / |O(L)| = mass(X), so
  for every group the count divided by |O(L)| mass is the number of genera
  of pairs in it: an integer. The masses of single components are computed
  by GENUS_ComponentMass.
 */

