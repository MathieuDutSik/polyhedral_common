/*
  Maximal orders and maximal lattices.

  An order Lambda of a semisimple algebra B_p over Q_p is in a maximal
  order Lambda'_p (MaximalOrders.h; MaximalOrderAt for Lambda = Z rho(G));
  a Lambda-lattice L gives the Lambda'_p-lattice N = Lambda'_p L, with p^a
  N in L in N.

  The uniqueness used for the pieces. In a hermitian space V over a local
  field (quadratic: E = K; hermitian: E / K quadratic; quaternionic: E a
  quaternion algebra over K, with its canonical involution), a lattice L
  is a-maximal (a a fractional ideal of K) if its norm n(L), the ideal
  generated by the h(x, x), is in a, and no larger lattice has this
  property; the a-maximal lattices of V are isometric (Kirschmer,
  Definite quadratic and hermitian forms with small class number,
  Habilitation, Lemma 3.5.2, from O'Meara 91:2 and Shimura, Arithmetic of
  unitary groups, Ann. Math. 79 (1964), Proposition 4.13). This is about
  the norm, not the scale s(L) (the ideal of the h(x, y)): the maximal
  lattices for a bound on the scale need not be isometric. Over Q_2, the
  odd <1, 7> and the even hyperbolic plane are both unimodular, so both
  maximal with s(L) in Z_2, in the same space. The scale and the norm
  determine each other except at the bad primes (p above 2 and E = K, or
  E / K ramified), so the maximal Lambda'_p-lattices for an integral form
  (FlipNeighbors up to the end, UpToMaximalLattice) are unique up to the
  isometries commuting with G at the other primes only: by Morita
  equivalence over the maximal order, with E the local division algebra
  of Lambda'_p and K its centre (MaximalLatticesUniqueAt).
 */

// The commutant End_G(M) cap M_n(Z), on the columns.
template <typename T, typename Tint>
std::vector<MyMatrix<T>> IntegralCommutantBasis(GroupLattice<T> const &M) {
  int n = M.gram.rows();
  int N = n * n;
  std::vector<std::vector<T>> eqs;
  for (auto const &g : M.gens) {
    for (int r = 0; r < n; r++) {
      for (int c = 0; c < n; c++) {
        std::vector<T> e(N, T(0));
        for (int t = 0; t < n; t++) {
          e[r * n + t] += g(t, c);
          e[t * n + c] -= g(r, t);
        }
        eqs.push_back(e);
      }
    }
  }
  MyMatrix<T> Eq(static_cast<int>(eqs.size()), N);
  for (size_t i = 0; i < eqs.size(); i++) {
    for (int j = 0; j < N; j++) {
      Eq(static_cast<int>(i), j) = eqs[i][j];
    }
  }
  return UnflattenMatrices(IntegralSpaceSaturation(NullspaceTrMat(Eq)), n);
}

template <typename T, typename Tint>
std::vector<MyMatrix<T>> SelfAdjointCommutantBasis(GroupLattice<T> const &M) {
  int n = M.gram.rows();
  int N = n * n;
  std::vector<std::vector<T>> eqs;
  // X g - g X = 0 for the gens, X^T A - A X = 0
  for (auto const &g : M.gens) {
    for (int r = 0; r < n; r++) {
      for (int c = 0; c < n; c++) {
        std::vector<T> e(N, T(0));
        for (int t = 0; t < n; t++) {
          e[r * n + t] += g(t, c);
          e[t * n + c] -= g(r, t);
        }
        eqs.push_back(e);
      }
    }
  }
  MyMatrix<T> const &A = M.gram;
  for (int r = 0; r < n; r++) {
    for (int c = 0; c < n; c++) {
      std::vector<T> e(N, T(0));
      for (int t = 0; t < n; t++) {
        e[t * n + r] += A(t, c);
        e[t * n + c] -= A(r, t);
      }
      eqs.push_back(e);
    }
  }
  MyMatrix<T> Eq(static_cast<int>(eqs.size()), N);
  for (size_t i = 0; i < eqs.size(); i++) {
    for (int j = 0; j < N; j++) {
      Eq(static_cast<int>(i), j) = eqs[i][j];
    }
  }
  MyMatrix<T> Sol = NullspaceTrMat(Eq);
  MyMatrix<T> SolZ = IntegralSpaceSaturation(Sol);
  return UnflattenMatrices(SolZ, n);
}

// The same for the order Z rho(G) spanned by the elements of G on M.
template <typename T, typename Tint>
std::optional<MaximalOrderData<T, Tint>>
MaximalOrderAt(GroupLattice<T> const &M, Tint const &p, size_t max_elt) {
  std::vector<MyMatrix<T>> ListP;
  for (auto const &g : M.gens) {
    ListP.push_back(g.transpose());
  }
  std::vector<MyMatrix<T>> elts;
  for (auto const &x : GroupElementsAndInverses(ListP).first) {
    elts.push_back(x.transpose());
  }
  return MaximalOrderOfSpanAt<T, Tint>(elts, p, max_elt);
}

/*
  Whether the maximal p^{-2a}-integral Lambda'_p-lattices over the
  G-lattice M (rho on M, of commutant End_G(M)) are unique up to the
  isometries commuting with G, by the norm and the scale determining each
  other at p (see the top): true at odd p, and at p = 2 when End_G(M) is
  not commutative (a quaternion algebra: never a bad prime), or a field K
  with a non trivial involution (the adjoint for the form) such that K /
  K^+ is not ramified above 2, v_2(d_K) = 2 v_2(d_{K^+}). False at p = 2
  for a field K with the trivial involution (E = K) or K / K^+ ramified
  above 2.
 */
template <typename T, typename Tint>
bool MaximalLatticesUniqueAt(GroupLattice<T> const &M, Tint const &p) {
  if (p != 2) {
    return true;
  }
  int n = M.gram.rows();
  std::vector<MyMatrix<T>> C = IntegralCommutantBasis<T, Tint>(M);
  for (auto const &x : C) {
    for (auto const &y : C) {
      if (x * y != y * x) {
        return true;
      }
    }
  }
  int d = static_cast<int>(C.size());
  if (static_cast<int>(SelfAdjointCommutantBasis<T, Tint>(M).size()) == d) {
    return false;
  }
  // O_K (Round 2), and its self-adjoint part O_{K^+}
  std::vector<MyMatrix<T>> OK = CommutativeMaximalOrder<T, Tint>(C, n);
  MyMatrix<T> const &A = M.gram;
  MyMatrix<T> Ainv = Inverse(A);
  T nd = UniversalScalarConversion<T, int>(n / d);
  // Tr_{K/Q}(x y), the trace on M_n divided by n / d
  auto trace_form = [&](std::vector<MyMatrix<T>> const &B) -> MyMatrix<T> {
    int k = B.size();
    MyMatrix<T> F(k, k);
    for (int u = 0; u < k; u++) {
      for (int v = 0; v < k; v++) {
        MyMatrix<T> P = B[u] * B[v];
        T tr(0);
        for (int w = 0; w < n; w++) {
          tr += P(w, w);
        }
        F(u, v) = tr / nd;
      }
    }
    return F;
  };
  std::vector<MyMatrix<T>> diffs;
  for (auto const &x : OK) {
    diffs.push_back(x - Ainv * x.transpose() * A);
  }
  MyMatrix<Tint> Eq = UniversalMatrixConversion<Tint, T>(
      RemoveFractionMatrix(FlattenMatrices(diffs)));
  MyMatrix<Tint> U = NullspaceIntMat(Eq);
  std::vector<MyMatrix<T>> OK0;
  for (int i = 0; i < U.rows(); i++) {
    MyMatrix<T> y = ZeroMatrix<T>(n, n);
    for (int j = 0; j < U.cols(); j++) {
      y += UniversalScalarConversion<T, Tint>(U(i, j)) * OK[j];
    }
    OK0.push_back(y);
  }
  Tint two(2);
  int vK = RationalValuation<T, Tint>(T_abs(DeterminantMat(trace_form(OK))),
                                      two);
  // Tr_{K/Q} = 2 Tr_{K^+/Q} on K^+
  int d0 = static_cast<int>(OK0.size());
  int vK0 = RationalValuation<T, Tint>(
                T_abs(DeterminantMat(trace_form(OK0))), two) -
            d0;
  return vK == 2 * vK0;
}

/*
  L moved up at p to a maximal p^{-2a}-integral Lambda'_p-lattice, L a sum
  of copies of a G-lattice of rank n_M: Lambda'_p L, then the steps up
  while one exists. The operators of Lambda'_p act as lambda (x) Id on the
  coordinates of M (x) Z^c when tensor_layout, Id (x) lambda otherwise. The
  form is scaled by p^{2a} times the part prime to p of its denominator (a
  unit at p) for the steps, and back.
 */
template <typename T, typename Tint>
GroupLattice<T> UpToMaximalLattice(GroupLattice<T> const &L,
                                   MaximalOrderData<T, Tint> const &order,
                                   Tint const &p, int n_M,
                                   bool tensor_layout) {
  int nL = L.gram.rows();
  size_t n_gen = L.gens.size();
  MyMatrix<T> I = IdentityMat<T>(nL / n_M);
  GroupLattice<T> LL = L;
  for (auto const &lam : order.basis) {
    GroupLattice<T> lam_c = tensor_layout
                                ? TensorWithLattice(GroupLattice<T>{lam, {}}, I)
                                : TensorWithLattice(GroupLattice<T>{I, {}}, lam);
    LL.gens.push_back(lam_c.gram);
  }
  MyMatrix<T> Gen = IdentityMat<T>(nL);
  for (size_t k = n_gen; k < LL.gens.size(); k++) {
    Gen = Concatenate(Gen, MyMatrix<T>(LL.gens[k].transpose()));
  }
  LL = GroupLatticeOfRows(LL, Gen);
  T p_T = UniversalScalarConversion<T, Tint>(p);
  T scale(1);
  for (int e = 0; e < 2 * order.a; e++) {
    scale *= p_T;
  }
  T den(1);
  for (int i = 0; i < nL; i++) {
    for (int j = 0; j < nL; j++) {
      den = LCMpair(den, GetDenominator(LL.gram(i, j)));
    }
  }
  Tint den_i = UniversalScalarConversion<Tint, T>(den);
  while (ResInt(den_i, p) == 0) {
    den_i /= p;
  }
  scale *= UniversalScalarConversion<T, Tint>(den_i);
  LL.gram *= scale;
  T_small_prime p_s = UniversalScalarConversion<T_small_prime, Tint>(p);
  while (true) {
    size_t n_down = 0;
    std::vector<GroupLattice<T>> neigh =
        FlipNeighbors(LL, p_s, n_down, false, true);
    if (neigh.empty()) {
      break;
    }
    LL = neigh[0];
  }
  LL.gram /= scale;
  LL.gens.resize(n_gen);
  return LL;
}

