/*
  The classes of the genus of an indefinite Hermitian lattice L of rank
  m >= 2 over an imaginary quadratic field E (K_0 = Q).

  By strong approximation for the special unitary group, the classes of an
  indefinite genus are its special genera (Schiemann; Kirschmer,
  Habilitation, Chapter 5; Hecke.jl's genus_generators, after [Kir19,
  Algorithm 4.7]). They form a group Q = C / C_0 extended, in even rank, by
  an F_2-space W: C is the class group of E and C_0 its subgroup generated
  by the ramified primes (the classes coming from Q being trivial); W is
  V / S, V = F_2^PP for the ramified primes P where every Jordan block of L
  has an even rank and an odd scale (with Hecke.jl's condition at a dyadic
  P), S spanned by the roots of unity u (u - 1 in P^{v_P(D)} or not, D the
  different).

  When W = 0 (always in odd rank), a neighbor of L at a split prime P where
  L is unimodular is in the special genus shifted by the class of P in Q,
  so the representatives are found by a search on Q, as for the indefinite
  lattices over Z (GenusIndefinite.h): the P-neighbors of the lattices
  found, for the split primes P by increasing norm, until every element of
  Q has a lattice. W != 0 needs a cocycle (Hecke.jl) and is not done.
 */

template <typename T, typename Tint> struct HermIndefiniteResult {
  bool done = true;
  std::string reason;
  size_t n_class = 0;
  // the bases of the representatives (rows in the coordinates of the
  // ambient space), the given lattice first
  std::vector<MyMatrix<T>> l_basis;
  std::vector<int64_t> l_prime;
};

/*
  The form of the class of the prime P above ell: a Z-basis of P is ell Z +
  ((-b + sqrt D) / 2) Z, b^2 = D mod 4 ell, with the sign of b such that
  (-b + sqrt D) / 2 is in P. sqrt_D is sqrt(D) in the coordinates of the
  basis of O_E.
 */
template <typename T, typename Tint>
BinaryForm<Tint> HermPrimeForm(HermIdealPrime<Tint> const &P,
                               MyVector<T> const &sqrt_D, Tint const &D) {
  Tint ell = UniversalScalarConversion<Tint, int64_t>(P.ell);
  Tint four_ell = Tint(4) * ell;
  Tint par = ResInt(D, Tint(2));
  if (par < 0) {
    par += 2;
  }
  for (Tint b = par; b < Tint(2) * ell + par; b += 2) {
    if (ResInt(Tint(b * b - D), four_ell) != 0) {
      continue;
    }
    for (int sgn : {1, -1}) {
      Tint bs = Tint(sgn) * b;
      MyVector<T> x = sqrt_D;
      x(0) -= UniversalScalarConversion<T, Tint>(bs);
      x /= T(2);
      if (!IsIntegralVector(x)) {
        continue;
      }
      MyVector<Tint> xi = UniversalVectorConversion<Tint, T>(x);
      if (HermInLattice<T, Tint>(P.ideal, xi)) {
        BinaryForm<Tint> f{ell, bs, (bs * bs - D) / four_ell};
        return BinaryFormReduce(f);
      }
    }
  }
#ifdef SANITY_CHECK_HERMITIAN_INDEFINITE
  std::cerr << "HERMINDEF: no form for the prime " << P.name << "\n";
  throw TerminalException{1};
#endif
  __builtin_unreachable();
}

template <typename T, typename Tint>
HermIndefiniteResult<T, Tint>
HermIndefiniteRepresentatives(CMOrder<T, Tint> const &ord,
                              RealifiedRing<T, Tint> const &ring,
                              MyMatrix<T> const &A, int64_t max_prime,
                              [[maybe_unused]] std::ostream &os) {
  HermIndefiniteResult<T, Tint> res;
  HermLatticeData<T, Tint> L0 = HermLatticeOfBasis(ord, ring, A);
  int m = L0.n() / ord.deg;
  // D = -det Tr(e_a conj(e_b)), and sqrt(D) = delta / f for delta = theta -
  // conj(theta), f the index of Z[theta] in O_E (e_0 = 1)
  Tint D = -DeterminantMat(ord.trace_norm_form());
  MyVector<Tint> delta = ord.theta - ord.conjugate(ord.theta);
  MyVector<Tint> delta2 = ord.product(delta, delta);
  Tint f(1);
  while (f * f * D != delta2(0)) {
    f += 1;
#ifdef SANITY_CHECK_HERMITIAN_INDEFINITE
    if (f * f * T_abs(D) > T_abs(delta2(0))) {
      std::cerr << "HERMINDEF: delta^2 is not D times a square\n";
      throw TerminalException{1};
    }
#endif
  }
  MyVector<T> sqrt_D = UniversalVectorConversion<T, Tint>(delta) /
                       UniversalScalarConversion<T, Tint>(f);
  // C_0, generated by the ramified primes, and the set PP of even rank
  std::vector<BinaryForm<Tint>> l_gen0;
  std::vector<std::pair<std::vector<HermIdealPrime<Tint>>, size_t>> l_PP;
  for (auto const &fac : FactorsInt(T_abs(D))) {
    int64_t ell = UniversalScalarConversion<int64_t, Tint>(fac);
    std::vector<HermIdealPrime<Tint>> l_prime = HermIdealPrimesAbove(ord, ell);
    for (size_t j = 0; j < l_prime.size(); j++) {
      if (l_prime[j].type != HermIdealType::Ramified) {
        continue;
      }
      l_gen0.push_back(HermPrimeForm<T, Tint>(l_prime[j], sqrt_D, D));
      if (m % 2 != 0) {
        continue;
      }
      HermLocalSymbol sym = HermLocalSymbolOfLattice(L0, l_prime, j);
      bool in_PP = true;
      int e = (ell == 2) ? HermDifferentVal(ord, l_prime, j) : 1;
      for (size_t i = 0; i < sym.blocks.size(); i++) {
        auto const &b = sym.blocks[i];
        if (b[1] % 2 != 0) {
          in_PP = false;
        }
        if (ell != 2 && b[0] % 2 == 0) {
          in_PP = false;
        }
        if (ell == 2 && ((e + b[0]) % 2 != 0 || e + b[0] != sym.norms[i])) {
          in_PP = false;
        }
      }
      if (in_PP) {
        l_PP.push_back({l_prime, j});
      }
    }
  }
  ClassGroupQuotient<Tint> Q = GetClassGroupQuotient(D, l_gen0);
  // W = V / S
  if (!l_PP.empty()) {
    std::vector<uint64_t> l_s;
    for (auto const &u : ord.roots_of_unity) {
      MyVector<Tint> zz = u;
      zz(0) -= 1;
      uint64_t v = 0;
      for (size_t i = 0; i < l_PP.size(); i++) {
        auto const &[l_prime, j] = l_PP[i];
        int vd = (l_prime[j].ell == 2) ? HermDifferentVal(ord, l_prime, j) : 1;
        bool zero = IsZeroVector(zz) ||
                    HermIdealVal(ord, l_prime[j],
                                 UniversalVectorConversion<T, Tint>(zz)) >= vd;
        if (!zero) {
          v |= uint64_t(1) << i;
        }
      }
      l_s.push_back(v);
    }
    // the rank of S over F_2
    std::vector<uint64_t> basis;
    for (uint64_t x : l_s) {
      for (uint64_t b : basis) {
        if ((x ^ b) < x) {
          x ^= b;
        }
      }
      if (x != 0) {
        basis.push_back(x);
        std::sort(basis.begin(), basis.end(), std::greater<uint64_t>());
      }
    }
    if (basis.size() < l_PP.size()) {
      res.done = false;
      res.reason = "the even rank with " + std::to_string(l_PP.size()) +
                   " ramified primes of odd scale and W of dimension " +
                   std::to_string(l_PP.size() - basis.size()) +
                   " (a cocycle, not done)";
      return res;
    }
  }
  res.n_class = Q.order_quotient();
#ifdef DEBUG_HERMITIAN_INDEFINITE
  os << "HERMINDEF: h(E) = " << Q.order_group << ", |C_0| = " << Q.sub.size()
     << ", " << res.n_class << " classes\n";
#endif
  // the search on Q by neighbors at split primes, by increasing norm
  std::vector<BinaryForm<Tint>> l_elt{Q.canonical(BinaryFormIdentity(D))};
  res.l_basis.push_back(A);
  for (int64_t ell = 2; res.l_basis.size() < res.n_class && ell <= max_prime;
       ell++) {
    bool is_prime = true;
    for (int64_t q = 2; q * q <= ell; q++) {
      if (ell % q == 0) {
        is_prime = false;
      }
    }
    if (!is_prime || !HermIsUnimodularAt(L0, ell)) {
      continue;
    }
    std::vector<HermIdealPrime<Tint>> l_prime = HermIdealPrimesAbove(ord, ell);
    if (l_prime.size() != 2 || l_prime[0].type != HermIdealType::Split) {
      continue;
    }
    BinaryForm<Tint> c = HermPrimeForm<T, Tint>(l_prime[0], sqrt_D, D);
    if (Q.canonical(c) == l_elt[0]) {
      continue;
    }
    HermNeighborPrime<T, Tint> np = HermGetNeighborPrime(ord, l_prime, 0);
    bool used = false;
    size_t n_now = res.l_basis.size();
    for (size_t i = 0; i < n_now; i++) {
      BinaryForm<Tint> x = Q.canonical(BinaryFormCompose(l_elt[i], c, D));
      if (std::find(l_elt.begin(), l_elt.end(), x) != l_elt.end()) {
        continue;
      }
      HermLatticeData<T, Tint> L = HermLatticeOfBasis(ord, ring, res.l_basis[i]);
      HermLineSpace ls = HermGetLineSpace(L, np.C);
      std::vector<MyMatrix<T>> l_n = HermNeighbors(L, np, ls.line_vector(0));
#ifdef SANITY_CHECK_HERMITIAN_INDEFINITE
      if (l_n.size() != 1) {
        std::cerr << "HERMINDEF: a split prime gives one neighbor per line\n";
        throw TerminalException{1};
      }
#endif
      MyMatrix<T> A_n = l_n[0] * res.l_basis[i];
#ifdef SANITY_CHECK_HERMITIAN_INDEFINITE
      if (!HermSameLocalSymbolsAbove(L, HermLatticeOfBasis(ord, ring, A_n),
                                     l_prime)) {
        std::cerr << "HERMINDEF: a neighbor at " << l_prime[0].name
                  << " is not in the genus\n";
        throw TerminalException{1};
      }
#endif
      res.l_basis.push_back(A_n);
      l_elt.push_back(x);
      used = true;
    }
    if (used) {
      res.l_prime.push_back(ell);
    }
  }
  if (res.l_basis.size() < res.n_class) {
    res.done = false;
    res.reason = "the split primes up to " + std::to_string(max_prime) +
                 " do not generate the class group quotient";
  }
  return res;
}

