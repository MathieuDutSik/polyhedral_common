#!/bin/bash
# Enumeration of the classes of pairs (L, g) in the genus of a pair
# (GENUS_EnumerateIsometry), stopped by the mass of GENUS_IsometryMass.
#
# - E8+E8 with -1: the pairs are the lattices, so this is the genus of the
#   even unimodular lattices of rank 16 (E8+E8 and D16+);
# - the genus of rank 8 and determinant 25 with -1: its 3 classes;
# - E8+E8 with a root reflection: 2 classes, the centralizers being
#   2 |W(E7)| |W(E8)| and 2^15 16! / 240;
# - E8+E8 with an element of order 3 of an A2 subsystem: 2 classes, a
#   Hermitian component over Z[zeta_3] of mass 1/6, found at p = 2;
# - the genus of determinant 25 with a root reflection: 4 classes of pairs,
#   glued at 2;
# - groups <r, r'> of two orthogonal reflections.
# In every case the mass must close: complete = true.
set -e
BIN=../../src_genera/GENUS_EnumerateIsometry

run_case() {
    lat=$1
    isom=$2
    expected=$3
    echo "--- ($lat, $isom), expecting $expected classes of pairs ---"
    out=$($BIN eiso_${lat}.txt eiso_${isom}.txt eiso_mass_${isom}.txt \
              Summary stdout 2>/dev/null)
    echo "$out"
    nb=$(echo "$out" | sed -n 's/^classes of pairs = //p')
    complete=$(echo "$out" | sed -n 's/^complete = //p')
    if [ "$nb" != "$expected" ] || [ "$complete" != "true" ]; then
        echo "ERROR: ($lat, $isom) gave $nb classes, complete=$complete" >&2
        exit 1
    fi
}

run_case E8E8 mI16 2
run_case d25 mI8 3
run_case E8E8 refl16 2
run_case E8E8 ord3 2
run_case d25 refl8 4
# abelian groups, two isometries per seed: two orthogonal root reflections
# of E8+E8 in one summand (4 classes, D16+ included) and of the genus of
# determinant 25 (6 classes)
run_case E8E8 klein16 4
run_case d25 klein8 6
# the group of order 6 generated by an element of order 3 of an A2 and a
# commuting reflection: 3 classes, found at p = 5, where only the
# characters with values +-1 have eigenvectors but P^12(F_5) is 50 times
# smaller than P^12(F_7) for the fixed lattice of rank 13
run_case E8E8 c6 3
# a non-abelian group, W(A2) = S3: the neighbours of the irreducible
# isotropic G-submodules at p = 5, by random points in P^13(F_5), find the
# class on D16+ (2 classes)
run_case E8E8 S3 2
# W(A2) diagonal on A2^3 in E6 (one class, centraliser of order 12, the
# local factor 2) and on two orthogonal A2 of E8+E8 (3 classes)
run_case E6diag A2diag 1
run_case E6x2 A2diagx2 2
run_case A6x3 F21x3 2
run_case E8i C4S5 2
run_case E8w C3S5 1
run_case qD4x2 qD4x2Q8 1
run_case qE8h qE8hQ8 1
run_case qZ4 qZ4Q8 1
run_case qE8ico qE8ico2I 1
run_case qD4x4 qD4x4Q8 2
run_case qIcoLam qIcoLam2I 3
run_case qD4A2 qD4A2QS 1
run_case qD4A2x2 qD4A2x2QS 1
run_case qD4W2glue qD4W2glueQS 3
run_case qD4A2W2 qD4A2W2QS 2
run_case qD4Ideal qD4IdealQS 1
run_case qDic4 qDic4Dic 1
run_case qDic5 qDic5Dic 1
run_case qDic6 qDic6Dic 1
run_case qDic9 qDic9Dic 1
run_case qDic7 qDic7Dic 1
run_case bg0007c3 bg0007c3G 2
run_case bg1235c4 bg1235c4G 1
run_case bg0555c2 bg0555c2G 33
run_case bg2129p242 bg2129p242G 1
run_case bg2141p1441 bg2141p1441G 1
run_case bg0502p192 bg0502p192G 1
run_case bg0578p72 bg0578p72G 1
run_case bg1577p576 bg1577p576G 1
run_case bg0806p576 bg0806p576G 1
run_case A10x2 F55x2 2
run_case E8E8 S3diag2 3
# F21 on seven of the nine coordinates of A8: a Hermitian component over
# Q(sqrt -7) glued at 7 to the fixed lattice, 2 classes
run_case A8 F21A8 2
# D5 in W(A4) on two A4, one in each E8 of E8+E8: a component quadratic
# over Q(sqrt 5) glued at 5 to the fixed lattice, 2 classes (at p = 3)
run_case E8E8D5 D5 2

# The even unimodular lattices of rank 8 and 16 with a structure over Z[w]
# and Z[i] (Hentschel-Krieg-Nebe, Corollaries 1 and 2): 1, 1, 1 and 3 classes
run_case lit_E8x1 lit_w_E8x1 1
run_case lit_E8x2 lit_w_E8x2 1
run_case lit_E8x1 lit_i_E8x1 1
run_case lit_E8x2 lit_i_E8x2 3

# The recognition by isometry tests alone, by Plesken-Souvignier on the
# least spanning level of vectors (the default) and by the graph method; a
# lattice method that reads the first form only is refused for pairs.
opt_case() {
    lat=$1
    isom=$2
    expected=$3
    shift 3
    echo "--- ($lat, $isom) with $*, expecting $expected classes ---"
    out=$($BIN eiso_${lat}.txt eiso_${isom}.txt eiso_mass_${isom}.txt \
              Summary stdout "$@" 2>/dev/null)
    echo "$out"
    nb=$(echo "$out" | sed -n 's/^classes of pairs = //p')
    complete=$(echo "$out" | sed -n 's/^complete = //p')
    if [ "$nb" != "$expected" ] || [ "$complete" != "true" ]; then
        echo "ERROR: ($lat, $isom) with $* gave $nb classes, complete=$complete" >&2
        exit 1
    fi
}
opt_case E8E8 klein16 4 recognition=isometry
opt_case d25 klein8 6 recognition=isometry
opt_case qIcoLam qIcoLam2I 3 recognition=isometry
opt_case lit_E8x2 lit_i_E8x2 3 recognition=isometry
opt_case E8E8 refl16 2 recognition=isometry isomorphism_method=graph
opt_case d25 klein8 6 recognition=isometry isomorphism_method=graph
echo "--- isomorphism_method=weyl_chamber must be refused ---"
rc=0
$BIN eiso_E8E8.txt eiso_refl16.txt eiso_mass_refl16.txt Summary stdout \
     recognition=isometry isomorphism_method=weyl_chamber > /dev/null 2>&1 \
     || rc=$?
if [ "$rc" != "1" ]; then
    echo "ERROR: isomorphism_method=weyl_chamber was not refused (exit $rc)" >&2
    exit 1
fi

# The module neighbours at p = 2, for groups of odd order on lattices of odd
# determinant: F21 on A8 and on A6^3, at the prime 2 alone; and the prime 2
# refused for a group of even order (S3 = W(A2) on E8+E8)
p2_case() {
    lat=$1
    isom=$2
    expected=$3
    echo "--- ($lat, $isom) at p = 2 alone, expecting $expected classes ---"
    out=$($BIN eiso_${lat}.txt eiso_${isom}.txt eiso_mass_${isom}.txt \
              Summary stdout 2 1 2>/dev/null)
    echo "$out"
    nb=$(echo "$out" | sed -n 's/^classes of pairs = //p')
    complete=$(echo "$out" | sed -n 's/^complete = //p')
    if [ "$nb" != "$expected" ] || [ "$complete" != "true" ]; then
        echo "ERROR: ($lat, $isom) at p = 2 gave $nb classes, complete=$complete" >&2
        exit 1
    fi
}
p2_case A8 F21A8 2
p2_case A6x3 F21x3 2
echo "--- (E8E8, S3) at p = 2 must be refused ---"
rc=0
$BIN eiso_E8E8.txt eiso_S3.txt eiso_mass_S3.txt Summary stdout 2 1 \
     > /dev/null 2>&1 || rc=$?
if [ "$rc" != "1" ]; then
    echo "ERROR: p = 2 was not refused for S3 (exit $rc)" >&2
    exit 1
fi

# The exit status: a target mass that the seed alone exceeds must stop the
# program with status 3 (mass exceeded), and a target twice the true mass
# at the single prime 2 with status 2 (incomplete), so that neither can pass
# for a complete enumeration.
status_case() {
    lat=$1
    isom=$2
    massfile=$3
    prime=$4
    expected_rc=$5
    expected_line=$6
    echo "--- ($lat, $isom) with $massfile at p=$prime, expecting exit $expected_rc ---"
    rc=0
    out=$($BIN eiso_${lat}.txt eiso_${isom}.txt $massfile Summary stdout \
              $prime 1 2>/dev/null) || rc=$?
    echo "$out"
    if [ "$rc" != "$expected_rc" ] || ! echo "$out" | grep -q "^$expected_line$"; then
        echo "ERROR: ($lat, $isom) with $massfile exited with $rc" >&2
        exit 1
    fi
}
status_case E8E8 mI16 eiso_mass_wrong_tiny.txt 2 3 "mass exceeded = true"
status_case d25 mI8 eiso_mass_mI8_double.txt 2 2 "complete = false"

echo "All isometry enumeration tests passed"
touch CI_CONCLUSION
