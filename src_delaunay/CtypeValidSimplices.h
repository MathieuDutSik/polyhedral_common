/*
  The Delaunay simplices that are valid on a whole iso-edge domain (C-type).

  Let C be a generic iso-edge domain: the open cone of the forms Q having
  the same 2(2^n - 1) relevant vectors E. Its closure is the polyhedral cone
  generated by finitely many extreme rays R_1, ..., R_m, which are positive
  semidefinite and in general degenerate. The iso-Delaunay domains inside C
  have different triangulations, and we look for the simplices that belong
  to all of them, because they give constraints that hold on the whole of C
  (lower bounds on the covering density or the packing-covering constant).

  --- Emptiness is linear in the form ---

  For a simplex S = conv(v_0, ..., v_n) and w in Z^n write
  w - v_0 = sum_i alpha_i (v_i - v_0) and set

      f_{S,w}(Q) = Q[w - v_0] - sum_i alpha_i Q[v_i - v_0].

  For Q positive definite, f_{S,w}(Q) = Q[w - c] - r^2 with c and r the
  circumcenter and circumradius of S, so the set

      E(S) = { Q >= 0 : f_{S,w}(Q) >= 0 for all w in Z^n }

  is a closed convex cone, and for Q > 0 it says that S is contained in a
  Delaunay polytope of Q with the same circumsphere. Hence C is contained
  in E(S) if and only if every extreme ray R_j is in E(S).

  --- The test on one ray ---

  Write y = w - v_0 and L_R(y) = sum_i alpha_i(y) R[v_i - v_0], a linear
  form in y with L_R(v_i - v_0) = R[v_i - v_0], so that
  f_{S,w}(R) = R[y] - L_R(y). Let K = ker(R) cap Z^n.
  * If L_R does not vanish on K, f is unbounded below along K and R is
    not in E(S).
  * Otherwise f factors through Z^n / K, on which R induces a positive
    definite form Rbar, and with 2 Rbar c = Lbar the condition is that no
    vector of Z^n / K is at Rbar-distance smaller than Rbar[c] from c: a
    closest vector problem.

  --- The candidates ---

  A valid simplex is a simplex of the Delaunay triangulation of every
  generic form of C. If the form Q given is not generic, a valid simplex
  is spanned by vertices of a Delaunay polytope of Q, so the candidates
  are the full-dimensional simplices spanned by the vertices of each
  Delaunay polytope. The Delaunay polytopes are known up to Aut(Q), and
  Aut(Q) preserves C since Q is in its interior, so the validity is
  constant on the orbits.

  --- Limitation ---

  The extreme rays are computed by a dual description without symmetry from
  the inequalities kept by the criterion of CTYP_GetConeInformation, which
  include redundant ones. This is fine for the usual iso-edge domains but
  does not finish on the domain of E6* (216 facets, 103680 automorphisms):
  an exact redundancy removal and a dual description using the automorphism
  group are needed there.

  Reference: the notes "Lattice coverings and packing-coverings in
  dimensions 6, 7 and 8 through iso-edge domains", Section 5.
 */

