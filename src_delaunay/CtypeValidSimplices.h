/*
  The coordinates of CTYP_GetConeInformation: an inequality f evaluated on
  the vector x = (q_11/2, ..., q_nn/2, q_12, ..., q_{n-1,n}) gives half of
  Q[V1] - Q[V2] (see CTYP_GetInsideGramMat).
 */
template <typename T>
MyMatrix<T> CtypeCoordinatesToGram(MyVector<T> const &x, int const &n) {
  MyMatrix<T> G(n, n);
  int pos = 0;
  for (int i = 0; i < n; i++) {
    G(i, i) = 2 * x(pos);
    pos++;
  }
  for (int i = 0; i < n; i++) {
    for (int j = i + 1; j < n; j++) {
      G(i, j) = x(pos);
      G(j, i) = x(pos);
      pos++;
    }
  }
  return G;
}

template <typename T> MyVector<T> GramToCtypeCoordinates(MyMatrix<T> const &G) {
  int n = G.rows();
  MyVector<T> x(n * (n + 1) / 2);
  int pos = 0;
  for (int i = 0; i < n; i++) {
    x(pos) = G(i, i) / 2;
    pos++;
  }
  for (int i = 0; i < n; i++) {
    for (int j = i + 1; j < n; j++) {
      x(pos) = G(i, j);
      pos++;
    }
  }
  return x;
}

template <typename T> struct IsoEdgeCone {
  // One relevant vector per non-zero class of Z^n / 2Z^n.
  MyMatrix<T> Ctype;
  // The inequalities in the coordinates of CTYP_GetConeInformation. Some
  // may be redundant, which does not matter here.
  MyMatrix<T> ListIneq;
  // The extreme rays of the closure, as Gram matrices.
  std::vector<MyMatrix<T>> ListRay;
};

/*
  The iso-edge domain containing GramMat in its interior. The computation
  of the C-type throws if a class of Z^n / 2Z^n has more than one pair of
  shortest vectors, that is if GramMat is not in a generic iso-edge domain.
 */
template <typename T, typename Tint, typename Tidx>
IsoEdgeCone<T> GetIsoEdgeCone(MyMatrix<T> const &GramMat, std::ostream &os) {
#ifdef TIMINGS_CTYPE_VALID_SIMPLICES
  MicrosecondTime time;
#endif
  int n = GramMat.rows();
  TypeCtypeExch<T> ctype = CTYP_GetCTypeFromGramMat<T, Tint>(GramMat, os);
  DataCtypeFacet<T, Tidx> data = CTYP_GetConeInformation<T, Tidx>(ctype, os);
#ifdef TIMINGS_CTYPE_VALID_SIMPLICES
  os << "|CTYPE_VALID: CTYP_GetConeInformation|=" << time << "\n";
#endif
#ifdef SANITY_CHECK_CTYPE_VALID_SIMPLICES
  MyVector<T> x = GramToCtypeCoordinates(GramMat);
  for (int i_ineq = 0; i_ineq < data.ListInequalities.rows(); i_ineq++) {
    T scal = data.ListInequalities.row(i_ineq).dot(x);
    if (scal <= 0) {
      std::cerr << "CTYPE_VALID: The Gram matrix is not in the interior of "
                   "its iso-edge domain, i_ineq="
                << i_ineq << " scal=" << scal << "\n";
      throw TerminalException{1};
    }
  }
#endif
  MyMatrix<T> EXT = double_desc::DualDescription(data.ListInequalities, os);
#ifdef TIMINGS_CTYPE_VALID_SIMPLICES
  os << "|CTYPE_VALID: DualDescription|=" << time << "\n";
#endif
  std::vector<MyMatrix<T>> ListRay;
  for (int i_ray = 0; i_ray < EXT.rows(); i_ray++) {
    MyVector<T> eRay = GetMatrixRow(EXT, i_ray);
    MyMatrix<T> R = RemoveFractionMatrix(CtypeCoordinatesToGram(eRay, n));
#ifdef SANITY_CHECK_CTYPE_VALID_SIMPLICES
    if (!IsPositiveSemiDefinite(R, os)) {
      std::cerr << "CTYPE_VALID: An extreme ray of the iso-edge domain is "
                   "not positive semidefinite\n";
      throw TerminalException{1};
    }
#endif
    ListRay.push_back(R);
  }
#ifdef DEBUG_CTYPE_VALID_SIMPLICES
  os << "CTYPE_VALID: |ListIneq|=" << data.ListInequalities.rows()
     << " |ListIrred|=" << data.ListIrred.size()
     << " |ListRay|=" << ListRay.size() << "\n";
#endif
  return {std::move(data.TheCtype), std::move(data.ListInequalities),
          std::move(ListRay)};
}

/*
  The data of one extreme ray R that does not depend on the simplex: the
  kernel K of R in Z^n, a completion Compl of K into a basis of Z^n, the
  positive definite form RedGram = Compl R Compl^T induced on Z^n / K and
  the closest vector solver for it.
 */
template <typename T, typename Tint> struct RayEmptinessTester {
  MyMatrix<T> R;
  int rank;
  MyMatrix<T> Kernel;
  MyMatrix<T> Compl;
  MyMatrix<T> RedGram;
  std::unique_ptr<CVPSolver<T, Tint>> solver;
};

template <typename T, typename Tint>
RayEmptinessTester<T, Tint> GetRayEmptinessTester(MyMatrix<T> const &R,
                                                  std::ostream &os) {
  int n = R.rows();
  MyMatrix<Tint> R_int =
      UniversalMatrixConversion<Tint, T>(RemoveFractionMatrix(R));
  MyMatrix<Tint> Kernel_int = NullspaceIntMat(R_int);
  MyMatrix<Tint> Compl_int = SubspaceCompletionInt(Kernel_int, n);
  MyMatrix<T> Kernel = UniversalMatrixConversion<T, Tint>(Kernel_int);
  MyMatrix<T> Compl = UniversalMatrixConversion<T, Tint>(Compl_int);
  MyMatrix<T> RedGram = Compl * R * Compl.transpose();
  int rank = Compl.rows();
#ifdef SANITY_CHECK_CTYPE_VALID_SIMPLICES
  if (rank == 0 || !IsPositiveDefinite(RedGram, os)) {
    std::cerr << "CTYPE_VALID: The form induced by the ray on Z^n / ker "
                 "should be positive definite, rank="
              << rank << "\n";
    throw TerminalException{1};
  }
#endif
  std::unique_ptr<CVPSolver<T, Tint>> solver =
      std::make_unique<CVPSolver<T, Tint>>(RedGram, os);
  return {R,
          rank,
          std::move(Kernel),
          std::move(Compl),
          std::move(RedGram),
          std::move(solver)};
}

/*
  Whether R is in E(S) for the simplex S whose vertex v_0 is at the origin
  and whose other vertices v_i - v_0 are the rows of Vdiff.
 */
template <typename T, typename Tint>
bool IsRayInEmptinessCone(RayEmptinessTester<T, Tint> const &rt,
                          MyMatrix<T> const &Vdiff) {
  int n = Vdiff.rows();
  // L_R(y) = y . ell with Vdiff ell = b, b_i = R[v_i - v_0].
  MyVector<T> b(n);
  for (int i = 0; i < n; i++) {
    MyVector<T> V = GetMatrixRow(Vdiff, i);
    b(i) = EvaluationQuadForm(rt.R, V);
  }
  MyVector<T> ell = Inverse(Vdiff) * b;
  for (int i = 0; i < rt.Kernel.rows(); i++) {
    MyVector<T> K = GetMatrixRow(rt.Kernel, i);
    if (K.dot(ell) != 0) {
      return false;
    }
  }
  // In the basis Compl of Z^n / K: f = RedGram[z] - ellRed . z
  //   = RedGram[z - c] - RedGram[c] with 2 RedGram c = ellRed.
  MyVector<T> ellRed = rt.Compl * ell;
  MyVector<T> c = Inverse(rt.RedGram) * ellRed / T(2);
  T r2 = EvaluationQuadForm(rt.RedGram, c);
  if (r2 == 0) {
    return true;
  }
  ResultShortest<Tint> res = rt.solver->ShortestAtDistance(c, r2);
  return !res.better_vector.has_value();
}

/*
  The full-dimensional simplices spanned by the vertices of a Delaunay
  polytope, given by the matrix EXT of its vertices with a first column of
  ones. For a simplex this is the simplex itself. Each simplex is returned
  as the list of its vertex indices.
 */
template <typename T, typename Tint>
std::vector<std::vector<int>> GetSpanningSimplices(MyMatrix<Tint> const &EXT) {
  int nbVert = EXT.rows();
  int n = EXT.cols() - 1;
  std::vector<std::vector<int>> ListSimplex;
  if (nbVert == n + 1) {
    std::vector<int> eSimp(n + 1);
    for (int i = 0; i <= n; i++) {
      eSimp[i] = i;
    }
    ListSimplex.push_back(eSimp);
    return ListSimplex;
  }
  MyMatrix<T> EXT_T = UniversalMatrixConversion<T, Tint>(EXT);
  std::vector<int> eSimp;
  std::function<void(int)> f_rec = [&](int start) -> void {
    if (static_cast<int>(eSimp.size()) == n + 1) {
      if (RankMat(SelectRow(EXT_T, eSimp)) == n + 1) {
        ListSimplex.push_back(eSimp);
      }
      return;
    }
    int n_missing = n + 1 - static_cast<int>(eSimp.size());
    for (int i = start; i <= nbVert - n_missing; i++) {
      eSimp.push_back(i);
      f_rec(i + 1);
      eSimp.pop_back();
    }
  };
  f_rec(0);
  return ListSimplex;
}

template <typename Tint> struct CellValidSimplices {
  // The vertices of the Delaunay polytope, with a first column of ones.
  MyMatrix<Tint> EXT;
  // The full-dimensional simplices spanned by its vertices.
  std::vector<std::vector<int>> ListSimplex;
  // For each of them, whether it is valid on the whole iso-edge domain.
  std::vector<bool> ListValid;
};

template <typename T, typename Tint> struct ResultValidSimplices {
  IsoEdgeCone<T> cone;
  std::vector<CellValidSimplices<Tint>> ListCell;
};

/*
  The simplices valid on the whole iso-edge domain containing GramMat in
  its interior, among the candidates given by the orbits of Delaunay
  polytopes of GramMat.
 */
template <typename T, typename Tint, typename Tgroup, typename Tidx>
ResultValidSimplices<T, Tint> ComputeValidSimplices(MyMatrix<T> const &GramMat,
                                                    std::ostream &os) {
  using TintGroup = typename Tgroup::Tint;
#ifdef TIMINGS_CTYPE_VALID_SIMPLICES
  MicrosecondTime time;
#endif
  int n = GramMat.rows();
  IsoEdgeCone<T> cone = GetIsoEdgeCone<T, Tint, Tidx>(GramMat, os);
  std::vector<RayEmptinessTester<T, Tint>> ListTester;
  for (auto &R : cone.ListRay) {
    ListTester.emplace_back(GetRayEmptinessTester<T, Tint>(R, os));
  }
#ifdef TIMINGS_CTYPE_VALID_SIMPLICES
  os << "|CTYPE_VALID: ListTester|=" << time << "\n";
#endif
  PolyHeuristicSerial<TintGroup> AllArr =
      AllStandardHeuristicSerial<T, TintGroup>(n + 1, os);
  DataLattice<T, Tint, Tgroup> data =
      GetDataLattice<T, Tint, Tgroup>(GramMat, AllArr, os);
  int max_runtime_second = 0;
  DelaunayTesselation<Tint, Tgroup> DT =
      get_delaunay_tessellation_serial<T, Tint, Tgroup>(data, "none",
                                                        max_runtime_second, os);
#ifdef TIMINGS_CTYPE_VALID_SIMPLICES
  os << "|CTYPE_VALID: Delaunay tessellation|=" << time << "\n";
#endif
  std::vector<CellValidSimplices<Tint>> ListCell;
  for (auto &eDel : DT.l_dels) {
    std::vector<std::vector<int>> ListSimplex =
        GetSpanningSimplices<T, Tint>(eDel.EXT);
    std::vector<bool> ListValid;
    for (auto &eSimp : ListSimplex) {
      MyMatrix<T> Vdiff(n, n);
      for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {
          Vdiff(i, j) = UniversalScalarConversion<T, Tint>(
              eDel.EXT(eSimp[i + 1], j + 1) - eDel.EXT(eSimp[0], j + 1));
        }
      }
      bool is_valid = true;
      for (auto &rt : ListTester) {
        if (!IsRayInEmptinessCone(rt, Vdiff)) {
          is_valid = false;
          break;
        }
      }
      ListValid.push_back(is_valid);
    }
#ifdef DEBUG_CTYPE_VALID_SIMPLICES
    size_t n_valid = 0;
    for (bool v : ListValid) {
      if (v) {
        n_valid++;
      }
    }
    os << "CTYPE_VALID: |EXT|=" << eDel.EXT.rows()
       << " |ListSimplex|=" << ListSimplex.size() << " n_valid=" << n_valid
       << "\n";
#endif
    ListCell.push_back(
        {eDel.EXT, std::move(ListSimplex), std::move(ListValid)});
  }
#ifdef TIMINGS_CTYPE_VALID_SIMPLICES
  os << "|CTYPE_VALID: emptiness tests|=" << time << "\n";
#endif
  return {std::move(cone), std::move(ListCell)};
}

template <typename T, typename Tint>
void WriteValidSimplicesGAP(std::ostream &os_out,
                            ResultValidSimplices<T, Tint> const &res) {
  os_out << "return rec(Ctype:=";
  WriteMatrixGAP(os_out, res.cone.Ctype);
  os_out << ", ListRay:=[";
  bool IsFirst = true;
  for (auto &R : res.cone.ListRay) {
    if (!IsFirst) {
      os_out << ",\n";
    }
    IsFirst = false;
    WriteMatrixGAP(os_out, R);
  }
  os_out << "], ListCell:=[";
  IsFirst = true;
  for (auto &cell : res.ListCell) {
    if (!IsFirst) {
      os_out << ",\n";
    }
    IsFirst = false;
    os_out << "rec(EXT:=";
    WriteMatrixGAP(os_out, cell.EXT);
    os_out << ", ListSimplex:=[";
    for (size_t i = 0; i < cell.ListSimplex.size(); i++) {
      if (i > 0) {
        os_out << ",";
      }
      os_out << "[";
      for (size_t j = 0; j < cell.ListSimplex[i].size(); j++) {
        if (j > 0) {
          os_out << ",";
        }
        os_out << (cell.ListSimplex[i][j] + 1);
      }
      os_out << "]";
    }
    os_out << "], ListValid:=[";
    for (size_t i = 0; i < cell.ListValid.size(); i++) {
      if (i > 0) {
        os_out << ",";
      }
      os_out << GAP_logical(cell.ListValid[i]);
    }
    os_out << "])";
  }
  os_out << "]);\n";
}

