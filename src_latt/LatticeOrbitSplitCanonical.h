/*
  Canonical form by orbit splitting under the automorphism group.

  The graph method of LatticeStabEquiCan.h builds the full matrix of
  pairwise scalar products of the invariant vector family, which is
  quadratic in the family size and is not viable on a family like the
  98280 minimal pairs of the Leech lattice. This file computes a
  canonical form WITHOUT any quadratic object, at the price of needing
  the automorphism group first, which the Plesken-Souvignier backtrack
  of src_group/PleskenSouvignier.h provides on precisely those large
  highly symmetric families.

  The scheme: with Aut known as a permutation group on the antipodal
  pairs of the family, a prefix of pairs p_1, ..., p_r spanning Q^n is
  chosen one at a time, each pick canonical UP TO THE GROUP. At each
  level the orbits of the stabilizer of the earlier picks are computed,
  and the next pick is any element of the orbit that minimizes an
  isometry-invariant key; all elements of one orbit are equivalent under
  the stabilizer, so which element is taken does not matter. The key is,
  in order: whether the orbit is orthogonal to the prefix (non-orthogonal
  preferred, which keeps the sign propagation below connected), the orbit
  size, the norms, and the sign-normalized tuples of scalar products with
  the prefix. When several orbits tie on the key, they are refined by the
  distribution of their scalar products against the invariant classes of
  the whole family (computable from ONE representative per orbit, since
  every such function is constant on an orbit -- this is what knowing the
  true orbits buys: Weisfeiler-Leman style refinement without the
  quadratic product matrix). An orbit tie that survives the refinement
  is BRANCHED: every tied orbit is explored, each branch completes to a
  canonical Gram matrix, and the lexicographically minimal one is the
  result. The tied set is isometry-invariant, so the branch set and
  hence the minimum stay canonical; the branch count is capped by
  OSC_MAX_BRANCH, beyond which the method declines. On the Leech lattice
  exactly one tie survives, at rank 7 with a stabilizer of order 1536,
  and the branching costs a factor two on the cheap tail of the
  selection.

  Once the prefix spans Q^n, the map v -> (<v, p_i>) is injective, so
  every vector of the family is pinned by its product profile: the pairs
  are sorted by their sign-normalized profiles, each pair takes the sign
  its normalized profile dictates, and the reordered signed family is
  passed to get_canonicalization_matrix exactly as the graph method
  passes its canonically reordered family.

  Signs of the prefix: the product graph on the prefix positions (edge =
  nonzero product) is sign-propagated component by component in canonical
  order. A flip of one whole component negates span(component), which is
  an integral isometry preserving the family whenever every family vector
  lies in the span of a single component (positive definiteness forces a
  vector whose profile is supported in one component into that
  component's span). That property is checked, and its failure -- several
  components with a straddling vector, which needs picks the orthogonal
  preference could not avoid -- is reported as a failure.

  The canonical form of this method is NOT comparable with the one of
  ComputeCanonicalForm: both are canonical, but they are different
  functions on the isometry classes.
 */

// The orbits of the group generated by ListPermGen on {0, ..., m-1}:
// the list of orbits and the orbit index of every point.
template <typename Telt>
std::pair<std::vector<std::vector<int>>, std::vector<int>>
osc_orbits(std::vector<Telt> const &ListPermGen, int m) {
  std::vector<int> orbit_id(m, -1);
  std::vector<std::vector<int>> orbits;
  for (int j = 0; j < m; j++) {
    if (orbit_id[j] != -1) {
      continue;
    }
    int id = orbits.size();
    std::vector<int> orb{j};
    orbit_id[j] = id;
    size_t cnd = 0;
    while (cnd < orb.size()) {
      for (auto &eGen : ListPermGen) {
        int im = eGen.at(orb[cnd]);
        if (orbit_id[im] == -1) {
          orbit_id[im] = id;
          orb.push_back(im);
        }
      }
      cnd++;
    }
    orbits.push_back(std::move(orb));
  }
  return {std::move(orbits), std::move(orbit_id)};
}

// Sign-normalizes the tuple in place so that its first non-zero entry is
// positive; returns the sign applied, 0 for the zero tuple.
template <typename Tint> int osc_normalize_tuple(std::vector<Tint> &v) {
  size_t len = v.size();
  size_t ipos = 0;
  while (ipos < len && v[ipos] == 0) {
    ipos++;
  }
  if (ipos == len) {
    return 0;
  }
  if (v[ipos] > 0) {
    return 1;
  }
  for (size_t i = ipos; i < len; i++) {
    v[i] = -v[i];
  }
  return -1;
}

/*
  Incremental row echelon over the field, for testing whether a vector
  increases the rank of the prefix span. Vectors inside the span are
  constant along a stabilizer orbit (the stabilizer fixes the prefix
  pointwise, hence its span pointwise), so one representative decides
  for the whole orbit.
 */
template <typename Tfield> struct OscEchelon {
  int n;
  std::vector<MyVector<Tfield>> rows;
  std::vector<int> pivots;
  explicit OscEchelon(int _n) : n(_n) {}
  int get_rank() const { return rows.size(); }
  MyVector<Tfield> reduce(MyVector<Tfield> v) const {
    for (size_t k = 0; k < rows.size(); k++) {
      Tfield const &c = v(pivots[k]);
      if (c != 0) {
        v -= c * rows[k];
      }
    }
    return v;
  }
  bool increases_rank(MyVector<Tfield> const &v) const {
    MyVector<Tfield> w = reduce(v);
    for (int i = 0; i < n; i++) {
      if (w(i) != 0) {
        return true;
      }
    }
    return false;
  }
  void insert(MyVector<Tfield> const &v) {
    MyVector<Tfield> w = reduce(v);
    int piv = -1;
    for (int i = 0; i < n; i++) {
      if (w(i) != 0) {
        piv = i;
        break;
      }
    }
    if (piv == -1) {
      std::cerr << "OSC: inserting a vector that does not increase the rank\n";
      throw TerminalException{1};
    }
    Tfield c = w(piv);
    for (int i = 0; i < n; i++) {
      w(i) = w(i) / c;
    }
    rows.push_back(w);
    pivots.push_back(piv);
  }
};

/*
  The raw products of every pair representative against the prefix pair p:
  entry (j, iMat) = <v_j, v_p> for the iMat-th form, signs relative to the
  stored sign-normalized representatives. One such column block is
  computed once per selected prefix pair; the orbit keys and the final
  profiles read from it.
 */
template <typename Tint>
MyMatrix<Tint> osc_products_column(PleskenSouvignierContext<Tint> const &ctx,
                                   int p) {
  int m = ctx.VS.m;
  int nbMat = ctx.ListMat.size();
  MyMatrix<Tint> col(m, nbMat);
  for (int iMat = 0; iMat < nbMat; iMat++) {
    col.col(iMat) = ctx.VS.V * ctx.W[iMat].row(p).transpose();
  }
  return col;
}

/*
  The base key of an orbit, from one representative: every entry is an
  isometry invariant and is constant on the orbit, so the minimum over
  the keys of the rank-increasing orbits is a canonical choice of orbit.
  Layout: [orthogonality flag, orbit size, norms, normalized product
  tuples against the prefix in order]. The non-orthogonal orbits are
  preferred so that a selected pair can receive its sign from the
  earlier ones whenever any candidate allows it.
 */
template <typename Tint>
std::vector<Tint> osc_orbit_key(PleskenSouvignierContext<Tint> const &ctx,
                                std::vector<MyMatrix<Tint>> const &prefix_col,
                                size_t orbit_size, int rep) {
  int nbMat = ctx.ListMat.size();
  size_t n_prefix = prefix_col.size();
  // Written in place: the flag and the orbit size first, then the norms,
  // then the normalized tuples, the flag being set once they are known.
  std::vector<Tint> key(2 + nbMat + n_prefix * nbMat);
  key[1] = Tint(static_cast<int>(orbit_size));
  for (int iMat = 0; iMat < nbMat; iMat++) {
    key[2 + iMat] = ctx.Lengths(rep, iMat);
  }
  bool orth = true;
  size_t pos = 2 + nbMat;
  for (size_t k = 0; k < n_prefix; k++) {
    size_t start = pos;
    for (int iMat = 0; iMat < nbMat; iMat++) {
      key[pos] = prefix_col[k](rep, iMat);
      if (key[pos] != 0) {
        orth = false;
      }
      pos++;
    }
    // The sign normalization of osc_normalize_tuple, on the slice.
    size_t ipos = start;
    while (ipos < pos && key[ipos] == 0) {
      ipos++;
    }
    if (ipos < pos && key[ipos] < 0) {
      for (size_t u = ipos; u < pos; u++) {
        key[u] = -key[u];
      }
    }
  }
  key[0] = orth ? Tint(1) : Tint(0);
  return key;
}

/*
  Refinement of a tied set of orbits by their product distributions
  against the invariant classes of the whole family: for a tied orbit
  representative r, the multiset of normalized product tuples of r
  against the pairs of each class, classes taken in the canonical order
  of their key histories. Constant on the orbit, so one representative
  suffices, and linear in the family size per tied orbit. The histories
  grow with each round, the class partition only refines, and the tied
  set shrinks or the refinement has stalled.

  Returns the index of the unique minimal orbit, or nothing when the
  tie survives: a genuine ambiguity this vocabulary cannot break,
  reported to the caller as the failure of the method.
 */
template <typename Tint>
std::optional<int>
osc_refine_tie(PleskenSouvignierContext<Tint> const &ctx,
               std::vector<std::vector<int>> const &orbits,
               std::vector<int> const &orbit_id,
               std::vector<std::vector<Tint>> &hist, std::vector<int> tied,
               [[maybe_unused]] std::ostream &os) {
  int m = ctx.VS.m;
  int nbMat = ctx.ListMat.size();
  int n_orbit = orbits.size();
  /*
    The classes are the distinct histories in increasing order. During the
    refinement only the histories of the orbits of the initial tie change:
    they all start equal to one key K and grow by appending, while every
    other history stays the key it was, all keys having one length. So
    the order of the other keys is computed once, and in each round only
    the changed histories are sorted and placed right after K, which they
    all exceed and which every larger key exceeds them in turn. This is
    the order the histories would have in a std::map over all orbits.
   */
  std::vector<int> by_hist(n_orbit);
  for (int iOrb = 0; iOrb < n_orbit; iOrb++) {
    by_hist[iOrb] = iOrb;
  }
  std::sort(by_hist.begin(), by_hist.end(), [&](int a, int b) -> bool {
    if (hist[a] != hist[b]) {
      return hist[a] < hist[b];
    }
    return a < b;
  });
  std::vector<int> base_rank(n_orbit);
  int n_base = 0;
  for (int k = 0; k < n_orbit; k++) {
    if (k > 0 && hist[by_hist[k]] != hist[by_hist[k - 1]]) {
      n_base++;
    }
    base_rank[by_hist[k]] = n_base;
  }
  n_base++;
  std::vector<int> const changed = tied;
  std::vector<uint8_t> is_changed(n_orbit, 0);
  for (auto &iOrb : changed) {
    is_changed[iOrb] = 1;
  }
  int rank_K = base_rank[changed[0]];
  // The normalized product tuples of each tied representative against all
  // the pairs, flattened (pair j at positions j * nbMat ...): they do not
  // depend on the round, so they are computed once per tied orbit.
  std::map<int, std::vector<Tint>> tuples_of;
  auto get_tuples = [&](int iOrb) -> std::vector<Tint> const & {
    auto iter = tuples_of.find(iOrb);
    if (iter != tuples_of.end()) {
      return iter->second;
    }
    int rep = orbits[iOrb][0];
    // One matrix-vector product per form: V is column major, so this is
    // contiguous where an entrywise loop over the rows of V is not.
    std::vector<MyVector<Tint>> cols;
    for (int iMat = 0; iMat < nbMat; iMat++) {
      cols.push_back(ctx.VS.V * ctx.W[iMat].row(rep).transpose());
    }
    std::vector<Tint> flat(static_cast<size_t>(m) * nbMat);
    std::vector<Tint> tup(nbMat);
    for (int j = 0; j < m; j++) {
      for (int iMat = 0; iMat < nbMat; iMat++) {
        tup[iMat] = cols[iMat](j);
      }
      osc_normalize_tuple(tup);
      for (int iMat = 0; iMat < nbMat; iMat++) {
        flat[static_cast<size_t>(j) * nbMat + iMat] = tup[iMat];
      }
    }
    return tuples_of.emplace(iOrb, std::move(flat)).first->second;
  };
  while (true) {
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
    os << "OSC: refining a tie of " << tied.size() << " orbits\n";
#endif
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
    MicrosecondTime time;
#endif
    // The classes of all orbits, ordered canonically by key history: the
    // changed histories, sorted, take the ranks right after K.
    std::vector<int> changed_sorted = changed;
    std::sort(changed_sorted.begin(), changed_sorted.end(),
              [&](int a, int b) -> bool { return hist[a] < hist[b]; });
    std::vector<int> class_of_orbit(n_orbit);
    int n_sub = 0;
    for (size_t k = 0; k < changed_sorted.size(); k++) {
      if (k > 0 && hist[changed_sorted[k]] != hist[changed_sorted[k - 1]]) {
        n_sub++;
      }
      class_of_orbit[changed_sorted[k]] = rank_K + 1 + n_sub;
    }
    n_sub++;
    for (int iOrb = 0; iOrb < n_orbit; iOrb++) {
      if (is_changed[iOrb] == 0) {
        int r = base_rank[iOrb];
        class_of_orbit[iOrb] = (r <= rank_K) ? r : r + n_sub;
      }
    }
    int n_class = n_base + n_sub;
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
    os << "|OSC: refine, " << n_class << " classes|=" << time << "\n";
#endif
    // The extension of each tied orbit: per class, the sorted multiset
    // of normalized product tuples of the representative against the
    // class members, flattened in class order.
    std::vector<std::vector<Tint>> ext(tied.size());
    for (size_t iTied = 0; iTied < tied.size(); iTied++) {
      std::vector<Tint> const &flat = get_tuples(tied[iTied]);
      std::vector<Tint> &e = ext[iTied];
      e.reserve(flat.size());
      Tint vmin(0), vmax(0);
      if (nbMat == 1) {
        for (auto &val : flat) {
          if (val < vmin) {
            vmin = val;
          }
          if (val > vmax) {
            vmax = val;
          }
        }
      }
      if (nbMat == 1 && vmax - vmin < Tint(64)) {
        // Small values, the common case: a counting sort over (class,
        // value) gives the same sequence as the per-class sorts, without
        // a bucket per class -- at the deep levels almost every orbit is a
        // class of its own.
        int range = UniversalScalarConversion<int, Tint>(vmax - vmin) + 1;
        std::vector<int> counts(static_cast<size_t>(n_class) * range, 0);
        for (int j = 0; j < m; j++) {
          int v = UniversalScalarConversion<int, Tint>(flat[j] - vmin);
          counts[static_cast<size_t>(class_of_orbit[orbit_id[j]]) * range +
                 v]++;
        }
        for (int c = 0; c < n_class; c++) {
          for (int v = 0; v < range; v++) {
            int cnt = counts[static_cast<size_t>(c) * range + v];
            for (int u = 0; u < cnt; u++) {
              e.push_back(vmin + Tint(v));
            }
          }
        }
      } else if (nbMat == 1) {
        // Tuples of length one: a sort of scalars per class gives the same
        // order as the sort of the one-entry tuples, without a vector per
        // tuple.
        std::vector<std::vector<Tint>> buckets(n_class);
        for (int j = 0; j < m; j++) {
          buckets[class_of_orbit[orbit_id[j]]].push_back(flat[j]);
        }
        for (int c = 0; c < n_class; c++) {
          std::sort(buckets[c].begin(), buckets[c].end());
          for (auto &val : buckets[c]) {
            e.push_back(val);
          }
        }
      } else {
        std::vector<std::vector<std::vector<Tint>>> buckets(n_class);
        for (int j = 0; j < m; j++) {
          std::vector<Tint> tup(flat.begin() + static_cast<size_t>(j) * nbMat,
                                flat.begin() +
                                    static_cast<size_t>(j + 1) * nbMat);
          buckets[class_of_orbit[orbit_id[j]]].push_back(std::move(tup));
        }
        for (int c = 0; c < n_class; c++) {
          std::sort(buckets[c].begin(), buckets[c].end());
          for (auto &t : buckets[c]) {
            for (auto &val : t) {
              e.push_back(val);
            }
          }
        }
      }
    }
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
    os << "|OSC: refine, extensions of " << tied.size() << " orbits|=" << time
       << "\n";
#endif
    // The new tied set: the orbits whose extension is minimal.
    size_t i_min = 0;
    for (size_t iTied = 1; iTied < tied.size(); iTied++) {
      if (ext[iTied] < ext[i_min]) {
        i_min = iTied;
      }
    }
    std::vector<int> new_tied;
    for (size_t iTied = 0; iTied < tied.size(); iTied++) {
      if (ext[iTied] == ext[i_min]) {
        new_tied.push_back(tied[iTied]);
      }
    }
    for (size_t iTied = 0; iTied < tied.size(); iTied++) {
      std::vector<Tint> &h = hist[tied[iTied]];
      for (auto &val : ext[iTied]) {
        h.push_back(val);
      }
    }
    if (new_tied.size() == 1) {
      return new_tied[0];
    }
    if (new_tied.size() == tied.size()) {
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
      os << "OSC: the tie of " << tied.size()
         << " orbits survives the refinement, failure\n";
#endif
      return {};
    }
    tied = std::move(new_tied);
  }
}

// The number of branches above which the tie exploration gives up: the
// cost and memory are linear in it, and a configuration needing more is
// better handled by a stronger invariant vocabulary.
static const size_t OSC_MAX_BRANCH = 16;

/*
  The order of the automorphism group acting on the antipodal pairs,
  when it is provably |Aut| / 2, and 0 otherwise. A kernel element g of
  the pair action has g v = eps_v * v for every family vector v; when
  the standard basis lies in the family, eps_i * eps_j * M(i, j) =
  M(i, j) forces one sign across a connected component of the graph of
  non-zero off-diagonal entries of M = ListMat[0], so a connected graph
  gives g = +-Id and the kernel is exactly {+-Id}. With the order known
  the randomized chain construction stops the moment the chain is
  complete; a 0 makes it verify itself by the deterministic completion
  pass, which dominates on a large degree (698s of a 749s Leech run).
  A wrong order would be dangerous -- a partial chain that happens to
  hit it would be returned as the group -- hence the proof, not a guess.
 */
template <typename Tint, typename Tord>
Tord osc_pair_action_order(PleskenSouvignierContext<Tint> const &ctx,
                           Tord const &order_aut) {
  int n = ctx.n();
  int m = ctx.VS.m;
  // The standard basis in the family.
  for (int i = 0; i < n; i++) {
    MyVector<Tint> e = ZeroVector<Tint>(n);
    e(i) = Tint(1);
    if (ctx.VS.Map.find(e) == ctx.VS.Map.end()) {
      return Tord(0);
    }
  }
  // Connectivity of the non-zero off-diagonal graph of ListMat[0].
  MyMatrix<Tint> const &M = ctx.ListMat[0];
  std::vector<uint8_t> seen(n, 0);
  std::vector<int> bfs{0};
  seen[0] = 1;
  size_t cnd = 0;
  while (cnd < bfs.size()) {
    int i = bfs[cnd];
    for (int j = 0; j < n; j++) {
      if (seen[j] == 0 && M(i, j) != 0) {
        seen[j] = 1;
        bfs.push_back(j);
      }
    }
    cnd++;
  }
  for (int i = 0; i < n; i++) {
    if (seen[i] == 0) {
      return Tord(0);
    }
  }
  (void)m;
  return order_aut / Tord(2);
}

/*
  The recursive selection: pair indices p_1, ..., p_n whose vectors span
  Q^n, each pick canonical up to the group given the earlier ones. At a
  tie that survives the refinement EVERY tied orbit is explored: the
  tied set is canonical, so the set of completed branches is canonical,
  and the caller takes the branch whose final canonical Gram matrix is
  lexicographically minimal. The completed prefixes are appended to
  out_prefix; the shared prefix/prefix_col/echelon state is restored on
  return. Returns false when the branch count would exceed OSC_MAX_BRANCH,
  which the caller reports as the failure of the method.
 */
template <typename Tint, typename Tgroup, typename Tfield>
bool osc_select_rec(PleskenSouvignierContext<Tint> const &ctx,
                    Tgroup const &H, std::vector<int> &prefix,
                    std::vector<MyMatrix<Tint>> &prefix_col,
                    OscEchelon<Tfield> const &ech,
                    std::vector<std::vector<int>> &out_prefix,
                    std::ostream &os) {
  using Telt = typename Tgroup::Telt;
  using Tidx = typename Telt::Tidx;
  int n = ctx.n();
  if (ech.get_rank() == n) {
    if (out_prefix.size() >= OSC_MAX_BRANCH) {
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
      os << "OSC: more than " << OSC_MAX_BRANCH << " branches, failure\n";
#endif
      return false;
    }
    out_prefix.push_back(prefix);
    return true;
  }
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  MicrosecondTime time;
#endif
  std::vector<Telt> LGen = H.GeneratorsOfGroup();
  std::pair<std::vector<std::vector<int>>, std::vector<int>> pr =
      osc_orbits(LGen, ctx.VS.m);
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  os << "|OSC: level " << prefix.size() << ", orbits of " << LGen.size()
     << " generators|=" << time << "\n";
#endif
  std::vector<std::vector<int>> const &orbits = pr.first;
  std::vector<int> const &orbit_id = pr.second;
  std::vector<std::vector<Tint>> hist(orbits.size());
  for (size_t iOrb = 0; iOrb < orbits.size(); iOrb++) {
    hist[iOrb] =
        osc_orbit_key(ctx, prefix_col, orbits[iOrb].size(), orbits[iOrb][0]);
  }
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  os << "|OSC: level " << prefix.size() << ", keys of " << orbits.size()
     << " orbits|=" << time << "\n";
#endif
  // The rank-increase test runs lazily, by ascending key: only the keys
  // at the front are ever tested. Membership of the span is constant on
  // an orbit, the stabilizer fixing the span pointwise. The orbits come
  // off a min-heap on (key, orbit index), the order of a full sort, in
  // blocks of equal keys: building the heap is linear and each orbit
  // taken costs a logarithm, whereas the selection only ever looks at the
  // first block with a rank-increasing orbit.
  auto heap_cmp = [&](int a, int b) -> bool {
    if (hist[a] != hist[b]) {
      return hist[b] < hist[a];
    }
    return b < a;
  };
  std::vector<int> heap(orbits.size());
  for (size_t iOrb = 0; iOrb < orbits.size(); iOrb++) {
    heap[iOrb] = iOrb;
  }
  std::make_heap(heap.begin(), heap.end(), heap_cmp);
  auto pop_min = [&]() -> int {
    std::pop_heap(heap.begin(), heap.end(), heap_cmp);
    int iOrb = heap.back();
    heap.pop_back();
    return iOrb;
  };
  auto next_block = [&]() -> std::vector<int> {
    std::vector<int> block;
    if (heap.empty()) {
      return block;
    }
    block.push_back(pop_min());
    while (!heap.empty() && hist[heap.front()] == hist[block[0]]) {
      block.push_back(pop_min());
    }
    return block;
  };
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
  size_t n_rank_test = 0;
#endif
  auto f_increases = [&](int iOrb) -> bool {
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
    n_rank_test++;
#endif
    int rep = orbits[iOrb][0];
    MyVector<Tfield> v(n);
    for (int i = 0; i < n; i++) {
      v(i) = UniversalScalarConversion<Tfield, Tint>(ctx.VS.V(rep, i));
    }
    return ech.increases_rank(v);
  };
  // The orbits to explore: the unique minimal one, or every member of a
  // tie the refinement cannot break.
  std::vector<int> selected;
  while (true) {
    std::vector<int> key_block = next_block();
    if (key_block.empty()) {
      break;
    }
    std::vector<int> block;
    for (auto &iOrb : key_block) {
      if (f_increases(iOrb)) {
        block.push_back(iOrb);
      }
    }
    if (block.size() == 1) {
      selected = block;
      break;
    }
    if (block.size() > 1) {
      std::optional<int> opt =
          osc_refine_tie(ctx, orbits, orbit_id, hist, block, os);
      if (opt) {
        selected = {*opt};
      } else {
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
        os << "OSC: branching over the " << block.size()
           << " orbits of a surviving tie\n";
#endif
        selected = block;
      }
      break;
    }
  }
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
  os << "OSC: level " << prefix.size() << ", " << n_rank_test
     << " rank tests\n";
#endif
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  os << "|OSC: level " << prefix.size() << ", choice|=" << time << "\n";
#endif
  if (selected.empty()) {
    std::cerr << "OSC: no rank-increasing orbit although the rank is not "
              << "full, the family does not have full rank\n";
    throw TerminalException{1};
  }
  for (auto &iOrb : selected) {
    // Orbit representatives are canonical only up to the group, so any
    // member serves; the smallest index keeps the run deterministic.
    int rep = orbits[iOrb][0];
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
    os << "OSC: level " << prefix.size() << ", " << orbits.size()
       << " orbits, selected orbit of size " << orbits[iOrb].size()
       << ", |H|=" << H.size() << "\n";
#endif
    prefix.push_back(rep);
    prefix_col.push_back(osc_products_column(ctx, rep));
    MyVector<Tfield> v(n);
    for (int i = 0; i < n; i++) {
      v(i) = UniversalScalarConversion<Tfield, Tint>(ctx.VS.V(rep, i));
    }
    OscEchelon<Tfield> ech_next = ech;
    ech_next.insert(v);
    bool res;
    if (ech_next.get_rank() < n) {
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
      MicrosecondTime time_stab;
#endif
      Tgroup Hnext = H.Stabilizer_OnPoints(Tidx(rep));
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
      os << "|OSC: level " << (prefix.size() - 1) << ", stabilizer|="
         << time_stab << "\n";
#endif
      res = osc_select_rec(ctx, Hnext, prefix, prefix_col, ech_next,
                           out_prefix, os);
    } else {
      res = osc_select_rec(ctx, H, prefix, prefix_col, ech_next, out_prefix,
                           os);
    }
    prefix.pop_back();
    prefix_col.pop_back();
    if (!res) {
      return false;
    }
  }
  return true;
}

/*
  The canonical prefixes: one when no tie survives, one per branch
  otherwise, each with its vectors spanning Q^n. Nothing when the branch
  cap is exceeded.
 */
template <typename Tint, typename Tgroup>
std::optional<std::vector<std::vector<int>>>
osc_select_prefixes(PleskenSouvignierContext<Tint> const &ctx,
                    Tgroup const &GRP, std::ostream &os) {
  // The echelon reductions have minor-sized numerators and denominators
  // that Rational<int64_t> would overflow SILENTLY, so the rank tests
  // stay in mpq whatever ring the products run in; the tests are lazy
  // and few, so the cost does not matter.
  using Tfield = mpq_class;
  int n = ctx.n();
  std::vector<int> prefix;
  std::vector<MyMatrix<Tint>> prefix_col;
  OscEchelon<Tfield> ech(n);
  std::vector<std::vector<int>> out_prefix;
  bool res = osc_select_rec<Tint, Tgroup, Tfield>(ctx, GRP, prefix,
                                                  prefix_col, ech, out_prefix,
                                                  os);
  if (!res) {
    return {};
  }
  return out_prefix;
}

/*
  The signed, canonically reordered family from the selected prefix: the
  signs of the prefix by propagation along its product graph, then every
  pair sorted by its sign-normalized profile against the signed prefix,
  which pins it uniquely since the prefix spans Q^n. The columns of the
  returned n x nbPair matrix are the vectors, as the graph pipeline's
  CanonicallyReorder_SHV_AbsTrick returns them. Nothing when the prefix
  splits into several orthogonal components and a family vector
  straddles them, the one case where a component sign flip is not an
  integral isometry and the arbitrary flip would not be canonical.
 */
template <typename Tint>
std::optional<MyMatrix<Tint>>
osc_build_canonical_family(PleskenSouvignierContext<Tint> const &ctx,
                           std::vector<int> const &prefix,
                           std::vector<MyMatrix<Tint>> const &prefix_col,
                           [[maybe_unused]] std::ostream &os) {
  int m = ctx.VS.m;
  int n = ctx.n();
  int nbMat = ctx.ListMat.size();
  // The product graph of the prefix: edge when some form has a nonzero
  // product. Products of prefix members are rows of the columns.
  auto raw_tuple = [&](int k, int l) -> std::vector<Tint> {
    std::vector<Tint> tup(nbMat);
    for (int iMat = 0; iMat < nbMat; iMat++) {
      tup[iMat] = prefix_col[k](prefix[l], iMat);
    }
    return tup;
  };
  auto has_edge = [&](int k, int l) -> bool {
    for (int iMat = 0; iMat < nbMat; iMat++) {
      if (prefix_col[k](prefix[l], iMat) != 0) {
        return true;
      }
    }
    return false;
  };
  // Components and sign propagation in canonical order: the root of each
  // component takes +1 and each new member the sign making its first
  // non-zero product with its discovering neighbor positive.
  std::vector<int> eps(n, 0);
  std::vector<int> comp(n, -1);
  int n_comp = 0;
  for (int start = 0; start < n; start++) {
    if (comp[start] != -1) {
      continue;
    }
    comp[start] = n_comp;
    eps[start] = 1;
    std::vector<int> bfs{start};
    size_t cnd = 0;
    while (cnd < bfs.size()) {
      int k = bfs[cnd];
      for (int l = 0; l < n; l++) {
        if (comp[l] == -1 && has_edge(k, l)) {
          comp[l] = n_comp;
          std::vector<Tint> tup = raw_tuple(k, l);
          int sgn = osc_normalize_tuple(tup);
          eps[l] = eps[k] * sgn;
          bfs.push_back(l);
        }
      }
      cnd++;
    }
    n_comp++;
  }
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
  os << "OSC: prefix product graph has " << n_comp << " components\n";
#endif
  // The profiles: entry (k, iMat) of pair j is <v_j, eps_k v_{p_k}>.
  // With the prefix spanning Q^n no profile is zero, so each pair gets
  // a canonical sign and the profiles order the pairs strictly.
  std::vector<std::vector<Tint>> profiles(m);
  std::vector<int> signs(m);
  for (int j = 0; j < m; j++) {
    std::vector<Tint> prof(n * nbMat);
    int pos = 0;
    for (int k = 0; k < n; k++) {
      for (int iMat = 0; iMat < nbMat; iMat++) {
        prof[pos] = Tint(eps[k]) * prefix_col[k](j, iMat);
        pos++;
      }
    }
    int sgn = osc_normalize_tuple(prof);
#ifdef SANITY_CHECK_ORBIT_SPLIT_CANONICAL
    if (sgn == 0) {
      std::cerr << "OSC: a pair has zero profile against a spanning prefix\n";
      throw TerminalException{1};
    }
#endif
    signs[j] = sgn;
    profiles[j] = std::move(prof);
  }
  if (n_comp > 1) {
    // A component flip is canonical only when it is an isometry of the
    // configuration: every pair's profile must be supported in a single
    // component, which puts the pair in that component's span.
    for (int j = 0; j < m; j++) {
      int seen = -1;
      for (int k = 0; k < n; k++) {
        bool nonzero = false;
        for (int iMat = 0; iMat < nbMat; iMat++) {
          if (prefix_col[k](j, iMat) != 0) {
            nonzero = true;
          }
        }
        if (nonzero) {
          if (seen == -1) {
            seen = comp[k];
          } else if (seen != comp[k]) {
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
            os << "OSC: a family vector straddles two orthogonal "
               << "components, failure\n";
#endif
            return {};
          }
        }
      }
    }
  }
  std::vector<int> order(m);
  for (int j = 0; j < m; j++) {
    order[j] = j;
  }
  std::sort(order.begin(), order.end(), [&](int a, int b) -> bool {
    return profiles[a] < profiles[b];
  });
#ifdef SANITY_CHECK_ORBIT_SPLIT_CANONICAL
  for (int j = 1; j < m; j++) {
    if (profiles[order[j - 1]] == profiles[order[j]]) {
      std::cerr << "OSC: two pairs share a profile against a spanning "
                << "prefix, the profiles should be injective\n";
      throw TerminalException{1};
    }
  }
#endif
  MyMatrix<Tint> SHVcan(n, m);
  for (int jCan = 0; jCan < m; jCan++) {
    int j = order[jCan];
    for (int i = 0; i < n; i++) {
      SHVcan(i, jCan) = Tint(signs[j]) * ctx.VS.V(j, i);
    }
  }
  return SHVcan;
}

/*
  The canonically reordered signed families of the reduced
  configuration, one per branch of the tie exploration (deduplicated),
  or nothing when the branch cap is exceeded or every branch has
  straddled sign components. Templated on the ring so that the caller
  runs it over certified int64 whenever the bounds allow; the adjugate
  of ListMatRed[0] comes from the caller, who computed it over the big
  integers.
 */
template <typename Tint, typename Tgroup>
std::optional<std::vector<MyMatrix<Tint>>> OrbitSplitCanonicalFamily(
    std::vector<MyMatrix<Tint>> const &ListMatRed,
    MyMatrix<Tint> const &SHVhalf,
    std::optional<std::pair<MyMatrix<Tint>, Tint>> const &adjdet0,
    std::ostream &os) {
  using Telt = typename Tgroup::Telt;
  using Tidx = typename Telt::Tidx;
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  MicrosecondTime time;
#endif
  PleskenSouvignierAutomResult<Tint, Tgroup> aut =
      PleskenSouvignierAutomorphism<Tint, Tgroup>(ListMatRed, SHVhalf, os, -1,
                                                  adjdet0);
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  os << "|OSC: automorphism group|=" << time << "\n";
#endif
  PleskenSouvignierContext<Tint> ctx =
      PleskenSouvignierBuildContext(ListMatRed, SHVhalf, false, 0, os,
                                    adjdet0);
  int m = ctx.VS.m;
  // The generators as permutations of the antipodal pairs; -Id acts
  // trivially there, and the orbits and stabilizers on pairs are what
  // the selection needs.
  std::vector<Telt> ListPermGen;
  ListPermGen.reserve(aut.ListGen.size());
  for (auto &eGen : aut.ListGen) {
    std::vector<Tidx> eList(m);
    for (int j = 0; j < m; j++) {
      int im = ps_operate(ctx, j + 1, eGen);
      eList[j] = Tidx((im > 0 ? im : -im) - 1);
    }
    ListPermGen.push_back(Telt(std::move(eList)));
  }
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  os << "|OSC: generators to permutations|=" << time << "\n";
#endif
  // The randomized chain construction: with the pair-action order
  // certified by osc_pair_action_order it stops the moment the chain is
  // complete, and with 0 it verifies itself by the completion pass;
  // both are exact, and both beat the deterministic Schreier-Sims of
  // Group(gens, m) on a degree like the 98280 Leech pairs. The explicit
  // identity: braces would select the vector constructor and build a
  // corrupt one-entry permutation, and the parenthesized declaration is
  // a vexing parse.
  typename Tgroup::Tint pair_order =
      osc_pair_action_order<Tint, typename Tgroup::Tint>(ctx, aut.order);
  Telt id_elt = Telt(Tidx(m));
  Tgroup GRP(ListPermGen, id_elt, pair_order);
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
  os << "OSC: |Aut| on pairs = " << GRP.size() << "\n";
#endif
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  os << "|OSC: permutation group|=" << time << "\n";
#endif
  std::optional<std::vector<std::vector<int>>> opt_prefixes =
      osc_select_prefixes<Tint, Tgroup>(ctx, GRP, os);
  if (!opt_prefixes) {
    return {};
  }
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  os << "|OSC: prefix selection|=" << time << "\n";
#endif
  std::vector<MyMatrix<Tint>> ListSHVcan;
  for (auto &prefix : *opt_prefixes) {
    std::vector<MyMatrix<Tint>> prefix_col;
    prefix_col.reserve(prefix.size());
    for (auto &p : prefix) {
      prefix_col.push_back(osc_products_column(ctx, p));
    }
    std::optional<MyMatrix<Tint>> opt_shv =
        osc_build_canonical_family(ctx, prefix, prefix_col, os);
    // A branch with straddled sign components is dropped: the drop is a
    // property of the branch's isometry class, so the surviving set
    // stays canonical.
    if (opt_shv) {
      bool is_new = true;
      for (auto &eSHV : ListSHVcan) {
        if (eSHV == *opt_shv) {
          is_new = false;
        }
      }
      if (is_new) {
        ListSHVcan.push_back(*opt_shv);
      }
    }
  }
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  os << "|OSC: canonical families|=" << time << "\n";
#endif
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
  os << "OSC: " << opt_prefixes->size() << " branches, "
     << ListSHVcan.size() << " distinct canonical families\n";
#endif
  if (ListSHVcan.empty()) {
    return {};
  }
  return ListSHVcan;
}

/*
  The kernel on the reduced integral configuration: the basis BasisRed
  with BasisRed * ListMatRed[0] * BasisRed^T canonical, or nothing on an
  orbit tie or straddled sign components. The family stage runs over
  certified int64 whenever the bounds of ps_certify_int64 allow; the
  basis extraction from the ordered family runs over the big type, its
  Hermite elimination having no certified bound. A failure of the family
  stage is an algorithmic failure, identical in either ring, so it is
  not retried.
 */
// Lexicographic comparison of two symmetric matrices, row major: the
// rule by which the branch results are ordered.
template <typename Tint>
bool osc_gram_less(MyMatrix<Tint> const &A, MyMatrix<Tint> const &B) {
  int n = A.rows();
  for (int i = 0; i < n; i++) {
    for (int j = 0; j < n; j++) {
      if (A(i, j) != B(i, j)) {
        return A(i, j) < B(i, j);
      }
    }
  }
  return false;
}

template <typename Tint, typename Tgroup>
std::optional<MyMatrix<Tint>>
OrbitSplitCanonicalizeKernel(std::vector<MyMatrix<Tint>> const &ListMatRed,
                             MyMatrix<Tint> const &SHVhalf, std::ostream &os) {
  static_assert(!std::is_same_v<Tint, int64_t>,
                "the kernel dispatches to int64 itself");
  std::pair<MyMatrix<Tint>, Tint> adjdet0 =
      AdjugateDeterminant(ListMatRed[0]);
  std::vector<MyMatrix<Tint>> ListSHVcan;
  PSInt64Bounds<Tint> bounds = ps_int64_bounds(ListMatRed, SHVhalf, adjdet0);
  if (ps_certify_int64(bounds, os)) {
    std::vector<MyMatrix<int64_t>> ListMatRed64;
    for (auto &eMat : ListMatRed) {
      ListMatRed64.push_back(ps_matrix_to_int64(eMat));
    }
    MyMatrix<int64_t> SHVhalf64 = ps_matrix_to_int64(SHVhalf);
    std::optional<std::pair<MyMatrix<int64_t>, int64_t>> adjdet64 =
        std::make_pair(
            ps_matrix_to_int64(adjdet0.first),
            UniversalScalarConversion<int64_t, Tint>(adjdet0.second));
    std::optional<std::vector<MyMatrix<int64_t>>> opt64 =
        OrbitSplitCanonicalFamily<int64_t, Tgroup>(ListMatRed64, SHVhalf64,
                                                   adjdet64, os);
    if (!opt64) {
      return {};
    }
    for (auto &eSHV : *opt64) {
      ListSHVcan.push_back(ps_matrix_from_int64<Tint>(eSHV));
    }
  } else {
    std::optional<std::vector<MyMatrix<Tint>>> opt =
        OrbitSplitCanonicalFamily<Tint, Tgroup>(ListMatRed, SHVhalf, adjdet0,
                                                os);
    if (!opt) {
      return {};
    }
    ListSHVcan = std::move(*opt);
  }
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  MicrosecondTime time;
#endif
  // The branch whose canonical Gram matrix is lexicographically minimal:
  // the branches of two isometric inputs correspond with equal Gram
  // matrices, so the minimum is canonical.
  std::optional<MyMatrix<Tint>> best_basis;
  std::optional<MyMatrix<Tint>> best_gram;
  for (auto &eSHV : ListSHVcan) {
    MyMatrix<Tint> BasisRed = get_canonicalization_matrix(eSHV, os);
    MyMatrix<Tint> eGram = BasisRed * ListMatRed[0] * BasisRed.transpose();
    if (!best_gram || osc_gram_less(eGram, *best_gram)) {
      best_gram = std::move(eGram);
      best_basis = std::move(BasisRed);
    }
  }
#ifdef TIMINGS_ORBIT_SPLIT_CANONICAL
  os << "|OSC: canonicalization matrix|=" << time << "\n";
#endif
  return best_basis;
}

/*
  The canonical form of a positive definite Gram matrix by the orbit
  splitting over the Plesken-Souvignier automorphism group: the basis B
  with B * GramMat * B^T canonical, or nothing when the tie exploration
  exceeds the branch cap or every branch has straddled sign components.
  The failure is a property of the isometry class, not of the
  presentation, so the method stays comparable across inputs: it fails
  on both members of an isometric pair or on neither.

  The family stage runs over certified int64 whenever the preanalysis of
  ps_certify_int64 allows, which covers every LLL-reduced lattice of the
  practical range, and over the ring of the caller otherwise.
 */
template <typename T, typename Tint, typename Tgroup>
std::optional<MyMatrix<Tint>>
OrbitSplitCanonicalizeGram(MyMatrix<T> const &GramMat, std::ostream &os) {
  LLLreduction<T, Tint> rec = LLLreducedBasis<T, Tint>(GramMat, os);
  MyMatrix<Tint> const &Pmat = rec.Pmat;
  std::vector<MyMatrix<T>> ListMat{GramMat};
  std::vector<MyMatrix<Tint>> ListMatInt =
      PleskenSouvignierIntegralForms<T, Tint>(ListMat);
  std::vector<MyMatrix<Tint>> ListMatRed{Pmat * ListMatInt[0] *
                                         Pmat.transpose()};
  MyMatrix<Tint> SHVhalf =
      PleskenSouvignierZspanFamilyHalf<T, Tint>(rec.GramMatRed, true, os);
#ifdef DEBUG_ORBIT_SPLIT_CANONICAL
  os << "OSC: Z-spanning family of " << SHVhalf.rows() << " antipodal pairs\n";
#endif
  std::optional<MyMatrix<Tint>> opt =
      OrbitSplitCanonicalizeKernel<Tint, Tgroup>(ListMatRed, SHVhalf, os);
  if (!opt) {
    return {};
  }
  MyMatrix<Tint> B = (*opt) * Pmat;
#ifdef SANITY_CHECK_ORBIT_SPLIT_CANONICAL
  if (T_abs(DeterminantMat(B)) != 1) {
    std::cerr << "OSC: the canonicalization basis is not unimodular\n";
    throw TerminalException{1};
  }
#endif
  return B;
}

